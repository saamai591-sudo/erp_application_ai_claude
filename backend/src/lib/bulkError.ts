import { Response } from "express";

/**
 * فرمت استاندارد پاسخ خطا برای عملیات دسته‌ای (bulk) که می‌تواند به‌ازای هر آیتم مستقل شکست بخورد —
 * طبق تصمیم صریح کاربر (۱۴۰۵/۰۶/۱۸)، به‌جای join کردن پیام‌های هر آیتم در یک رشته‌ی بلند (که در
 * فرانت‌اند فقط به‌صورت متن خام و بی‌ساختار قابل نمایش بود)، یک خلاصه (error، همان کلید همیشگی) +
 * آرایه‌ی ساختاریافته‌ی جزئیات (details) برگردانده می‌شود تا فرانت‌اند بتواند details را به‌صورت فایل
 * اکسل قابل‌دانلود نمایش دهد — نگاه کنید به frontend/src/components/BulkErrorDialog.tsx. هر مسیر
 * دیگری که details نفرستد (همان res.status(400).json({error}) قدیمی)، دقیقاً همان رفتار قبلی را دارد؛
 * این یک فیلد اختیاریِ اضافه‌شونده است، نه شکستن قرارداد قبلی.
 *
 * الگوی استاندارد برای هر عملیات دسته‌ی جدید: به‌جای جمع‌کردن پیام‌های رشته‌ای در طول پردازش، یک
 * آرایه از آبجکت‌های ساده (کلید = ستون فارسی-پذیر) جمع کنید و در پایان با همین تابع بفرستید.
 */
export function sendBulkError(res: Response, status: number, summary: string, details: Record<string, unknown>[]) {
  res.status(status).json({ error: summary, details });
}
