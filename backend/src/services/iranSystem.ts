const HT = new Map<string, number>(TABLE);

const SEPARATED_BEFORE = ["ء", "ر", "ز", "ژ", "آ", "أ", "ؤ", "إ", "ا", "د", "ذ"];
const isEnglishCharOrNumber = (c: string) => /[a-zA-Z0-9]/.test(c);

function findKey(item: string, before: string, after: string): number {
  let key = item;
  if (before === " " || SEPARATED_BEFORE.includes(before) || isEnglishCharOrNumber(before)) key = " " + key;
  if (after === " " || isEnglishCharOrNumber(after)) key += " ";
  if (item + after === "لا") key = item + after;
  const r = HT.get(key);
  return r !== undefined ? r : (HT.get(item) as number);
}

/** مقایسه‌ی ترتیبی رشته‌ها (معادل CompareTo در کد اصلی روی نمایش دهدهی بایت) */
const cmp = (a: string, b: string) => (a < b ? -1 : a > b ? 1 : 0);

export function unicodeToIranSystem(input: string): Buffer {
  const str = input.replace(/[\u200f\u200e]/g, "");
  const list: number[] = [];
  for (let i = 0; i < str.length; i++) {
    const ch = str[i];
    const before = i === 0 ? " " : str[i - 1];
    const after = i === str.length - 1 ? " " : str[i + 1];
    const key = findKey(ch, before, after);
    if (ch !== " " && before + ch !== "لا") list.push(key);
    else if (ch === " ") list.push(0x20);
  }
  const out: number[] = [];
  const run: number[] = [];
  let flag = true;
  const flush = () => {
    if (!flag) {
      for (let i = run.length - 1; i >= 0; i--) out.push(run[i]);
      run.length = 0;
      flag = true;
    }
  };
  for (let n = list.length - 1; n >= 0; n--) {
    const s = String(list[n]);
    const isRun =
      (cmp(s, "47") >= 0 && cmp(s, "57") <= 0) ||
      (cmp(s, "65") >= 0 && cmp(s, "90") <= 0) ||
      (cmp(s, "97") >= 0 && cmp(s, "122") <= 0) ||
      (cmp(s, "128") >= 0 && cmp(s, "137") <= 0) ||
      (run.length > 0 && s === "44");
    if (isRun) {
      run.push(list[n]);
      flag = false;
    } else if (s === "10") {
      flush();
      out.push(10);
      n--;
    } else {
      flush();
      out.push(list[n]);
    }
  }
  for (let i = run.length - 1; i >= 0; i--) out.push(run[i]);
  return Buffer.from(out);
}

/** آماده‌سازی متن برای تبدیل: ي/ك عربی → ی/ک فارسی، ارقام فارسی/عربی → لاتین، نیم‌فاصله → فاصله، اعراب حذف، نویسه‌ی بدون نگاشت → فاصله */
export function sanitizeForIranSystem(input: string): string {
  const t = input
    .replace(/ي/g, "ی")
    .replace(/ك/g, "ک")
    .replace(/[‌‍]/g, " ")
    .replace(/[ً-ٟ]/g, "")
    .replace(/[۰-۹]/g, (c) => String(c.charCodeAt(0) - 0x06f0))
    .replace(/[٠-٩]/g, (c) => String(c.charCodeAt(0) - 0x0660));
  let out = "";
  for (const ch of t) out += HT.has(ch) || HT.has(" " + ch) || HT.has(ch + " ") || HT.has(" " + ch + " ") ? ch : " ";
  return out;
}
