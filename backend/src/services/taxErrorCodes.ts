export interface ExplainedTaxCode {
  code: string;
  severity: "error" | "warning";
  field: string | null;
  fieldTitle: string | null;
  message: string;
}

/** کد خطا/هشدار لایه‌ی محتوا را به‌صورت «خطا/هشدار — عنوان فیلد: توضیح» برمی‌گرداند؛ پیام اصلی سامانه (اگر داده شود) در انتها می‌آید */
export function explainTaxCode(code: string, serverMessage?: string): ExplainedTaxCode {
  const c = String(code ?? "").trim();
  if (c === "00000") return { code: c, severity: "warning", field: null, fieldTitle: null, message: "تعداد پیام‌های خطا/هشدار بیش از ۵۰ مورد است و فقط ۵۰ مورد اول نمایش داده می‌شود" };
  const m = c.match(/^([01])(\d)(\d{3})(\d{2})?$/);
  if (!m) return { code: c, severity: c.startsWith("1") ? "warning" : "error", field: null, fieldTitle: null, message: serverMessage || `کد ناشناخته (${c})` };
  const [, st, kind, fieldNo, detail] = m;
  const field = FIELD_NO_TO_KEY[fieldNo] ?? null;
  const fieldTitle = field ? TAX_FIELD_TITLES[field] ?? field : null;
  let what = KIND_FA[kind] ?? `نوع اعتبارسنجی ${kind}`;
  if (kind === "1" && detail && JSON_DETAIL_FA[detail]) what = JSON_DETAIL_FA[detail];
  const head = `${STATUS_FA[st]}${fieldTitle ? ` — ${fieldTitle}` : fieldNo !== "000" ? ` — فیلد شماره ${fieldNo}` : ""}: ${what}`;
  return { code: c, severity: st === "1" ? "warning" : "error", field, fieldTitle, message: serverMessage ? `${head} (پیام سامانه: ${serverMessage})` : head };
}

