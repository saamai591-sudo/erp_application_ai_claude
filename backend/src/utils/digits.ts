const FA_DIGIT_MAP: Record<string, string> = { "۰": "0", "۱": "1", "۲": "2", "۳": "3", "۴": "4", "۵": "5", "۶": "6", "۷": "7", "۸": "8", "۹": "9" };
const AR_DIGIT_MAP: Record<string, string> = { "٠": "0", "١": "1", "٢": "2", "٣": "3", "٤": "4", "٥": "5", "٦": "6", "٧": "7", "٨": "8", "٩": "9" };

/**
 * ارقام فارسی یا عربی (که کاربر معمولاً با صفحه‌کلید فارسی/در اکسل وارد می‌کند) را به ارقام
 * انگلیسی تبدیل می‌کند — برای مقایسه‌ی کدها (که ممکن است در دیتابیس با هر یک از این سه رسم‌الخط
 * ذخیره شده باشند) و تبدیل به عدد (Number)، مستقل از این‌که کاربر کد را با کدام صفحه‌کلید تایپ کرده.
 */
export function toEnglishDigits(s: string): string {
  return s.replace(/[۰-۹٠-٩]/g, (d) => FA_DIGIT_MAP[d] ?? AR_DIGIT_MAP[d] ?? d);
}
