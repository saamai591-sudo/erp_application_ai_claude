// توکن احراز هویت عمداً هرگز در localStorage/sessionStorage/cookie ذخیره نمی‌شود — فقط در یک متغیر
// حافظه‌ای (module-level) سمت این تب نگه داشته می‌شود. این دقیقاً همان چیزی است که دو ویژگی خواسته‌شده
// را هم‌زمان تضمین می‌کند:
//   ۱) ایزوله بودن کامل بین تب‌ها: هر تب مرورگر یک نمونه‌ی کاملاً جدا از موتور جاوااسکریپت (و در نتیجه
//      این ماژول) دارد؛ چیزی که در حافظه‌ی یک تب نوشته می‌شود، هیچ راهی برای دیده‌شدن در تب دیگر ندارد
//      (برخلاف localStorage که بین همه‌ی تب‌های یک origin مشترک است).
//   ۲) پایان یافتن نشست با رفرش: با رفرش صفحه، کل حافظه‌ی جاوااسکریپت آن تب از صفر ساخته می‌شود، پس این
//      متغیر دوباره null می‌شود — یعنی کاربر باید دوباره وارد شود، بدون نیاز به هیچ منطق اضافه‌ای.
let currentToken: string | null = null;

export function getAuthToken(): string | null {
  return currentToken;
}

export function setAuthToken(token: string | null): void {
  currentToken = token;
}
