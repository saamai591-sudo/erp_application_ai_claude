       dd2.PersianCalendarSeason
INTO #seasons
FROM CFG.DimDate AS dd2
WHERE dd2.Date
BETWEEN @StartDate AND @FinishDate;

SET @Season =
(
    SELECT TOP (1) PersianCalendarSeason FROM #seasons AS s
);
	
