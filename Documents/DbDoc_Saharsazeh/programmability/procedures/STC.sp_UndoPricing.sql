
---------------------------------------------------------
CREATE   PROC [STC].sp_UndoPricing
(
    @PricingDate DATE,
    @selItems NVARCHAR(MAX),
    @FinancialPeriodID INT
)

--WITH ENCRYPTION
WITH RECOMPILE
AS


DECLARE @Columns NVARCHAR(MAX),
        @Columns2 NVARCHAR(MAX),
        @Query NVARCHAR(MAX),
        @ConditionalInnerJoin NVARCHAR(MAX),
        @UserID INT,
		@Maxdi int,
		@MaxPosition int,
		@SelectColumns NVARCHAR(MAX)



BEGIN TRY

    SET @UserID = CFG.GetuserID();
	
	if OBJECT_ID('tempdb..##UndoSelected') is not null drop table ##UndoSelected
	if OBJECT_ID('tempdb..##UndoPricingItemTemp') is not null drop table ##UndoPricingItemTemp

    EXEC CFG.TableFromIStuffTraceString @selItems, '##UndoSelected', 1;

    SELECT @Columns = STUFF(
    (
        SELECT DISTINCT
               ',' + QUOTENAME(al.TraceID)
        FROM STF.Trace al
        WHERE PricingBase = 1
        FOR XML PATH(''), TYPE
    ).value('.', 'NVARCHAR(MAX)'),1   ,1   ,    '');

    IF (@Columns IS NULL)
        SET @Columns = N'[-1]';



    SELECT @SelectColumns = STUFF(
    (
        SELECT DISTINCT
               ',' + QUOTENAME(al.TraceID)
        FROM STF.Trace al
        WHERE PricingBase = 1
        FOR XML PATH(''), TYPE
    ).value('.', 'NVARCHAR(MAX)'),1   ,0  ,'');


    IF (@SelectColumns IS NULL)
        SET @SelectColumns = N'';

    SELECT @ConditionalInnerJoin
        = N'inner join ##UndoSelected Selected on Selected.stuffid = p.stuffid AND Selected.StockID = p.StockID '
          + STUFF(
    (
        SELECT DISTINCT
               ' AND (Selected.' + QUOTENAME(TraceID) + ' is null or p.' + QUOTENAME(TraceID) + '= Selected.'
               + QUOTENAME(TraceID) + ')'
        FROM STF.Trace
        WHERE PricingBase = 1
        FOR XML PATH(''), TYPE
    ).value('.', 'NVARCHAR(MAX)'),1   ,1   ,'');


    IF (@ConditionalInnerJoin IS NULL)
        SET @ConditionalInnerJoin = N'inner join ##UndoSelected Selected on Selected.stuffid = p.stuffid AND Selected.StockID = p.StockID ';



    BEGIN TRAN;

    --**حذف تعديلات سيستمي
    BEGIN

        DELETE i
        FROM STC.RevisionCost h
            JOIN STC.RevisionCostItem i
                ON i.RevisionCostID = h.RevisionCostID
            JOIN STC.OutgoingItem oi
                ON oi.OutgoingItemID = i.OutgoingItemID
            JOIN STC.Outgoing o
                ON o.OutgoingID = oi.OutgoingID
            JOIN ##UndoSelected Selected
                ON Selected.stuffid = oi.StuffID
                   AND Selected.stockid = o.StockID
        WHERE h.AutoGenerated = 1
              AND h.FinancialPeriodID = @FinancialPeriodID
              AND h.Date >= @PricingDate;


        DELETE i
        FROM STC.RevisionCost h
            JOIN STC.RevisionCostItem i
                ON i.RevisionCostID = h.RevisionCostID
            JOIN STC.StockReceiptItem oi
                ON oi.StockReceiptItemID = i.StockReceiptItemID
            JOIN STC.StockReceipt o
                ON o.StockReceiptID = oi.StockReceiptID
            JOIN ##UndoSelected Selected
                ON Selected.stuffid = oi.StuffID
                   AND Selected.stockid = o.StockID
        WHERE h.AutoGenerated = 1
			  AND ISNULL([AutoGenerateType],0) <> 2
              AND h.FinancialPeriodID = @FinancialPeriodID
              AND h.Date >= @PricingDate;


        DELETE i
        FROM STC.RevisionCost h
            JOIN STC.RevisionCostItem i
                ON i.RevisionCostID = h.RevisionCostID
            JOIN STC.ReturnStockReceiptItem oi
                ON oi.ReturnStockReceiptItemID = i.ReturnStockReceiptItemID
            JOIN STC.ReturnStockReceipt o
                ON o.ReturnStockReceiptID = oi.ReturnStockReceiptID
            JOIN ##UndoSelected Selected
                ON Selected.stuffid = oi.StuffID
                   AND Selected.stockid = o.StockID
        WHERE h.AutoGenerated = 1
              AND h.FinancialPeriodID = @FinancialPeriodID
              AND h.Date >= @PricingDate;


        DELETE i
        FROM STC.RevisionCost h
            JOIN STC.RevisionCostItem i
                ON i.RevisionCostID = h.RevisionCostID
            JOIN STC.ReturnedOutgoingItem oi
                ON oi.ReturnedOutgoingItemID = i.ReturnedOutgoingItemID
            JOIN STC.ReturnedOutgoing o
                ON o.ReturnedOutgoingID = oi.ReturnedOutgoingID
            JOIN ##UndoSelected Selected
                ON Selected.stuffid = oi.StuffID
                   AND Selected.stockid = o.StockID
        WHERE h.AutoGenerated = 1
              AND h.FinancialPeriodID = @FinancialPeriodID
              AND h.Date >= @PricingDate;


        DELETE FROM STC.RevisionCost
        WHERE RevisionCostID NOT IN
              (
                  SELECT RevisionCostID FROM STC.RevisionCostItem GROUP BY RevisionCostID
              );

    END;


    IF OBJECT_ID('tempdb..#CheckTemp') IS NOT NULL
        DROP TABLE #CheckTemp;

    CREATE TABLE #CheckTemp
    (
        HeaderID INT,
        ItemID INT
    );

    --حذف محاسبات
    ---رسید انتقالی

    SET @Query
        = N'insert into #CheckTemp
				select StockReceiptID,StockReceiptItemID
				from
				(
				select  h.StockReceiptID,i.StockReceiptItemID,TraceID,i.stuffid,h.stockid,
						Case 
							When t.DLID IS NOT NULL THEN cast (t.DLID as nvarchar(max)) 
							When t.TraceItemID IS NOT NULL THEN cast (t.TraceItemID as nvarchar(max)) 
							else Value 
						end Value
				from stc.StockReceipt h
                JOIN [STC].[StockDocumentTypeBaseEntity] sdtb
                    ON h.StockDocumentTypeBaseEntityID = sdtb.StockDocumentTypeBaseEntityID
				join stc.StockDocumentType sdt on sdt.StockDocumentTypeID = sdtb.StockDocumentTypeID
				inner join stc.StockReceiptItem i  on h.StockReceiptID = i.StockReceiptID
				left join stc.StockReceiptItemTrace t on i.StockReceiptItemID=t.StockReceiptItemID
				where sdt.DocumentType = 5
				and h.Date >= @pDate
				and h.FinancialPeriodID = @pFinancialPeriodID
				)x pivot
					( max(Value)
							for TraceID in ( ' + @Columns + N')
						) p ' + @ConditionalInnerJoin;


    EXECUTE sp_executesql @Query,
                          N'@pFinancialPeriodID INT,@pDate Date',
                          @pFinancialPeriodID = @FinancialPeriodID,
                          @pDate = @PricingDate;

    UPDATE s
    SET Fee = 0,
        Price = 0
    FROM STC.StockReceiptItem s
        JOIN #CheckTemp c
            ON c.ItemID = s.StockReceiptItemID;

    UPDATE sr
    SET TotalInvoicePrice = ISNULL(
                            (
                                SELECT SUM(Price)
                                FROM STC.StockReceiptItem ari
                                WHERE ari.StockReceiptID = sr.StockReceiptID
                            ),
                            0
                                  ),
        TotalNetPrice = ISNULL(
                        (
                            SELECT SUM(NetPrice)
                            FROM STC.StockReceiptItem ari
                            WHERE ari.StockReceiptID = sr.StockReceiptID
                        ),
                        0
                              )
    FROM STC.StockReceipt sr
        JOIN #CheckTemp c
            ON c.HeaderID = sr.StockReceiptID;


	select @Maxdi = max(id),@MaxPosition = max(position) from ##UndoSelected
   SET @Query
        = N'
	insert into ##UndoSelected
	select @Maxdi + 1 , @MaxPosition + 1,stuffid,stockid'+ @SelectColumns+'
	from #CheckTemp a
	inner join stc.StockReceiptItem i  on a.ItemID = i.StockReceiptItemID 
	inner join stc.StockReceipt h on h.StockReceiptID = i.StockReceiptID
	left join 
	(
	select  StockReceiptItemID,TraceID,
			Case 
				When t.DLID IS NOT NULL THEN cast (t.DLID as nvarchar(max)) 
				When t.TraceItemID IS NOT NULL THEN cast (t.TraceItemID as nvarchar(max)) 
				else Value 
			end Value
	from stc.StockReceiptItemTrace t 
	)x pivot
	( max(Value)
			for TraceID in ( ' + @Columns + N')
	) p ON P.StockReceiptItemID = I.StockReceiptItemID
	group by stockid,stuffid,'+ @Columns

    EXECUTE sp_executesql @Query,
                          N'@Maxdi int,@MaxPosition int',
                          @Maxdi = @Maxdi,
                          @MaxPosition = @MaxPosition;

    DELETE FROM #CheckTemp;

    --- رسید تبدیل 


    SET @Query
        = N'insert into #CheckTemp
				select StockReceiptID,StockReceiptItemID
				from
				(
				select  i.StockReceiptID,i.StockReceiptItemID,TraceID,oi.stuffid,h.stockid,
						Case 
							When t.DLID IS NOT NULL THEN cast (t.DLID as nvarchar(max)) 
							When t.TraceItemID IS NOT NULL THEN cast (t.TraceItemID as nvarchar(max)) 
							else Value 
						end Value
				from stc.outgoing h
                JOIN [STC].[StockDocumentTypeBaseEntity] sdtb 
                    ON h.StockDocumentTypeBaseEntityID = sdtb.StockDocumentTypeBaseEntityID
				join stc.StockDocumentType sdt on sdt.StockDocumentTypeID = sdtb.StockDocumentTypeID
				join stc.outgoingitem oi on h.outgoingid = oi.outgoingid
				join stc.ConvertSpecification cs on cs.outgoingitemid = oi.outgoingitemid
				join stc.StockReceiptItem i  on cs.ConvertSpecificationid = i.ConvertSpecificationid
				left join stc.outgoingitemTrace t on oi.outgoingitemid=t.outgoingitemid
				where sdt.DocumentType = 9
				and h.Date >= @pDate
				and h.FinancialPeriodID = @pFinancialPeriodID
				)x pivot
					( max(Value)
							for TraceID in ( ' + @Columns + N')
						) p ' + @ConditionalInnerJoin;

				
    EXECUTE sp_executesql @Query,
                          N'@pFinancialPeriodID INT,@pDate Date',
                          @pFinancialPeriodID = @FinancialPeriodID,
                          @pDate = @PricingDate;



    UPDATE s
    SET Fee = 0,
        Price = 0
    FROM STC.StockReceiptItem s
        JOIN #CheckTemp c
            ON c.ItemID = s.StockReceiptItemID;

    UPDATE sr
    SET TotalInvoicePrice = ISNULL(
                            (
                                SELECT SUM(Price)
                                FROM STC.StockReceiptItem ari
                                WHERE ari.StockReceiptID = sr.StockReceiptID
                            ),
                            0
                                  ),
        TotalNetPrice = ISNULL(
                        (
                            SELECT SUM(NetPrice)
                            FROM STC.StockReceiptItem ari
                            WHERE ari.StockReceiptID = sr.StockReceiptID
                        ),
                        0
                              )
    FROM STC.StockReceipt sr
        JOIN #CheckTemp c
            ON c.HeaderID = sr.StockReceiptID;

	select @Maxdi = max(id),@MaxPosition = max(position) from ##UndoSelected
   SET @Query
        = N'
	insert into ##UndoSelected
	select @Maxdi + 1 , @MaxPosition + 1,stuffid,stockid' + @SelectColumns+'
	from #CheckTemp a
	inner join stc.StockReceiptItem i  on a.ItemID = i.StockReceiptItemID 
	inner join stc.StockReceipt h on h.StockReceiptID = i.StockReceiptID
	left join 
	(
	select  StockReceiptItemID,TraceID,
			Case 
				When t.DLID IS NOT NULL THEN cast (t.DLID as nvarchar(max)) 
				When t.TraceItemID IS NOT NULL THEN cast (t.TraceItemID as nvarchar(max)) 
				else Value 
			end Value
	from stc.StockReceiptItemTrace t
	)x pivot
	( max(Value)
			for TraceID in ( ' + @Columns + N')
	) p ON P.StockReceiptItemID = I.StockReceiptItemID
	group by stockid,stuffid,'+ @Columns

    EXECUTE sp_executesql @Query,
                          N'@Maxdi int,@MaxPosition int',
                          @Maxdi = @Maxdi,
                          @MaxPosition = @MaxPosition;

    DELETE FROM #CheckTemp;



    --- رسید ترکیب 

    SET @Query
        = N'insert into #CheckTemp
				select StockReceiptID,StockReceiptItemID
				from
				(
				select  i.StockReceiptID,i.StockReceiptItemID,TraceID,oi.stuffid,h.stockid,
						Case 
							When t.DLID IS NOT NULL THEN cast (t.DLID as nvarchar(max)) 
							When t.TraceItemID IS NOT NULL THEN cast (t.TraceItemID as nvarchar(max)) 
							else Value 
						end Value
				from stc.outgoing h
                JOIN [STC].[StockDocumentTypeBaseEntity] sdtb 
                    ON h.StockDocumentTypeBaseEntityID = sdtb.StockDocumentTypeBaseEntityID
				join stc.StockDocumentType sdt on sdt.StockDocumentTypeID = sdtb.StockDocumentTypeID
				join stc.outgoingitem oi on h.outgoingid = oi.outgoingid
				join stc.StuffComposition sc on sc.StuffCompositionid = oi.StuffCompositionid
				join stc.StockReceiptItem i  on sc.StockReceiptItemid = i.StockReceiptItemid
				left join stc.outgoingitemTrace t on oi.outgoingitemid=t.outgoingitemid
				where sdt.DocumentType = 12
				and h.Date >= @pDate
				and h.FinancialPeriodID = @pFinancialPeriodID
				)x pivot
					( max(Value)
							for TraceID in ( ' + @Columns + N')
						) p ' + @ConditionalInnerJoin;


    EXECUTE sp_executesql @Query,
                           N'@pFinancialPeriodID INT,@pDate Date',
                          @pFinancialPeriodID = @FinancialPeriodID,
                          @pDate = @PricingDate;

    UPDATE s
    SET Fee = 0,
        Price = 0
    FROM STC.StockReceiptItem s
        JOIN #CheckTemp c
            ON c.ItemID = s.StockReceiptItemID;

    UPDATE sr
    SET TotalInvoicePrice = ISNULL(
                            (
                                SELECT SUM(Price)
                                FROM STC.StockReceiptItem ari
                                WHERE ari.StockReceiptID = sr.StockReceiptID
                            ),
                            0
                                  ),
        TotalNetPrice = ISNULL(
                        (
                            SELECT SUM(NetPrice)
                            FROM STC.StockReceiptItem ari
                            WHERE ari.StockReceiptID = sr.StockReceiptID
                        ),
                        0
                              )
    FROM STC.StockReceipt sr
        JOIN #CheckTemp c
            ON c.HeaderID = sr.StockReceiptID;


	select @Maxdi = max(id),@MaxPosition = max(position) from ##UndoSelected
   SET @Query
        = N'
	insert into ##UndoSelected
	select @Maxdi + 1 , @MaxPosition + 1,stuffid,stockid' + @SelectColumns+'
	from #CheckTemp a
	inner join stc.StockReceiptItem i  on a.ItemID = i.StockReceiptItemID 
	inner join stc.StockReceipt h on h.StockReceiptID = i.StockReceiptID
	left join 
	(
	select  StockReceiptItemID,TraceID,
			Case 
				When t.DLID IS NOT NULL THEN cast (t.DLID as nvarchar(max)) 
				When t.TraceItemID IS NOT NULL THEN cast (t.TraceItemID as nvarchar(max)) 
				else Value 
			end Value
	from stc.StockReceiptItemTrace t
	)x pivot
	( max(Value)
			for TraceID in ( ' + @Columns + N')
	) p ON P.StockReceiptItemID = I.StockReceiptItemID
	group by stockid,stuffid,'+ @Columns

    EXECUTE sp_executesql @Query,
                          N'@Maxdi int,@MaxPosition int',
                          @Maxdi = @Maxdi,
                          @MaxPosition = @MaxPosition;

    DELETE FROM #CheckTemp;


    --- رسید پیمانکاری 

    SET @Query
        = N'insert into #CheckTemp
				select StockReceiptID,StockReceiptItemID
				from
				(
				select  i.StockReceiptID,i.StockReceiptItemID,TraceID,oi.stuffid,h.stockid,
						Case 
							When t.DLID IS NOT NULL THEN cast (t.DLID as nvarchar(max)) 
							When t.TraceItemID IS NOT NULL THEN cast (t.TraceItemID as nvarchar(max)) 
							else Value 
						end Value
				from stc.outgoing h
                JOIN [STC].[StockDocumentTypeBaseEntity] sdtb 
                    ON h.StockDocumentTypeBaseEntityID = sdtb.StockDocumentTypeBaseEntityID
				join stc.StockDocumentType sdt on sdt.StockDocumentTypeID = sdtb.StockDocumentTypeID
				join stc.outgoingitem oi on h.outgoingid = oi.outgoingid
				join stc.StockReceiptChargingService sc on sc.OutgoingItemID = oi.OutgoingItemID
				join stc.StockReceiptItem i  on sc.StockReceiptItemid = i.StockReceiptItemid
				left join stc.outgoingitemTrace t on oi.outgoingitemid=t.outgoingitemid
				where sdt.DocumentType = 14
				and h.Date >= @pDate
				and h.FinancialPeriodID = @pFinancialPeriodID
				)x pivot
					( max(Value)
							for TraceID in ( ' + @Columns + N')
						) p ' + @ConditionalInnerJoin;


    EXECUTE sp_executesql @Query,
                          N'@pFinancialPeriodID INT,@pDate Date',
                          @pFinancialPeriodID = @FinancialPeriodID,
                          @pDate = @PricingDate;

    UPDATE s
    SET Fee = 0,
        Price = 0
    FROM STC.StockReceiptItem s
        JOIN #CheckTemp c
            ON c.ItemID = s.StockReceiptItemID;

    UPDATE sr
    SET TotalInvoicePrice = ISNULL(
                            (
                                SELECT SUM(Price)
                                FROM STC.StockReceiptItem ari
                                WHERE ari.StockReceiptID = sr.StockReceiptID
                            ),
                            0
                                  ),
        TotalNetPrice = ISNULL(
                        (
                            SELECT SUM(NetPrice)
                            FROM STC.StockReceiptItem ari
                            WHERE ari.StockReceiptID = sr.StockReceiptID
                        ),
                        0
                              )
    FROM STC.StockReceipt sr
        JOIN #CheckTemp c
            ON c.HeaderID = sr.StockReceiptID;


	select @Maxdi = max(id),@MaxPosition = max(position) from ##UndoSelected
   SET @Query
        = N'
	insert into ##UndoSelected
	select @Maxdi + 1 , @MaxPosition + 1,stuffid,stockid' + @SelectColumns+'
	from #CheckTemp a
	inner join stc.StockReceiptItem i  on a.ItemID = i.StockReceiptItemID 
	inner join stc.StockReceipt h on h.StockReceiptID = i.StockReceiptID
	left join 
	(
	select  StockReceiptItemID,TraceID,
			Case 
				When t.DLID IS NOT NULL THEN cast (t.DLID as nvarchar(max)) 
				When t.TraceItemID IS NOT NULL THEN cast (t.TraceItemID as nvarchar(max)) 
				else Value 
			end Value
	from stc.StockReceiptItemTrace t
	)x pivot
	( max(Value)
			for TraceID in ( ' + @Columns + N')
	) p ON P.StockReceiptItemID = I.StockReceiptItemID
	group by stockid,stuffid,'+ @Columns

    EXECUTE sp_executesql @Query,
                          N'@Maxdi int,@MaxPosition int',
                          @Maxdi = @Maxdi,
                          @MaxPosition = @MaxPosition;

    DELETE FROM #CheckTemp;

    ---  برگشت حواله هاي دارای فی اتوماتیک

    SET @Query
        = N'insert into #CheckTemp
				select ReturnedOutgoingID,ReturnedOutgoingItemID
				from
				(
				select h.ReturnedOutgoingID,h.prevoucherid,i.ReturnedOutgoingItemID,TraceID,i.stuffid,h.stockid,
				Case 
					When t.DLID IS NOT NULL THEN cast (t.DLID as nvarchar(max)) 
					When t.TraceItemID IS NOT NULL THEN cast (t.TraceItemID as nvarchar(max)) 
					else Value 
				end Value

				from stc.ReturnedOutgoing h
				inner join stc.ReturnedOutgoingItem i  on h.ReturnedOutgoingID = i.ReturnedOutgoingID
				left join  stc.ReturnedOutgoingItemTrace t on i.ReturnedOutgoingItemID=t.ReturnedOutgoingItemID
				where (i.OutgoingItemID is not null or [AutoPriced] = 1)
				and h.Date >= @pDate
				and h.FinancialPeriodID = @pFinancialPeriodID
				)x pivot
					( max(Value)
							for TraceID in ( ' + @Columns + N')
						) p  ' + @ConditionalInnerJoin;

    EXECUTE sp_executesql @Query,
                          N'@pFinancialPeriodID INT,@pDate Date',
                          @pFinancialPeriodID = @FinancialPeriodID,
                          @pDate = @PricingDate;

    UPDATE i
    SET Fee = 0,
        Price = 0,
        [AutoPriced] = null
    FROM STC.ReturnedOutgoingItem i
        JOIN #CheckTemp c
            ON c.ItemID = i.ReturnedOutgoingItemID;


    UPDATE sr
    SET TotalPrice =
        (
            SELECT SUM(Price)
            FROM STC.ReturnedOutgoingItem ari
            WHERE ari.ReturnedOutgoingID = sr.ReturnedOutgoingID
        )
    FROM STC.ReturnedOutgoing sr
        JOIN #CheckTemp c
            ON c.HeaderID = sr.ReturnedOutgoingID;


    DELETE FROM #CheckTemp;

    -- برگشت رسيد

    SET @Query
        = N'insert into #CheckTemp
				select ReturnStockReceiptID,ReturnStockReceiptItemID
				from
				(
				select  i.ReturnStockReceiptItemID,TraceID,i.stuffid,h.prevoucherid,h.ReturnStockReceiptID,h.stockid,
						Case When t.DLID IS NOT NULL THEN cast (t.DLID as nvarchar(max)) 
							 When t.TraceItemID IS NOT NULL THEN cast (t.TraceItemID as nvarchar(max)) 
						else Value end Value
				from stc.ReturnStockReceipt h
				inner join stc.ReturnStockReceiptItem i  on h.ReturnStockReceiptID = i.ReturnStockReceiptID
				left join 
				 stc.ReturnStockReceiptItemTrace t on i.ReturnStockReceiptItemID=t.ReturnStockReceiptItemID
				where h.Date >= @pDate
				and h.FinancialPeriodID = @pFinancialPeriodID
				)x pivot
					( max(Value)
							for TraceID in ( ' + @Columns + N')
						) p ' + @ConditionalInnerJoin;


    EXECUTE sp_executesql @Query,
                          N'@pFinancialPeriodID INT,@pDate Date',
                          @pFinancialPeriodID = @FinancialPeriodID,
                          @pDate = @PricingDate;


    UPDATE s
    SET Fee = 0,
        Price = 0,
        Version = Version + 1,
        LastEditor = @UserID,
        LastEditionDate = GETDATE()
    FROM STC.ReturnStockReceiptItem s
        JOIN #CheckTemp c
            ON c.ItemID = s.ReturnStockReceiptItemID;
    WITH temp
    AS (SELECT i.ReturnStockReceiptID,
               SUM(Price) Price
        FROM STC.ReturnStockReceiptItem i
            JOIN STC.ReturnStockReceipt h
                ON h.ReturnStockReceiptID = i.ReturnStockReceiptID
        WHERE h.FinancialPeriodID = @FinancialPeriodID
        GROUP BY i.ReturnStockReceiptID)
    UPDATE v
    SET TotalInvoicePrice = vi.Price
    FROM STC.ReturnStockReceipt v
        JOIN temp vi
            ON v.ReturnStockReceiptID = vi.ReturnStockReceiptID;

    DELETE FROM #CheckTemp;

    -- حواله

    SET @Query
        = N'insert into #CheckTemp
				select OutgoingID,OutgoingItemID
				from
				(
				select  i.OutgoingItemID,TraceID,i.stuffid,h.prevoucherid,h.OutgoingID,h.stockid,
						Case When t.DLID IS NOT NULL THEN cast (t.DLID as nvarchar(max)) 
							When t.TraceItemID IS NOT NULL THEN cast (t.TraceItemID as nvarchar(max)) 
						else Value end Value
				from stc.Outgoing h
				inner join stc.OutgoingItem i  on h.OutgoingID = i.OutgoingID
				left join  stc.OutgoingItemTrace t on i.OutgoingItemID=t.OutgoingItemID
				where h.Date >= @pDate
				and h.FinancialPeriodID = @pFinancialPeriodID
				)x pivot
					( max(Value)
							for TraceID in ( ' + @Columns + N')
						) p ' + @ConditionalInnerJoin;

    EXECUTE sp_executesql @Query,
                          N'@pFinancialPeriodID INT,@pDate Date',
                          @pFinancialPeriodID = @FinancialPeriodID,
                          @pDate = @PricingDate;

    UPDATE oi
    SET Fee = 0,
        Price = 0
    FROM STC.OutgoingItem oi
        JOIN #CheckTemp c
            ON c.ItemID = oi.OutgoingItemID;


    UPDATE o
    SET TotalPrice =
        (
            SELECT SUM(Price)
            FROM STC.OutgoingItem ari
            WHERE ari.OutgoingID = o.OutgoingID
        )
    FROM STC.Outgoing o
        JOIN #CheckTemp c
            ON c.HeaderID = o.OutgoingID;

    DELETE FROM #CheckTemp;

    --**  بروزرسانی تاریخ آخرین قیمت گذاری جداول قيمت گذاري


    SET @Query
        = N'select id,PricingItemID into ##UndoPricingItemTemp
					from    (select  i.PricingItemID,
									Case When DLID IS NOT NULL THEN cast (DLID as nvarchar(max)) 
										 When TraceItemID IS NOT NULL THEN cast (TraceItemID as nvarchar(max)) 
									else Value end Value,
									TraceID,stuffid,stockid

							from stc.PricingItem i
							left join 	 stc.PricingItemTrace tr  on tr.PricingItemID = i.PricingItemID
							where lastpricingdate >= @pDate
							) x
							pivot 
							(
								 max(Value)
								for TraceID in (' + @Columns + N')
							) p ' + @ConditionalInnerJoin;

    EXECUTE sp_executesql   @Query, 
							N'@pDate Date',
							@pDate = @PricingDate;

    UPDATE p
    SET LastPricingDate = DATEADD(DAY, -1, @PricingDate)
    FROM STC.PricingItem p
        JOIN ##UndoPricingItemTemp t
            ON p.PricingItemID = t.PricingItemID;



    COMMIT;

END TRY
BEGIN CATCH

    IF (@@TRANCOUNT > 0)
        ROLLBACK TRAN;

    DECLARE @ErrorMessage NVARCHAR(4000);
    DECLARE @ErrorSeverity INT;
    DECLARE @ErrorState INT;

    SELECT @ErrorMessage = ERROR_MESSAGE(),
           @ErrorSeverity = ERROR_SEVERITY(),
           @ErrorState = ERROR_STATE();


    RAISERROR(   @ErrorMessage,  -- Message text.
                 @ErrorSeverity, -- Severity.
                 @ErrorState     -- State.
             );


END CATCH;
