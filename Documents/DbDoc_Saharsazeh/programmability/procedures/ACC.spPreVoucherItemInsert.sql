CREATE    PROC [ACC].spPreVoucherItemInsert
    @PreVoucherID int,
    @RowIndex int,   
    @SlID int,
    @Description nvarchar(MAX),
    @Description2 nvarchar(MAX),
    @Debit decimal(36, 10),
    @Credit decimal(36, 10),
    @CurrencyID int,
    @CurrencyRate decimal(20, 10),
    @CurrencyDebit decimal(36, 10),
    @CurrencyCredit decimal(36, 10),
    @Creator int,
    @CreationDate datetime,
    @LastEditor int,
    @LastEditionDate datetime,
    @IsAutoGenerated bit

		--WITH ENCRYPTION 
AS 
	SET NOCOUNT ON 
	SET XACT_ABORT ON  
	
	INSERT INTO [ACC].[PreVoucherItem] ([PreVoucherID], [RowIndex], [SlID], [Description], [Description2], [Debit], [Credit], [CurrencyID], [CurrencyRate], [CurrencyDebit], [CurrencyCredit], [Creator], [CreationDate], [LastEditor], [LastEditionDate], [Version],IsAutoGenerated)
	SELECT @PreVoucherID, @RowIndex, @SlID, @Description, @Description2, @Debit, @Credit, @CurrencyID, @CurrencyRate, @CurrencyDebit, @CurrencyCredit, @Creator, @CreationDate, @LastEditor, @LastEditionDate, 0,@IsAutoGenerated
	
	-- Begin Return Select <- do not remove
	SELECT [PreVoucherItemID], [Version]
	FROM   [ACC].[PreVoucherItem]
	WHERE  [PreVoucherItemID] = SCOPE_IDENTITY();
	-- End Return Select <- do not remove
