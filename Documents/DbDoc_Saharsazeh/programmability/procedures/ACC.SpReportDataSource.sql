CREATE   PROCEDURE [ACC].SpReportDataSource
(
    @FinicialPeriodID        INT,
    @DocumentTypeIds         VARCHAR(500) = NULL,
    @FromNumber              INT = NULL,
    @ToNumber                INT = NULL,
    @FromSubNumber           INT = NULL,
    @ToSubNumber             INT = NULL,
    @FromDate                DATE = NULL,
    @ToDate                  DATE = NULL,
    @SelectedBranch          VARCHAR(MAX) = NULL,
    @FromReferenceNumber     INT = NULL,
    @ToReferenceNumber       INT = NULL,
    @ShowType                TINYINT,
	@voucherStatusIds VARCHAR(500) = NULL,
	@SelectedSlTreeLevel     VARCHAR(MAX) = NULL,
	@SelecedDlType           VARCHAR(MAX) = NULL,
	@SelectedDL              VARCHAR(MAX) = NULL,
	@ResTable				 VARCHAR(MAX),
	@IsCurrency BIT = 0
)

--WITH ENCRYPTION
WITH RECOMPILE
AS
	DECLARE @StariFP           INT,
	        @EndFP             INT,
	        @Opening           INT,
	        @Closing           INT
			

	SELECT @Opening = DocumentTypeID
	FROM   acc.DocumentType
	WHERE  engname = 'Opening'
	
	SELECT @Closing = DocumentTypeID
	FROM   acc.DocumentType
	WHERE  engname = 'Closing'
	
	SELECT * INTO #vwFinancialPeriodAccess
	FROM 	[CFG].[vwFinancialPeriodAccess]
	WHERE UserID = cfg.GetuserID()
	
	SELECT * INTO #vwBranchAccess
	FROM [CFG].[vwBranchAccess] 
	WHERE UserID = cfg.GetuserID()
		
	SELECT * INTO #vwaccountingslaccess 
	FROM cfg.vwaccountingslaccess c
	WHERE c.UserID = cfg.GetuserID()
	
	
	SET @StariFP = CFG.GetFinanacialPeriodId(@FromDate)
	SET @EndFP = CFG.GetFinanacialPeriodId(@ToDate)			
	
	SELECT VALUE
	into #DocumentTypeIds
	FROM   CFG.R_FnCommaStr2Table(@DocumentTypeIds)

	SELECT VALUE
	into #voucherStatusIds
	FROM   CFG.R_FnCommaStr2Table(@voucherStatusIds)
	
	CREATE TABLE #SelectedBranch
	(
		id           INT,
		CurrencyId	 INT
	)
	
	INSERT INTO #SelectedBranch
	select id,CurrencyId from (
	SELECT cfg.GetStringPart(VALUE, 1) id,
		   cfg.GetStringPart(VALUE, 2) CurrencyId
	FROM   cfg.Split(@SelectedBranch, '#')
	)a
	group by id,CurrencyId

	SELECT  v.VoucherID,
			v.BranchID,
	       CASE 
	            WHEN DocumentTypeID = @Opening 
	                 OR v.Number < @FromNumber 
	                 OR v.Date < @FromDate
	                 OR v.ReferenceNumber < @FromReferenceNumber THEN 1
	            ELSE 0
	       END IsFirst
	into #V
	FROM   Acc.Voucher v
		   join #DocumentTypeIds d on d.value = v.DocumentTypeID
		   join #voucherStatusIds vs on vs.value = v.VoucherStatusID
	       JOIN #vwFinancialPeriodAccess rla
	            ON  v.FinancialPeriodID = rla.FinancialPeriodID
		   join #vwBranchAccess ba
				on ba.BranchID = v.BranchID
	       LEFT JOIN  (select id from #SelectedBranch group by id) Tbranch 
	            ON  v.BranchID = Tbranch.Id
	WHERE  (
	           (
	               v.FinancialPeriodID = @StariFP
	               OR v.DocumentTypeID <> @Opening
	           )
	           AND 
			   (
			   v.FinancialPeriodID = @EndFP 
			   OR v.DocumentTypeID <> @Closing
			   )
	       )
	       AND (
	                  (@ShowType = 1 AND v.autogenerated = 1)
	               OR (@ShowType = 2 AND v.autogenerated = 0)
	               OR (@ShowType = 3)
	           )
	       AND (@FromDate IS NULL OR v.Date >= @FromDate)
	       AND (@ToDate IS NULL OR v.Date <= @ToDate)
	       AND (
	               @FromNumber IS NULL
	               OR @FromNumber = 0
	               OR v.Number >= @FromNumber
	           )
	       AND (
	               @ToNumber IS NULL
	               OR @ToNumber = 0
	               OR v.Number <= @ToNumber
	           )
	       AND (
	               @FromSubNumber IS NULL
	               OR @FromSubNumber = 0
	               OR v.SubNumber >= @FromSubNumber
	           )
	       AND (
	               @ToSubNumber IS NULL
	               OR @ToSubNumber = 0
	               OR v.SubNumber <= @ToSubNumber
	           )
	       AND (
	               @FromReferenceNumber IS NULL
	               OR @FromReferenceNumber = 0
	               OR v.ReferenceNumber >= @FromReferenceNumber
	           )
	       AND (
	               @ToReferenceNumber IS NULL
	               OR @ToReferenceNumber = 0
	               OR v.ReferenceNumber <= @ToReferenceNumber
	           )
			AND (@SelectedBranch IS NULL OR Tbranch.id IS NOT NULL)
	Declare @Column varchar(max),
			@query  nvarchar(max),
			@Join nvarchar(max),
			@DlWhereClose nvarchar(max),
			@TempSlTable nvarchar(max),
			@SlTable nvarchar(max),
			@VITable nvarchar(max),
			@SelectedSlsTable nvarchar(max),
			@SelectedDlsTable nvarchar(max)

	SET @TempSlTable = cfg.getTempTableName(1);
	set @SlTable = cfg.getTempTableName(1);
	set @VITable = cfg.getTempTableName(1);
	set @SelectedSlsTable = cfg.getTempTableName(1);
	set @SelectedDlsTable = cfg.getTempTableName(1);

	SELECT @Column = STUFF(
	            (
	                SELECT DISTINCT ','+QUOTENAME(SlTreeLevelID)
	                FROM   acc.SlTreeLevel
	                        FOR XML PATH(''),
	                        TYPE
	            ).value('.', 'NVARCHAR(MAX)'),1,1,'')
	
	CREATE TABLE #SelectedSls0
	(
		KeyField int identity(1,1),
		LevelId      varchar(50),
		ID           varchar(50),
		Currency     varchar(50)
	)	

	INSERT INTO #SelectedSls0
	SELECT cfg.GetStringPart(VALUE, 1),
			cfg.GetStringPart(VALUE, 2),
			cfg.GetStringPart(VALUE, 3)
	FROM   cfg.Split(@SelectedSlTreeLevel, '|')
	
	set @query = N'
	select *
	into '+@SelectedSlsTable+'
	from (select *  from #SelectedSls0) x
	pivot
	(
	max(id)
	for LevelId in ('+@Column+')
	)p'

	EXECUTE sp_executeSQL     
			@Query

	if @SelectedSlTreeLevel is not null
	begin
	set @Join = 
			STUFF(
	            (
	                SELECT 'join '+@SelectedSlsTable+' ssls'+LevelId+
							' on sl.'+QUOTENAME(LevelId)+' = ssls'+LevelId+'.'+QUOTENAME(LevelId)+
							case when @IsCurrency = 0 then '' else 
							' and vi.currencyid = ssls'+LevelId+'.currency ' end +							
						   char(13)+char(10)
	                FROM   #SelectedSls0
					group by LevelId
	                        FOR XML PATH(''),
	                        TYPE
	            ).value('.', 'NVARCHAR(MAX)'),1,0,'')
	end
	else if @SelectedSlTreeLevel is null
	set @Join = ''

			
	SELECT s.SlID,
		   s.ParentID,
		   s.SlTreeLevelID
	into #TT
	FROM ACC.SL AS s
	where s.SlID <> -1

	set @query = N'
	;with C as
	(
	  select T.SlID,
			 T.SlID as RootID,
			 SlTreeLevelID
	  from #TT T
	  union all
	  select T.SlID,
			 C.RootID,
			 c.SlTreeLevelID
	  from #TT T
		inner join C 
		  on T.ParentId = C.SlID
	)
	select * 
	into '+@TempSlTable+' 
	from(
		select *  from c
		)x
		pivot
		(
		max(rootid)
		for SlTreeLevelID in ('+@Column+')
		)p'
	
	exec(@query)
	
	
	SET @query = N'
	select a.* into '+@SlTable+' from '+@TempSlTable+'  a
	join #vwaccountingslaccess b on a.slid = b.slid
	'
	exec(@query)	

	DECLARE @SlTreeLevelID varchar(10)
	DECLARE @LevelOrder int
	DECLARE @PreviousSlTreeLevelID varchar(10)

	DECLARE db_cursor CURSOR FOR 
	SELECT SlTreeLevelID,LevelOrder 
	FROM acc.SlTreeLevel
	order by LevelOrder 

	OPEN db_cursor  
	FETCH NEXT FROM db_cursor INTO @SlTreeLevelID, @LevelOrder

	WHILE @@FETCH_STATUS = 0  
	BEGIN  
			  select @PreviousSlTreeLevelID =  SlTreeLevelID
			  from acc.SlTreeLevel
			  where LevelOrder = @LevelOrder - 1

			  set @query =N'update '+@SlTable+'
			  set ['+@SlTreeLevelID+'] = ['+@PreviousSlTreeLevelID+']
			  where ['+@SlTreeLevelID+'] is null
			  '
			  EXECUTE sp_executeSQL     
		  			@Query
		  FETCH NEXT FROM db_cursor INTO @SlTreeLevelID, @LevelOrder 
	END 

	CLOSE db_cursor  
	DEALLOCATE db_cursor 

	if @SelecedDlType is null and @SelectedDL is null
	begin
		set @query = N'
		SELECT DISTINCT vi.VoucherItemID,vi.Debit,vi.Credit,vi.CurrencyID,CurrencyDebit,CurrencyCredit,IsFirst,BranchID,sl.*
		into '+@ResTable+'
		FROM #V
		INNER JOIN acc.VoucherItem AS vi
			ON vi.VoucherID=#V.voucherid
		INNER JOIN  '+@SlTable+' sl
					ON sl.SlId = vi.SlId
	    LEFT JOIN  #SelectedBranch Tbranch
	        ON  #V.BranchID = Tbranch.Id '+
			case when @IsCurrency = 0 then '' else 
			'and vi.CurrencyID = Tbranch.CurrencyID
			' end
		+@Join+'
		where (@SelectedBranch IS NULL OR Tbranch.id IS NOT NULL)'
	--	print @Query
		EXECUTE sp_executeSQL     
				@Query,
			  N'@SelectedSlTreeLevel NVARCHAR(MAX),
				@SelectedBranch  NVARCHAR(MAX)',
				@SelectedSlTreeLevel = @SelectedSlTreeLevel,
				@SelectedBranch = @SelectedBranch

	end
	else
	begin 
		DECLARE @Columns VARCHAR(MAX);
		SELECT @Columns = STUFF(
		(
			SELECT DISTINCT
				   ',' + QUOTENAME(al.AccountLevelID)
			FROM ACC.AccountLevel al
			FOR XML PATH(''), TYPE
		).value('.', 'NVARCHAR(MAX)'),1   ,1   ,'');

		IF @Columns IS NULL
		   OR @Columns = ''
			SET @Columns = '[-1]';

		CREATE TABLE #SelectedDltype
		(
			id         INT,
			CurrencyID INT
		)

		INSERT INTO #SelectedDltype
		SELECT  cfg.GetStringPart(VALUE, 1),
				cfg.GetStringPart(VALUE, 2) 
		FROM   cfg.Split(@SelecedDlType, '#')	

		CREATE TABLE #Selecteddl0
		(
			KeyField int identity(1,1),
			[LEVEL] varchar(50),
			id varchar(50),
			currency varchar(50)
		);

		INSERT INTO #Selecteddl0
		SELECT
			   CFG.GetStringPart(value, 1) [LEVEL],
			   CFG.GetStringPart(value, 2) id,
			   CFG.GetStringPart(value, 3) currency
		FROM CFG.Split(@SelectedDl, '|');

		if NOT EXISTS (select *  from #Selecteddl0 where [LEVEL] = -1)
		begin

			set @DlWhereClose = 
					STUFF(
						(
							SELECT ' and alvi.'+QUOTENAME([LEVEL])+' in (select id from #Selecteddl0 where [LEVEL] = '+cast([LEVEL] as varchar(100))+
							case when @IsCurrency = 0 then ')' else
							' and currency = vi.currencyid )' end+
								   char(13)+char(10)
							FROM   #Selecteddl0 
							group by [LEVEL]
									FOR XML PATH(''),
									TYPE
						).value('.', 'NVARCHAR(MAX)'),1,0,'')
			if @DlWhereClose is null
			set @DlWhereClose = ''
	
			set @query = N'
				SELECT alvi.VoucherItemID,
					alvi.AccountLevelID,
					alvi.DlID,
					d.DlTypeID,
					dlt.CurrencyID SelectedDlTypeCurrencyID
				  into #AccountLevelVoucherItem
				FROM   Acc.AccountLevelVoucherItem alvi		
				INNER JOIN acc.DL AS d
					ON  d.DLID = alvi.DlID
				LEFT JOIN (
							select id 
							from #Selecteddl0 
							group by id
						  ) sd on sd.id = alvi.dlid
				LEFT JOIN 
				(
					select  id,
							CurrencyID
					from #SelectedDltype
					group by id,CurrencyID
				)dlt
					ON dlt.id = d.DlTypeID
				where (@SelecedDlType is null or dlt.id is not null)
				and   (@SelectedDl is null or sd.id is not null)

				select *
				into #AccountLevelVoucherItem01
				from
					(
					select VoucherItemID,AccountLevelID,DlID,SelectedDlTypeCurrencyID 
					from #AccountLevelVoucherItem
					) x
				PIVOT
				(
					MAX(DlID)
					FOR AccountLevelID IN (' + @Columns + N')
				)piv


				SELECT DISTINCT vi.VoucherItemID,vi.Debit,vi.Credit,vi.CurrencyID,CurrencyDebit,CurrencyCredit,IsFirst,BranchID,sl.*
				into '+@ResTable+'
				FROM #V
				INNER JOIN acc.VoucherItem AS vi
					ON vi.VoucherID=#V.voucherid
				INNER JOIN  '+@SlTable+' sl
							ON sl.SlId = vi.SlId
				LEFT JOIN  #SelectedBranch Tbranch
					ON  #V.BranchID = Tbranch.Id '+
					case when @IsCurrency = 0 then '' else 
					'and vi.CurrencyID = Tbranch.CurrencyID
					' end
				+@Join+'
				INNER JOIN #AccountLevelVoucherItem01 AS alvi
					ON  alvi.VoucherItemID = vi.VoucherItemID
					'
					+
					case when @SelecedDlType is null or @IsCurrency = 0 then '' else 
					'and vi.CurrencyID = alvi.SelectedDlTypeCurrencyID
					' end					
					+
					'
				where  (@SelectedBranch IS NULL OR Tbranch.id IS NOT NULL)'
				+@DlWhereClose
		--	print @Query
			EXECUTE sp_executeSQL     
					@Query,
					N'@SelecedDlType NVARCHAR(MAX),
					  @SelectedSlTreeLevel NVARCHAR(MAX),
					  @SelectedBranch  NVARCHAR(MAX),
					  @SelectedDl NVARCHAR(MAX)',
					@SelecedDlType = @SelecedDlType,
					@SelectedSlTreeLevel = @SelectedSlTreeLevel,
					@SelectedBranch = @SelectedBranch,
					@SelectedDl = @SelectedDl
		end

		if EXISTS (select *  from #Selecteddl0 where [LEVEL] = -1)
		begin
			set @query = N'
				SELECT 
					alvi.VoucherItemID,
					alvi.DlID,
					Currency 
				 into #AccountLevelVoucherItem
				FROM   Acc.AccountLevelVoucherItem alvi		
				join (
				select id , currency
				from #Selecteddl0 
				group by id , currency
					 ) sd on sd.id = alvi.dlid
				INNER JOIN acc.DL AS d
					ON  d.DLID = alvi.DlID
				LEFT JOIN #SelectedDltype dlt
					ON dlt.id = d.DlTypeID
				where (@SelecedDlType is null or dlt.id is not null)

				SELECT DISTINCT vi.VoucherItemID,vi.Debit,vi.Credit,vi.CurrencyID,CurrencyDebit,CurrencyCredit,IsFirst,BranchID,sl.*
				into '+@ResTable+'
				FROM #V
				INNER JOIN acc.VoucherItem AS vi
					ON vi.VoucherID=#V.voucherid
				INNER JOIN  '+@SlTable+' sl
							ON sl.SlId = vi.SlId
				LEFT JOIN  #SelectedBranch Tbranch
					ON  #V.BranchID = Tbranch.Id '+
					case when @IsCurrency = 0 then '' else 
					'and vi.CurrencyID = Tbranch.CurrencyID
					' end
				+@Join+'
				INNER JOIN #AccountLevelVoucherItem alvi
					ON  alvi.VoucherItemID = vi.VoucherItemID '
					+
					case when @IsCurrency = 0 then '' else 
					'and vi.CurrencyID = alvi.Currency
					' end				
					+
					' 
				where  (@SelectedBranch IS NULL OR Tbranch.id IS NOT NULL)'
			--print @Query
			EXECUTE sp_executeSQL     
					@Query,
					N'@SelecedDlType NVARCHAR(MAX),
					  @SelectedSlTreeLevel NVARCHAR(MAX),
					  @SelectedBranch  NVARCHAR(MAX)',
					@SelecedDlType = @SelecedDlType,
					@SelectedSlTreeLevel = @SelectedSlTreeLevel,
					@SelectedBranch = @SelectedBranch
					
					
		end
	end
