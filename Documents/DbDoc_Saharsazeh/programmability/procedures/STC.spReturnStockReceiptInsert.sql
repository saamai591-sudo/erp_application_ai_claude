CREATE   PROC [STC].[spReturnStockReceiptInsert]
    @AutoGenerated BIT ,
    @StockDocumentTypeBaseEntityID INT ,
    @StockID INT ,
    @DeliverDlID BIGINT ,
    @DeliverStockID INT ,
    @Number INT ,
    @Date DATE ,
    @TotalInvoicePrice DECIMAL(30, 4) ,
    @PreVoucherID INT ,
    @Creator INT ,
    @CreationDate DATETIME ,
    @LastEditor INT ,
    @LastEditionDate DATETIME ,
    @FinancialPeriodID INT ,
    @ReturnedOutgoingID INT
--WITH ENCRYPTION 
AS
BEGIN
    SET NOCOUNT ON;
    SET XACT_ABORT ON;

    DECLARE @StartNum INT = NULL ,
            @EndNum INT = NULL ,
            @Stock BIT = 0 ,
            @ResetType BIT = 0 ,
            @DocumentNumID INT ,
			@StockDocumentTypeID INT,
            @DocumentNumTypeID INT ,
            @Message NVARCHAR(MAX);

    SELECT @DocumentNumTypeID = DocumentNumTypeID
    FROM   CFG.[DocumentNumType]
    WHERE  EngName = 'ReturnStockReceipt';

	SELECT  @StockDocumentTypeID = StockDocumentTypeID
    FROM    stc.StockDocumentTypeBaseEntity sdtb
	WHERE sdtb.StockDocumentTypeBaseEntityID = @StockDocumentTypeBaseEntityID


    SELECT @StartNum = StartNum ,
           @EndNum = EndNum ,
           @DocumentNumID = DocumentNumID
    FROM   CFG.DocumentNum
    WHERE  DocumentNumTypeID = @DocumentNumTypeID
           AND FinancialPeriodID = @FinancialPeriodID;

    IF EXISTS (   SELECT 1
                  FROM   CFG.DocumentNumResetNumberBase
                  WHERE  DocumentNumID = @DocumentNumID
                         AND DocumentNumResetNumberBaseTypeID = 3 )
        BEGIN
            SET @Stock = 1;
        END;

    IF EXISTS (   SELECT 1
                  FROM   CFG.DocumentNumResetNumberBase
                  WHERE  DocumentNumID = @DocumentNumID
                         AND DocumentNumResetNumberBaseTypeID = 2 )
        BEGIN
            SET @ResetType = 1;
        END;

    IF (   @Number = 0
           OR @Number IS NULL )
        BEGIN
            SET @Number = ISNULL((   SELECT MAX(Number) + 1
                              FROM   [STC].[ReturnStockReceipt] rsr
							  JOIN [STC].[StockDocumentTypeBaseEntity] sdtb
									ON rsr.StockDocumentTypeBaseEntityID = sdtb.StockDocumentTypeBaseEntityID

                              WHERE  FinancialPeriodID = @FinancialPeriodID
                                     AND (   @Stock = 0
                                             OR StockID = @StockID )
                                     AND (   @ResetType = 0
                                             OR sdtb.StockDocumentTypeID = @StockDocumentTypeID )) ,
                          @StartNum);
        END;
    ELSE
        BEGIN
            IF EXISTS (   SELECT 1
                            FROM   [STC].[ReturnStockReceipt]rsr
							JOIN [STC].[StockDocumentTypeBaseEntity] sdtb
								ON rsr.StockDocumentTypeBaseEntityID = sdtb.StockDocumentTypeBaseEntityID
                            WHERE  FinancialPeriodID = @FinancialPeriodID
                                   AND (   @Stock = 0
                                           OR StockID = @StockID )
                                   AND (   @ResetType = 0
                                           OR sdtb.StockDocumentTypeID = @StockDocumentTypeID )
                                   AND Number = @Number )
                BEGIN

                    SELECT @Message = 'NumberIsDuplicate'
                    RAISERROR(@Message, 16, 12);
                    RETURN 0;
                END;
        END;

    IF (   @Number >= @StartNum
           AND (   @EndNum IS NULL
                   OR @Number <= @EndNum ))
        BEGIN

            INSERT INTO [STC].[ReturnStockReceipt] ( [AutoGenerated] ,
                                                     StockDocumentTypeBaseEntityID ,
                                                     [StockID] ,
                                                     [DeliverDlID] ,
                                                     [DeliverStockID] ,
                                                     [Number] ,
                                                     [Date] ,
                                                     [TotalInvoicePrice] ,
                                                     [PreVoucherID] ,
                                                     [Version] ,
                                                     [Creator] ,
                                                     [CreationDate] ,
                                                     [LastEditor] ,
                                                     [LastEditionDate] ,
                                                     [FinancialPeriodID] ,
                                                     [ReturnedOutgoingID])
                        SELECT @AutoGenerated ,
                               @StockDocumentTypeBaseEntityID ,
                               @StockID ,
                               @DeliverDlID ,
                               @DeliverStockID ,
                               @Number ,
                               @Date ,
                               @TotalInvoicePrice ,
                               @PreVoucherID ,
                               0 ,
                               @Creator ,
                               @CreationDate ,
                               @LastEditor ,
                               @LastEditionDate ,
                               @FinancialPeriodID ,
                               @ReturnedOutgoingID;

            -- Begin Return Select <- do not remove
            SELECT [ReturnStockReceiptID] ,
                   [Version] ,
                   [Number]
            FROM   [STC].[ReturnStockReceipt]
            WHERE  [ReturnStockReceiptID] = SCOPE_IDENTITY();
        -- End Return Select <- do not remove
        
        END;
    ELSE
        BEGIN
            SELECT @Message ='InvalidNumberRange'
            RAISERROR(@Message, 16, 12);
        END;
END;
