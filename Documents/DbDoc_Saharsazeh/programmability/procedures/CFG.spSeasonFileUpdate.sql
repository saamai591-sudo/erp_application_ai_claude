CREATE   PROC [CFG].[spSeasonFileUpdate]
    @SeasonFileID INT,
    @FinancialPeriodID INT,
    @Season TINYINT,
    @AutoGenerated BIT,
    @DOCType TINYINT,
    @DocName NVARCHAR(MAX),
    @ID BIGINT,
    @StuffTitle NVARCHAR(MAX),
    @LessThanQuorum BIT,
    @IsHagholAmalKari BIT,
    @IsArzi BIT,
    @Sarjam BIT,
    @KalaType INT,
    @Amount DECIMAL(30, 4),
    @Tax DECIMAL(30, 4),
    @Duty DECIMAL(30, 4),
    @Discount DECIMAL(30, 4),
    @ZipCode NVARCHAR(256),
    @PreNumberOfCity NVARCHAR(50),
    @Phone NVARCHAR(50),
    @Address NVARCHAR(MAX),
    @PartyFirstName NVARCHAR(MAX),
    @PartyLastName NVARCHAR(MAX),
    @EconomicCode NVARCHAR(50),
    @NationalID NVARCHAR(50),
    @HCType1Code TINYINT,
    @provinceCode NVARCHAR(50),
    @cityCode NVARCHAR(50),
    @Type BIT,
    @Number INT,
    @Date NVARCHAR(50),
    @TradeType TINYINT,
    @BranchCode INT,
    @BranchTitle NVARCHAR(MAX),
    @Version INT,
    @Creator INT,
    @CreationDate DATETIME,
    @LastEditor INT,
    @LastEditionDate DATETIME,
    @ArzType INT,
    @Arz_Price DECIMAL(30, 4),
    @Arz_MaliatArzeshAfzoodeh DECIMAL(30, 4),
    @Arz_AvarezArzeshAfzoodeh DECIMAL(30, 4),
    @Arz_SayerAvarez DECIMAL(30, 4),
    @Arz_TakhfifPrice DECIMAL(30, 4),
    @ArzBarabari_Price DECIMAL(18, 2),
    @ArzBarabari_MaliatArzeshAfzoodeh DECIMAL(18, 2),
    @ArzBarabari_AvarezArzeshAfzoodeh DECIMAL(18, 2),
    @ArzBarabari_SayerAvarez DECIMAL(18, 2),
    @ArzBarabari_TakhfifPrice DECIMAL(18, 2),
    @FactorNo NVARCHAR(100),
    @FactorDate VARCHAR(10),
    @SarFaslType INT,
    @SaleTypeTitle NVARCHAR(256),
    @CountryCode VARCHAR(50),
    @PurchaseType TINYINT,
    @FidaCode NVARCHAR(11),
    @AmountAccordingLicense DECIMAL(30, 4),
    @Currency NVARCHAR(25),
    @Arz_AmountAccordingLicense DECIMAL(30, 4),
    @ArzBarabari_AmountAccordingLicense DECIMAL(18, 2),
    @CotajNumber VARCHAR(250),
    @CotajDate VARCHAR(10),
    @EntranceCustomsCode NVARCHAR(100),
    @AssessmentCustomsCode NVARCHAR(100),
    @LetterCreditNumber NVARCHAR(100),
    @OpeningCreditDate VARCHAR(10),
	@Nationality int ,
	@PayDate NVARCHAR(10),
	@GrossPrice DECIMAL(30,4),
	@NetPrice DECIMAL(30,4),
	@TaxDeducted  DECIMAL(30,4),
	@ContractNumber NVARCHAR(250) ,
	@StartDate DATE,
	@FinishDate DATE,
    @CompanyID INT
AS
SET NOCOUNT ON;


IF @Version =
(
    SELECT [Version]
    FROM [CFG].[SeasonFile]
    WHERE [SeasonFileID] = @SeasonFileID
)
BEGIN
    SET @Version = @Version + 1;

    UPDATE [CFG].[SeasonFile]
    SET [FinancialPeriodID] = @FinancialPeriodID,
        [Season] = @Season,
        [AutoGenerated] = @AutoGenerated,
        [DOCType] = @DOCType,
        [DocName] = @DocName,
        [ID] = @ID,
        [StuffTitle] = @StuffTitle,
        [LessThanQuorum] = @LessThanQuorum,
        [Amount] = @Amount,
        [Tax] = @Tax,
        [Duty] = @Duty,
        [Discount] = @Discount,
        [ZipCode] = @ZipCode,
        [PreNumberOfCity] = @PreNumberOfCity,
        [Phone] = @Phone,
        [Address] = @Address,
        [PartyFirstName] = @PartyFirstName,
        [PartyLastName] = @PartyLastName,
        [EconomicCode] = @EconomicCode,
        [NationalID] = @NationalID,
        [HCType1Code] = @HCType1Code,
        [provinceCode] = @provinceCode,
        [cityCode] = @cityCode,
        [Type] = @Type,
        [Number] = @Number,
        [Date] = @Date,
        [TradeType] = @TradeType,
        [BranchCode] = @BranchCode,
        [BranchTitle] = @BranchTitle,
        [Version] = @Version,
        [Creator] = @Creator,
        [CreationDate] = @CreationDate,
        [LastEditor] = @LastEditor,
        [LastEditionDate] = @LastEditionDate,
        [ArzType] = @ArzType,
        [Arz_Price] = @Arz_Price,
        [Arz_MaliatArzeshAfzoodeh] = @Arz_MaliatArzeshAfzoodeh,
        [Arz_AvarezArzeshAfzoodeh] = @Arz_AvarezArzeshAfzoodeh,
        [Arz_SayerAvarez] = @Arz_SayerAvarez,
        [Arz_TakhfifPrice] = @Arz_TakhfifPrice,
        [ArzBarabari_Price] = @ArzBarabari_Price,
        [ArzBarabari_MaliatArzeshAfzoodeh] = @ArzBarabari_MaliatArzeshAfzoodeh,
        [ArzBarabari_AvarezArzeshAfzoodeh] = @ArzBarabari_AvarezArzeshAfzoodeh,
        [ArzBarabari_SayerAvarez] = @ArzBarabari_SayerAvarez,
        [ArzBarabari_TakhfifPrice] = @ArzBarabari_TakhfifPrice,
        [FactorNo] = @FactorNo,
        [FactorDate] = @FactorDate,
        [SarFaslType] = @SarFaslType,
        IsHagholAmalKari = @IsHagholAmalKari,
        Sarjam = @Sarjam,
        KalaType = @KalaType,
        IsArzi = @IsArzi,
        SaleTypeTitle = @SaleTypeTitle,
        CountryCode = @CountryCode,
        PurchaseType = @PurchaseType,
        FidaCode = @FidaCode,
        AmountAccordingLicense = @AmountAccordingLicense,
        Currency = @Currency,
        Arz_AmountAccordingLicense = @Arz_AmountAccordingLicense,
        ArzBarabari_AmountAccordingLicense = @ArzBarabari_AmountAccordingLicense,
        CotajNumber = @CotajNumber,
        CotajDate = @CotajDate,
        EntranceCustomsCode = @EntranceCustomsCode,
        AssessmentCustomsCode = @AssessmentCustomsCode,
        LetterCreditNumber = @LetterCreditNumber,
        OpeningCreditDate = @OpeningCreditDate,
        Nationality = @Nationality, 
        PayDate = @PayDate,
        GrossPrice = @GrossPrice,
        NetPrice = @NetPrice,
        TaxDeducted = @TaxDeducted,
        ContractNumber = @ContractNumber,
	    StartDate = @StartDate,
	    FinishDate = @FinishDate,
        [CompanyID]=@CompanyID
    WHERE [SeasonFileID] = @SeasonFileID;

    -- Begin Return Select <- do not remove
    SELECT [Version]
    FROM [CFG].[SeasonFile]
    WHERE [SeasonFileID] = @SeasonFileID;
-- End Return Select <- do not remove
END;
ELSE
    RAISERROR('Version mismatch...', 16, 10);
