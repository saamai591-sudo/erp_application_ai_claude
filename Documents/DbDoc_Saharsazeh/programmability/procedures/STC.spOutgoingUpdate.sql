CREATE   PROC [STC].[spOutgoingUpdate] 
    @OutgoingID int,
    @AutoGenerated bit,
    @StockDocumentTypeBaseEntityID INT ,
    @Number int,
    @Date date,
    @StockID int,
    @DeliverDlID bigint,
    @DeliverStockID int,
    @FinancialPeriodID int,
    @PreVoucherID int,
    @Version int,
    @LastEditor int,
    @LastEditionDate datetime,
    @TotalPrice decimal(30,4)

--WITH ENCRYPTION 
AS 
BEGIN
	SET NOCOUNT ON 

	DECLARE @PreVersion INT,
			@PrePrevoucherID INT
			
	Select  @PreVersion = [Version],
			@PrePrevoucherID = PreVoucherID
	 from [STC].[Outgoing]
	where [OutgoingID] = @OutgoingID			

	if @Version <> @PreVersion or @PrePrevoucherID is not null	
	begin
	RAISERROR('Version mismatch...', 16 , 10)
	return
	end
	
	DECLARE @StartNum  INT = NULL,
			@EndNum    INT = NULL,
			@Stock	   bit = 0,
			@ResetType bit = 0,
			@DocumentNumID int,
			@StockReceiptID  INT ,
			@StockDocumentTypeID INT,
			@StockReceiptStartNum  INT = NULL,
			@StockReceiptEndNum    INT = NULL,
			@StockReceiptStock	   bit = 0,
			@StockReceiptResetType bit = 0,
			@StockReceiptDocumentNumID int,
			@StockReceiptNumber int,
			@Message NVARCHAR(MAX)
	
	SELECT  @StockDocumentTypeID = StockDocumentTypeID
    FROM    stc.StockDocumentTypeBaseEntity sdtb
	where sdtb.StockDocumentTypeBaseEntityID = @StockDocumentTypeBaseEntityID

	SELECT @StartNum = StartNum,
		   @EndNum = EndNum,
		   @DocumentNumID =DocumentNumID 
	FROM   CFG.DocumentNum 
	WHERE  DocumentNumTypeID = 16
		   AND FinancialPeriodID = @FinancialPeriodID

	If Exists (select * from cfg.DocumentNumResetNumberBase 
	where DocumentNumID=@DocumentNumID and DocumentNumResetNumberBaseTypeID=3)
	Begin
	Set @Stock = 1
	End
	
	If Exists (select * from cfg.DocumentNumResetNumberBase 
	where DocumentNumID=@DocumentNumID and DocumentNumResetNumberBaseTypeID=2)
	Begin
	Set @ResetType = 1
	END
	           
	IF (@Number = 0 OR @Number IS NULL)
	BEGIN
		SET @Number = ISNULL(
            (	SELECT MAX(Number) + 1
                FROM   [STC].[Outgoing] o
				JOIN [STC].[StockDocumentTypeBaseEntity] sdtb 
						ON o.StockDocumentTypeBaseEntityID = sdtb.StockDocumentTypeBaseEntityID
                WHERE  FinancialPeriodID = @FinancialPeriodID and (@Stock=0 OR StockID=@StockID)
                and (@ResetType=0 OR [StockDocumentTypeID]=@StockDocumentTypeID)
            )
            ,@StartNum)
    END
	ELSE
	BEGIN
		
		IF (Exists (SELECT * FROM [STC].[Outgoing]  o
					JOIN [STC].[StockDocumentTypeBaseEntity] sdtb 
						ON o.StockDocumentTypeBaseEntityID = sdtb.StockDocumentTypeBaseEntityID
		            WHERE FinancialPeriodID = @FinancialPeriodID 
		            AND (@Stock=0 OR StockID=@StockID)
					AND (@ResetType=0 OR [StockDocumentTypeID]=@StockDocumentTypeID) 
					AND Number = @Number 
					AND outgoingid <> @OutgoingID) )
		BEGIN
			
			
			RAISERROR('NumberIsDuplicate',16,12)
			--NumberIsDuplicate
			--RAISERROR('شماره حواله تکراری است', 16, 12)
		END
					
	END
	
      IF (
       @Number >= @StartNum
       AND (@EndNum IS NULL OR @Number <= @EndNum)
   )
	BEGIN
	

		UPDATE [STC].[Outgoing]
		SET     [AutoGenerated] = @AutoGenerated, 
				[StockDocumentTypeBaseEntityID] = @StockDocumentTypeBaseEntityID,
				[TotalPrice] = @TotalPrice, 
				[Number] = @Number, 
				[Date] = @Date, 
				[StockID] = @StockID, 
				[DeliverDlID] = @DeliverDlID, 
				[DeliverStockID] = @DeliverStockID, 
				[Version] = @Version + 1, 
				[LastEditor] = @LastEditor, 
				[LastEditionDate] = @LastEditionDate
		WHERE  [OutgoingID] = @OutgoingID
	
		-- Begin Return Select <- do not remove
		SELECT  [Version] 
        FROM   [STC].[Outgoing]
		WHERE  [OutgoingID] = @OutgoingID	
		-- End Return Select <- do not remove		
		

	end 
	
	ELSE		
	BEGIN
		
		RAISERROR('InvalidNumberRange',16,12)
		--InvalidNumberRange
		--RAISERROR('شماره در محدوده ي مجاز نمي باشد', 16, 12)
	END

	
END
