
CREATE    PROC [STF].spTraceDocumentNumTypeInsert
    @TraceID INT ,
    @DocumentNumTypeID SMALLINT ,
    @Creator INT ,
    @CreationDate DATETIME ,
    @LastEditor INT ,
    @LastEditionDate DATETIME,
	@IsAutoGenerated BIT 
AS
    SET NOCOUNT ON;


    INSERT INTO [STF].[TraceDocumentNumType] ( [TraceID] ,
                                               [DocumentNumTypeID] ,
                                               [Version] ,
                                               [Creator] ,
                                               [CreationDate] ,
                                               [LastEditor] ,
                                               [LastEditionDate] ,
											   [IsAutoGenerated])
                SELECT @TraceID ,
                       @DocumentNumTypeID ,
                       0 ,
                       @Creator ,
                       @CreationDate ,
                       @LastEditor ,
                       @LastEditionDate,
					   @IsAutoGenerated;

    DECLARE @id INT;

    SET @id = SCOPE_IDENTITY();



    -- Begin Return Select <- do not remove
    SELECT [TraceDocumentNumTypeID] ,
           [Version]
    FROM   [STF].[TraceDocumentNumType]
    WHERE  [TraceDocumentNumTypeID] = @id;
-- End Return Select <- do not remove
