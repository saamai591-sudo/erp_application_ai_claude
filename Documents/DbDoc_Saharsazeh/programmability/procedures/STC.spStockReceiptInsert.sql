	
-----------------------------------------------------------------------
CREATE    PROC [STC].spStockReceiptInsert
    @AutoGenerated BIT,
    @StockDocumentTypeBaseEntityID INT,
    @StockID INT,
    @DeliverDlID BIGINT,
    @DeliverStockID INT,
    @Number INT,
    @Date DATE,
    @TotalInvoicePrice DECIMAL(30, 4),
    @TotalEstimatedPrice DECIMAL(30, 4),
    @TotalCosts DECIMAL(30, 4),
    @TotalNetPrice DECIMAL(30, 4),
    @PreVoucherID INT,
    @OutgoingID INT,
    @Creator INT,
    @CreationDate DATETIME,
    @LastEditor INT,
    @LastEditionDate DATETIME,
    @FinancialPeriodID INT

--WITH ENCRYPTION 
AS
BEGIN
    SET NOCOUNT ON;
    SET XACT_ABORT ON;

    DECLARE @Type TINYINT,
	@StockDocumentTypeID INT;

	select @StockDocumentTypeID = StockDocumentTypeID 
	from STC.StockDocumentTypeBaseEntity sdtb
	WHERE sdtb.StockDocumentTypeBaseEntityID = @StockDocumentTypeBaseEntityID

	SELECT @Type = [Type]
	FROM STC.StockDocumentType AS sdt
	WHERE sdt.StockDocumentTypeID = @StockDocumentTypeID;

    IF (
           @Type = 7
           AND EXISTS
    (
        SELECT 1
        FROM STC.StockReceipt AS sr		
		join STC.StockDocumentTypeBaseEntity sdtb 
				on sr.StockDocumentTypeBaseEntityID = sdtb.StockDocumentTypeBaseEntityID
		INNER JOIN STC.StockDocumentType AS sdt
				ON sdt.StockDocumentTypeID = sdtb.StockDocumentTypeID
        WHERE FinancialPeriodID = @FinancialPeriodID
              AND sr.StockID = @StockID
              AND sdt.[Type] = 7
    )
       )
    BEGIN
        DECLARE @Message NVARCHAR(MAX);

        SELECT @Message ='STC_spStockReceiptInsert_1'

        RAISERROR(@Message, 16, 12);
       
        RETURN;
    END;

    DECLARE @StartNum INT = NULL,
            @EndNum INT = NULL,
            @Stock BIT = 0,
            @ResetType BIT = 0,
            @DocumentNumID INT,
            @DocumentNumTypeID INT;


    SELECT @DocumentNumTypeID = DocumentNumTypeID
    FROM [CFG].[DocumentNumType]
    WHERE EngName = 'StockReceipt';

    SELECT @StartNum = StartNum,
           @EndNum = EndNum,
           @DocumentNumID = DocumentNumID
    FROM CFG.DocumentNum
    WHERE DocumentNumTypeID = @DocumentNumTypeID
          AND FinancialPeriodID = @FinancialPeriodID;





    IF EXISTS
    (
        SELECT *
        FROM CFG.DocumentNumResetNumberBase
        WHERE DocumentNumID = @DocumentNumID
              AND DocumentNumResetNumberBaseTypeID = 3
    )
    BEGIN
        SET @Stock = 1;
    END;

    IF (
           @Type = 7
           OR EXISTS
    (
        SELECT *
        FROM CFG.DocumentNumResetNumberBase
        WHERE DocumentNumID = @DocumentNumID
              AND DocumentNumResetNumberBaseTypeID = 2
    )
       )
    BEGIN
        SET @ResetType = 1;
    END;

    IF (@Number = 0 OR @Number IS NULL)
    BEGIN

        SET @Number = ISNULL(
                      (
                          SELECT MAX(Number) + 1
                          FROM [STC].[StockReceipt] sr
						  join STC.StockDocumentTypeBaseEntity sdtb 
								on sr.StockDocumentTypeBaseEntityID = sdtb.StockDocumentTypeBaseEntityID
                          WHERE FinancialPeriodID = @FinancialPeriodID
                                AND
                                (
                                    @Stock = 0
                                    OR StockID = @StockID
                                )
                                AND
                                (
                                    @ResetType = 0
                                    OR sdtb.StockDocumentTypeID = @StockDocumentTypeID
                                )
                      ),
                      @StartNum
                            );
    END;
    ELSE
    BEGIN
        IF (EXISTS
        (
            SELECT *
            FROM [STC].[StockReceipt]  sr
			join STC.StockDocumentTypeBaseEntity sdtb 
				on sr.StockDocumentTypeBaseEntityID = sdtb.StockDocumentTypeBaseEntityID
            WHERE FinancialPeriodID = @FinancialPeriodID
                  AND
                  (
                      @Stock = 0
                      OR StockID = @StockID
                  )
                  AND
                  (
                      @ResetType = 0
                      OR sdtb.[StockDocumentTypeID] = @StockDocumentTypeID
                  )
                  AND Number = @Number
        )
           )
        BEGIN


            SELECT @Message = 'NumberIsDuplicate'
          
            RAISERROR(@Message, 16, 12);
            --RAISERROR('شماره وارد شده تکراری است.', 16, 12)
            RETURN;
        END;
    END;

    IF (@Number >= @StartNum AND (@EndNum IS NULL OR @Number <= @EndNum))
    BEGIN



        INSERT INTO [STC].[StockReceipt]
        (
            [AutoGenerated],
            StockDocumentTypeBaseEntityID,
            [StockID],
            [DeliverDlID],
            [DeliverStockID],
            [Number],
            [Date],
            [TotalInvoicePrice],
            [TotalEstimatedPrice],
            [TotalCosts],
            [TotalNetPrice],
            [PreVoucherID],
            [OutgoingID],
            [Version],
            [Creator],
            [CreationDate],
            [LastEditor],
            [LastEditionDate],
            [FinancialPeriodID]
        )
        SELECT @AutoGenerated,
               @StockDocumentTypeBaseEntityID,
               @StockID,
               @DeliverDlID,
               @DeliverStockID,
               @Number,
               @Date,
               @TotalInvoicePrice,
               @TotalEstimatedPrice,
               @TotalCosts,
               @TotalNetPrice,
               @PreVoucherID,
               @OutgoingID,
               0,
               @Creator,
               @CreationDate,
               @LastEditor,
               @LastEditionDate,
               @FinancialPeriodID

        -- Begin Return Select <- do not remove
        SELECT [StockReceiptID],
               [Version],
               [Number]
        FROM [STC].[StockReceipt]
        WHERE [StockReceiptID] = SCOPE_IDENTITY();
    -- End Return Select <- do not remove


    END;
    ELSE
    BEGIN
        SELECT @Message = 'InvalidNumberRange'

        RAISERROR(@Message, 16, 12);
    END;

END;
