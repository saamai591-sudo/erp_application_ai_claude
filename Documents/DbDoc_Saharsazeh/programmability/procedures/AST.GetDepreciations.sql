CREATE     PROC [AST].GetDepreciations
(
@FinancialPeriodID int
)
--WITH ENCRYPTION 
as

declare @Working nvarchar(150),
		@Unused nvarchar(150),
		@UserCulture varchar(2),
		@Columns nvarchar(max),
		@Query nvarchar(max),
		@ColumnsInSelect nvarchar(max),
		@CultureNo CHAR(1)
	
	set @UserCulture = CFG.GetuserCulture();

	select @CultureNo = CultureNo
	from CFG.CultureInfo 
	where Culture = @UserCulture

	select @Working =LV.Value
	from cfg.LocalizeEnum L
	join cfg.LocalizeEnumValue LV on L.LocalizeEnumID = LV.LocalizeEnumID
	where L.Enum = 'AssetusageStatus'
	and L.Item = 'Working'
	and LV.Culture = @UserCulture

	select @Unused = LV.Value
	from cfg.LocalizeEnum L
	join cfg.LocalizeEnumValue LV on L.LocalizeEnumID = LV.LocalizeEnumID
	where L.Enum = 'AssetusageStatus'
	and L.Item = 'Unused'
	and LV.Culture = @UserCulture



	select @Columns = STUFF((SELECT DISTINCT ',' + QUOTENAME(DlTypeID) 
									FROM acc.UsedDlType  WHERE SaturnModuleID = 14
									FOR XML PATH(''), TYPE
								   ).value('.', 'NVARCHAR(MAX)'),1,1,'')
								   
	if(@Columns is null)
	set @Columns = '[-1]'
	
	select @ColumnsInSelect = STUFF((SELECT DISTINCT ' ,' +QUOTENAME(DlTypeID) +' as T' +cast(DlTypeID as nvarchar(150))
									FROM acc.UsedDlType  WHERE SaturnModuleID = 14
									FOR XML PATH(''), TYPE
								   ).value('.', 'NVARCHAR(MAX)'),1,1,'')
								   
	if(@ColumnsInSelect is null)
	set @ColumnsInSelect = ''

		declare @UserID VARCHAR(50),
			@DateType TINYINT,
			@DateFormat VARCHAR(50)

	SET  @UserID=cfg.GetuserID()

	SELECT @DateType = us.SettingValue
	FROM   cfg.UserSetting us
	WHERE  us.SettingKey = 'Date_Type'
	       AND us.UserID = @UserID
	
	IF @DateType IS NULL
	SET @DateType = CASE cfg.GetuserCulture() WHEN 'fa' THEN 0	
											  WHEN 'en' THEN 1
											  WHEN 'ar' THEN 2 END
	
	
	SELECT @DateFormat = us.SettingValue
	FROM   cfg.UserSetting us
	WHERE  us.SettingKey = 'Date_Format'
	       AND us.UserID =  @UserID	

   	SELECT * INTO #vwBranchAccess
	  FROM cfg.vwBranchAccess AS vba

	IF @DateFormat IS NULL
		SET @DATEFORMAT = 'YY/MM/DD' 
		
	SET @Query = N'SELECT 
						d.DepreciationID,
						d.AssetID,
						d.AssetSettingID,
						d.Value,
						d.DepreciationType,
						d.VoucherID,
						d.Version,
						d.Creator,
						d.LastEditor,
						d.CreationDate,
						d.LastEditionDate,
						d.AdjustmentItemID,
						d.RepairID,
						d.RevaluationItemID,
						d.Date,
						d.IsAutoGenerated,
						CFG.GetCLRSaturnDate(d.Date, @DateFormat , 0, @DateType ) AS Date_Date,
								isnull(ac.ParentCode,'''')+ac.Code AssetCategoryCode,
							   case @CultureNo 
								 when 1 then ac.Title
								 when 2 then ac.Title2
							   end as AssetCategoryTitle
						into #Depreciation
					FROM  AST.Depreciation as d
						join AST.Asset as a on a.AssetID=d.AssetID
						join AST.AssetCategory as ac on ac.AssetCategoryID=a.AssetCategoryID
					WHERE FinancialPeriodID = @FinancialPeriodID

					SELECT voucherid,
						CFG.GetCLRSaturnDate(Date, @DateFormat , 0, @DateType) AS VoucherDate,
						ReferenceNumber as VoucherNumber
						into #voucher
					FROM acc.voucher where FinancialPeriodID = @FinancialPeriodID

					SELECT d.DepreciationID,a.Plaque,
						   case @CultureNo
							 when 1 then a.Title
							 when 2 then a.Title2
						   end as Title,
						   b.Code as BranchCode,
						   case @CultureNo
							 when 1 then b.Title
							 when 2 then b.Title2
						   end as BranchTitle'+@ColumnsInSelect+'
						,case when ass.Status = 1 then @Working
							 when ass.Status = 2 then @Unused end AssetStatus,
						d.value,
						d.VoucherID,
						v.VoucherNumber,
						v.VoucherDate,
						d.Date,
						d.Date_Date,
						d.AssetCategoryCode,
						d.AssetCategoryTitle,
						case when d.DepreciationType = 1 then N''عادی''
							 when d.DepreciationType = 2 then N''تعمیر''
							 when d.DepreciationType = 3 then N''تغییر بهاء''
							 when d.DepreciationType = 4 then N''مازاد ناشی از تجدید ارزیابی'' end DepreciationType,
						d.IsAutoGenerated,
						CFG.GetCLRSaturnDate(d.CreationDate, @DateFormat  , 1, @DateType) AS CreateDateString, 
						CFG.GetCLRSaturnDate(d.LastEditionDate, @DateFormat , 1, @DateType) AS EditionDateString, 				
						u.Name AS CreatorUserName, 
						u2.Name AS EditorName
					from #Depreciation d
						JOIN CFG.[User] AS u ON u.UserID = d.Creator 
						JOIN CFG.[User] AS u2 ON u2.UserID = d.LastEditor
						JOIN AST.AssetSetting ass on d.AssetSettingID = ass.AssetSettingID
						JOIN AST.Asset a on a.AssetID = ass.AssetID
						INNER JOIN #vwBranchAccess vba on a.BranchID=vba.BranchID
						JOIN CFG.Branch b on b.BranchID = a.BranchID
						LEFT JOIN 
						(
							select AssetSettingID,asd.DlTypeID,
							case @CultureNo
								 when 1 then d.Title
								 when 2 then d.Title2
							end as Title 
							from ast.AssetSettingDl asd
							JOIN acc.Dl d ON asd.DlID = d.DLID 
						)x pivot
						(
							max(Title)
							for DlTypeID in ('+@Columns+')
						) p on p.AssetSettingID = d.AssetSettingID 
						LEFT JOIN #voucher v on v.voucherid = d.voucherid
'

EXEC sp_executesql @Query, N'@DateType TINYINT,
							@DateFormat VARCHAR(50),
							@Working nvarchar(150),
							@Unused nvarchar(150),
							@FinancialPeriodID int,
							@CultureNo CHAR(1)',
							@CultureNo = @CultureNo,
							@DateType = @DateType,
							@DateFormat = @DateFormat,
							@Working = @Working,
							@Unused  = @Unused,
							@FinancialPeriodID = @FinancialPeriodID
