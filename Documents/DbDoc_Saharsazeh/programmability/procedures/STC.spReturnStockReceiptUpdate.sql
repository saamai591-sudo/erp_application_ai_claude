CREATE   PROC [STC].[spReturnStockReceiptUpdate]
    @ReturnStockReceiptID INT ,
    @AutoGenerated BIT ,
    @StockDocumentTypeBaseEntityID INT ,
    @StockID INT ,
    @DeliverDlID BIGINT ,
    @DeliverStockID INT ,
    @Number INT ,
    @Date DATE ,
    @TotalInvoicePrice DECIMAL(30, 4) ,
    @PreVoucherID INT ,
    @Version INT ,
    @Creator INT ,
    @CreationDate DATETIME ,
    @LastEditor INT ,
    @LastEditionDate DATETIME ,
    @FinancialPeriodID INT 
--WITH ENCRYPTION 
AS
    SET NOCOUNT ON;

    DECLARE @PrePrevoucher INT ,
            @Preversion INT;

    SELECT @Preversion = [Version] ,
           @PrePrevoucher = PreVoucherID
    FROM   [STC].[ReturnStockReceipt]
    WHERE  [ReturnStockReceiptID] = @ReturnStockReceiptID;

    IF @Version <> @Preversion
       OR @PrePrevoucher IS NOT NULL
        RAISERROR('Version mismatch...', 16, 10);
    BEGIN

        DECLARE @StartNum INT = NULL ,
                @EndNum INT = NULL ,
                @Stock BIT = 0 ,
                @ResetType BIT = 0 ,
				@StockDocumentTypeID INT,
                @DocumentNumID INT ,
                @DocumentNumTypeID INT ,
                @Message NVARCHAR(MAX);

        SELECT @DocumentNumTypeID = DocumentNumTypeID
        FROM   [CFG].[DocumentNumType]
        WHERE  EngName = 'ReturnStockReceipt';

		SELECT @StockDocumentTypeID = StockDocumentTypeID
		FROM stc.StockDocumentTypeBaseEntity sdtb
		where sdtb.StockDocumentTypeBaseEntityID = @StockDocumentTypeBaseEntityID

        SELECT @StartNum = StartNum ,
               @EndNum = EndNum ,
               @DocumentNumID = DocumentNumID
        FROM   CFG.DocumentNum
        WHERE  DocumentNumTypeID = @DocumentNumTypeID
               AND FinancialPeriodID = @FinancialPeriodID;

        IF EXISTS (   SELECT 1
                      FROM   CFG.DocumentNumResetNumberBase
                      WHERE  DocumentNumID = @DocumentNumID
                             AND DocumentNumResetNumberBaseTypeID = 3 )
            BEGIN
                SET @Stock = 1;
            END;

        IF EXISTS (   SELECT 1
                      FROM   CFG.DocumentNumResetNumberBase
                      WHERE  DocumentNumID = @DocumentNumID
                             AND DocumentNumResetNumberBaseTypeID = 2 )
            BEGIN
                SET @ResetType = 1;
            END;

        IF (   @Number = 0
               OR @Number IS NULL )
            BEGIN
                SET @Number = ISNULL(
                              (   SELECT MAX(Number) + 1
                                  FROM   [STC].[ReturnStockReceipt] rsr
								   JOIN [STC].[StockDocumentTypeBaseEntity] sdtb
                                        ON rsr.StockDocumentTypeBaseEntityID = sdtb.StockDocumentTypeBaseEntityID
                                  WHERE  FinancialPeriodID = @FinancialPeriodID
                                         AND (   @Stock = 0
                                                 OR StockID = @StockID )
                                         AND (   @ResetType = 0
                                                 OR sdtb.StockDocumentTypeID = @StockDocumentTypeID )) ,
                              @StartNum);
            END;
        ELSE
            BEGIN
                IF ( EXISTS (   SELECT *
                                FROM   [STC].[ReturnStockReceipt] rsr
								JOIN [STC].[StockDocumentTypeBaseEntity] sdtb
                                    ON rsr.StockDocumentTypeBaseEntityID = sdtb.StockDocumentTypeBaseEntityID
                                WHERE  ReturnStockReceiptID <> @ReturnStockReceiptID
                                       AND FinancialPeriodID = @FinancialPeriodID
                                       AND (   @Stock = 0
                                               OR StockID = @StockID )
                                       AND (   @ResetType = 0
                                               OR sdtb.StockDocumentTypeID = @StockDocumentTypeID )
                                       AND Number = @Number ))
                    BEGIN
                        SELECT @Message ='NumberIsDuplicate'
                        RAISERROR(@Message, 16, 12);
                    END;
            END;

        IF (   @Number >= @StartNum
               AND (   @EndNum IS NULL
                       OR @Number <= @EndNum ))
            BEGIN

                UPDATE [STC].[ReturnStockReceipt]
                SET    [AutoGenerated] = @AutoGenerated ,
                       StockDocumentTypeBaseEntityID = @StockDocumentTypeBaseEntityID ,
                       [StockID] = @StockID ,
                       [DeliverDlID] = @DeliverDlID ,
                       [DeliverStockID] = @DeliverStockID ,
                       [Number] = @Number ,
                       [Date] = @Date ,
                       [TotalInvoicePrice] = @TotalInvoicePrice ,
                       [Version] = @Version + 1 ,
                       [LastEditor] = @LastEditor ,
                       [LastEditionDate] = @LastEditionDate
                WHERE  [ReturnStockReceiptID] = @ReturnStockReceiptID;

                -- Begin Return Select <- do not remove
                SELECT [Version]  ,
                       [Number]
                FROM   [STC].[ReturnStockReceipt]
                WHERE  [ReturnStockReceiptID] = @ReturnStockReceiptID;
            -- End Return Select <- do not remove
            END;
        ELSE
            BEGIN
                SELECT @Message =  'InvalidNumberRange'
                RAISERROR(@Message, 16, 12);
            END;
    END;
