CREATE   PROC [ACC].[spVoucherInsert]
    @BranchID INT ,
    @FinancialPeriodID INT ,
    @DocumentTypeID SMALLINT ,
    @Number INT ,
    @ReferenceNumber INT ,
    @DailyNumber INT ,
    @SubNumber NVARCHAR(256) ,
    @Date DATE ,
    @VoucherStatusID SMALLINT ,
    @Description NVARCHAR(MAX) ,
    @Description2 NVARCHAR(MAX) ,
    @Total DECIMAL(36, 10),
    @AutoGenerated bit,
    @Creator INT ,
    @CreationDate DATETIME
--WITH ENCRYPTION 
AS
BEGIN

    SET NOCOUNT ON;
    SET XACT_ABORT ON;

    DECLARE @StartNum INT = NULL,
            @EndNum INT = NULL,
            @CompanyId INT;

    SELECT @CompanyId = b.CompanyID
    FROM CFG.Branch AS b
    WHERE b.BranchID = @BranchID;


    SELECT @StartNum = StartNum,
           @EndNum = EndNum
    FROM CFG.DocumentNum
    WHERE DocumentNumTypeID = 1
          AND FinancialPeriodID = @FinancialPeriodID;


    SET @ReferenceNumber = ISNULL(
                           (
                               SELECT MAX(v.ReferenceNumber) + 1
                               FROM [ACC].[Voucher] v
                                   JOIN CFG.Branch AS b
                                       ON b.BranchID = v.BranchID
                               WHERE v.FinancialPeriodID = @FinancialPeriodID
                                     AND b.CompanyID = @CompanyId
                           ),
                           1
                                 );

    SET @DailyNumber = ISNULL(
                       (
                           SELECT MAX(v.DailyNumber) + 1
                           FROM [ACC].[Voucher] v
                               JOIN CFG.Branch AS b
                                   ON b.BranchID = v.BranchID
                           WHERE v.Date = @Date
                                 AND b.CompanyID = @CompanyId
                       ),
                       1
                             );

    IF (@Number = 0 OR @Number IS NULL)
        SET @Number = ISNULL(
                      (
                          SELECT MAX(v.Number) + 1
                          FROM [ACC].[Voucher] v
                              JOIN CFG.Branch AS b
                                  ON b.BranchID = v.BranchID
                          WHERE v.FinancialPeriodID = @FinancialPeriodID
                                AND b.CompanyID = @CompanyId
                      ),
                      @StartNum
                            );


    IF EXISTS
    (
        SELECT 1
        FROM [ACC].[Voucher] v
            JOIN CFG.Branch AS b
                ON b.BranchID = v.BranchID
        WHERE v.Number = @Number
              AND v.FinancialPeriodID = @FinancialPeriodID
              AND b.CompanyID = @CompanyId
    )
    BEGIN
        RAISERROR(N'Accounting.DuplicateVoucherNumber', 16, 12);
    END;

    DECLARE @Reviewer INT = NULL;
    IF (@VoucherStatusID = 3)
    BEGIN
        SET @Reviewer = CFG.GetuserID();
    END;

    IF (@Number >= @StartNum AND (@EndNum IS NULL OR @Number <= @EndNum))
    BEGIN
        INSERT INTO [ACC].[Voucher]
        (
            [BranchID],
            [FinancialPeriodID],
            [DocumentTypeID],
            [Number],
            [ReferenceNumber],
            [DailyNumber],
            [SubNumber],
            [Date],
            [VoucherStatusID],
            [Description],
            [Description2],
            Total,
            Reviewer,
            [Creator],
            [CreationDate],
            [LastEditor],
            [LastEditionDate],
            [Version],
            [AutoGenerated]
        )
        SELECT @BranchID,
               @FinancialPeriodID,
               @DocumentTypeID,
               @Number,
               @ReferenceNumber,
               @DailyNumber,
               @SubNumber,
               @Date,
               @VoucherStatusID,
               @Description,
               @Description2,
               @Total,
               @Reviewer,
               @Creator,
               @CreationDate,
               @Creator,
               @CreationDate,
               0,
               @AutoGenerated;

        -- Begin Return Select <- do not remove
        SELECT [VoucherID],
               [Version],
               [Number],
               [ReferenceNumber],
               [DailyNumber],
               [Reviewer]
        FROM [ACC].[Voucher]
        WHERE [VoucherID] = SCOPE_IDENTITY();
        -- End Return Select <- do not remove
    END;
    ELSE
    BEGIN
        RAISERROR('InvalidNumberRange', 16, 12);
    END;

END;
