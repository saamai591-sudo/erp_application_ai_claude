CREATE   PROCEDURE AST.DeleteCalculatedInsurances
	@ids VARCHAR(MAX) = Null,
	@AssetIDs NVARCHAR(MAX) = Null,
	@SelectedDate DATE = null,
	@SkipAutoGeneratedCheck BIT = 0,
	@Subject TinyInt = 1
	 
	 --WITH ENCRYPTION
AS
	CREATE TABLE #Value
	(
		InsuranceSharingID INT
	)
	
	IF @ids is NOT NULL
	BEGIN
	    INSERT INTO #Value(InsuranceSharingID)
	    SELECT VALUE
	    FROM   [CFG].[R_FnCommaStr2Table](@ids)
	END
	
	IF @AssetIDs is NOT NULL
	BEGIN
	    SELECT VALUE AssetID
	    INTO   #Assets
	    FROM   [CFG].[R_FnCommaStr2Table](@AssetIDs)
	    
	    
	    INSERT INTO #Value(InsuranceSharingID)
	    SELECT is1.InsuranceSharingID
	    FROM   ast.InsuranceSharing   AS is1
	           JOIN ast.AssetSetting  AS as1
	                ON  as1.AssetSettingID = is1.AssetSettingID
	           JOIN #Assets           AS a2
	                ON  as1.AssetID = a2.AssetID
	    WHERE  is1.[Date] = @SelectedDate and is1.IsAutoGenerated = 1
	END
	
	DECLARE @AssetSettingID     INT,
	        @date               DATE,
	        @Plaque             VARCHAR(MAX),
	        @Message            NVARCHAR(MAX) 
	
	DECLARE db_cursor CURSOR 
	FOR
	    SELECT AssetSettingID,
	           DATE
	    FROM   ast.InsuranceSharing
	    WHERE  InsuranceSharingID IN (SELECT InsuranceSharingID
	                                  FROM   #value)
	
	OPEN db_cursor 
	FETCH NEXT FROM db_cursor INTO @AssetSettingID,@date
	
	WHILE @@FETCH_STATUS = 0
	BEGIN
	    IF @SkipAutoGeneratedCheck = 0 AND EXISTS (
               SELECT 1
               FROM   ast.InsuranceSharing AS d
                      JOIN #value b ON d.InsuranceSharingID = b.InsuranceSharingID
               WHERE  d.IsAutoGenerated = 1
                      AND ISNULL(@subject,1) = 1
           )
        BEGIN
            SET @Message = 'StockManager.Messages.SomeSelectedRowsAreAutoGeneratedAndCannotBeDeleted'
            RAISERROR(@Message, 16, 10)
            RETURN
        END
	    
	    SELECT @Plaque = a.Plaque
	    FROM   ast.InsuranceSharing d
	           JOIN ast.AssetSetting ass
	                ON  d.AssetSettingID = ass.AssetSettingID
	           JOIN ast.Asset a
	                ON  a.AssetID = ass.AssetID
	    WHERE  d.AssetSettingID = @AssetSettingID
	           AND d.date > @date
	           AND InsuranceSharingID NOT IN (SELECT InsuranceSharingID
	                                          FROM   #value)
	    
	    IF @Plaque is NOT null
	    BEGIN
	        SET @Message = ISNULL(@Message, '') + ',' + @Plaque
	    END
	    
	    FETCH NEXT FROM db_cursor INTO @AssetSettingID,
	       @date
	
	END 
	
	CLOSE db_cursor 
	DEALLOCATE db_cursor
	
	IF @Message is NOT null
	BEGIN
	    SET @Message = right(@Message, LEN(@Message) -1)
	    SET @Message = 'E_' + 
	        'پلاکهای زیر در تاریخهای بعدی دارای هزینه بیمه هستند. حذف هزینه را از آخرین تاریخ انجام دهید.'
	        + CHAR(13) + @Message
	    
	    RAISERROR(@Message, 16, 10)
	    return
	END
	
	IF EXISTS (
	       SELECT *
	       FROM   ast.AssetClosingOperation
	       WHERE  FinancialPeriodID IN (SELECT distinct FinancialPeriodID
	                                    FROM   ast.InsuranceSharing
	                                    WHERE  InsuranceSharingID IN (SELECT InsuranceSharingID
	                                                                  FROM   #value))
	   )
	BEGIN
	    SET @Message = 'به دلیل بسته بودن سیستم دارایی ثابت، انجام این عملیات مجاز نیست.'
	    RAISERROR(@Message, 16, 10)
	    return
	END
	
	
	DELETE 
	FROM   ast.InsuranceSharing
	WHERE  InsuranceSharingID IN (SELECT InsuranceSharingID
	                              FROM   #value)
