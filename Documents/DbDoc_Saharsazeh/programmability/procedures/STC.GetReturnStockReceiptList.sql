
------------------------------[STC].GetReturnStockReceiptList----------------------------------------------------------------------------------------------
CREATE   PROC [STC].[GetReturnStockReceiptList]
(
    @FinancialPeriodID INT,
    @dateFormat NVARCHAR(20),
    @dateType INT,   
    @IsAmount BIT,
    @PageNumber INT,
    @RowspPage INT,
    @Sort NVARCHAR(MAX) = NULL,
    @Filter NVARCHAR(MAX) = NULL
)
AS
BEGIN
   DECLARE @UserID INT,
			@cultureNo INT,
			@Culture NVARCHAR(10),
            @ViewRelatedToUser INT,
            @ViewRelatedToOthers NVARCHAR(MAX),
            @UnauthorizedUsers NVARCHAR(MAX),
            @entityName NVARCHAR(100) = N'ReturnQuantityReceipt',
			@WithOutbase NVARCHAR(100),
			@StockReceipt NVARCHAR(100),
			@ReturnRequest NVARCHAR(100),
			@Voucher NVARCHAR(100),
			@PreVoucher NVARCHAR(100),
			@Submit NVARCHAR(100);

	SET @Culture = CFG.GetuserCulture();

	SELECT @WithOutbase = LV.Value
	FROM   CFG.LocalizeEnum L
		   JOIN CFG.LocalizeEnumValue LV
				ON  L.LocalizeEnumID = LV.LocalizeEnumID
	WHERE  L.Enum = 'ReturnReceiptBaseType'
		   AND L.Item = 'WithOutbase'
		   AND LV.Culture = @Culture;

	SELECT @StockReceipt = LV.Value
	FROM   CFG.LocalizeEnum L
		   JOIN CFG.LocalizeEnumValue LV
				ON  L.LocalizeEnumID = LV.LocalizeEnumID
	WHERE  L.Enum = 'ReturnReceiptBaseType'
		   AND L.Item = 'StockReceipt'
		   AND LV.Culture = @Culture;

	SELECT @ReturnRequest = LV.Value
	FROM   CFG.LocalizeEnum L
		   JOIN CFG.LocalizeEnumValue LV
				ON  L.LocalizeEnumID = LV.LocalizeEnumID
	WHERE  L.Enum = 'ReturnReceiptBaseType'
		   AND L.Item = 'ReturnRequest'
		   AND LV.Culture = @Culture;

	SELECT @Submit = LV.Value
	FROM   CFG.LocalizeEnum L
	       JOIN CFG.LocalizeEnumValue LV
	            ON  L.LocalizeEnumID = LV.LocalizeEnumID
	WHERE  L.Enum = 'Statuses'
	       AND L.Item = 'Submit'
	       AND LV.Culture = @Culture;
	
	SELECT @Voucher = LV.Value
	FROM   CFG.LocalizeEnum L
	       JOIN CFG.LocalizeEnumValue LV
	            ON  L.LocalizeEnumID = LV.LocalizeEnumID
	WHERE  L.Enum = 'PreVoucherStatuses'
	       AND L.Item = 'Voucher'
	       AND LV.Culture = @Culture;
	
	SELECT @PreVoucher = LV.Value
	FROM   CFG.LocalizeEnum L
	       JOIN CFG.LocalizeEnumValue LV
	            ON  L.LocalizeEnumID = LV.LocalizeEnumID
	WHERE  L.Enum = 'PreVoucherStatuses'
	       AND L.Item = 'PreVoucher'
	       AND LV.Culture = @Culture;

	SELECT @CultureNo = CultureNo
	FROM CFG.CultureInfo
	WHERE Culture = @Culture;

    IF @IsAmount = 1
    BEGIN
        SET @entityName = N'ReturnAmountReceipt';
    END;

    SET @UserID = CFG.GetuserID();

    SELECT @ViewRelatedToUser = UserID
    FROM CFG.vwOperationLevelAccess
    WHERE EntityName = @entityName
          AND AccessKey = 'ViewRelatedToUser'
          AND UserID = @UserID;

    SELECT @ViewRelatedToOthers = UserID,
           @UnauthorizedUsers = Users
    FROM CFG.vwOperationLevelAccess
    WHERE EntityName = @entityName
          AND AccessKey = 'ViewRelatedToOthers'
          AND UserID = @UserID;

    IF @Sort IS NULL
       OR @Sort = ''
        SET @Sort = N'Number desc ';

    DECLARE @Query NVARCHAR(MAX);

    SET @Query
        = N' SELECT vsa.StockID    INTO #stockAccess    FROM CFG.vwStockAccess AS vsa;
			SELECT vsda.StockDocumentTypeID     INTO #vwStockDocumentsAccess    FROM CFG.vwStockDocumentsAccess AS vsda;

    ;WITH Query_Result (ReturnStockReceiptID, 
						AutoGenerated, 
						StockDocumentTypeBaseEntityID,
						TypeString,
						StockID,  
						StockID_Original, 
						StockCode, 
						StockTitle, 
						DeliverDlID, 
						DeliverStockID, 
						DeliverCode,
                        DeliverTitle, 
						Number, 
						[Date],
						Date_Original, 
						Date_Date,
						BaseEntity, 
						TotalInvoicePrice,
						PreVoucherID, 
						[Version], 
						Creator, 
						CreationDate,
						CreateDateString,
						LastEditionDate,
                        EditionDateString, 
						FinancialPeriodID, 
						VoucherID, 
						VoucherNumber,
						VoucherDate,
						Date_VoucherDate,
						CreatorUserName,
						EditorName,
						StockIsInRecounting,
						BaseEntityTitle,
						StockDocumentTypeTitle,
						StateString)
							AS (SELECT rsr.ReturnStockReceiptID,
							   rsr.AutoGenerated,
							   rsr.StockDocumentTypeBaseEntityID,
							   CASE @cultureNo
								   WHEN 2 THEN
									   sdt.Title2
								   ELSE
									   sdt.Title
							   END AS TypeString,
							   rsr.StockID,
							   rsr.StockID AS StockID_Original,
							   s.Code AS StockCode,
							   CASE @cultureNo
								   WHEN 2 THEN
									   s.Title2
								   ELSE
									   s.Title
							   END AS StockTitle,
							   rsr.DeliverDlID,
							   rsr.DeliverStockID,
							   CASE
								   WHEN rsr.DeliverStockID IS NOT NULL THEN
									   CAST(ds.Code AS NVARCHAR(500))
								   ELSE
									   d.Code
							   END AS DeliverCode,
							   CASE @cultureNo
								   WHEN 2 THEN
									   CASE
										   WHEN rsr.DeliverStockID IS NOT NULL THEN
											   ds.Title2
										   ELSE
											   d.Title2
									   END
								   ELSE
									   CASE
										   WHEN rsr.DeliverStockID IS NOT NULL THEN
											   ds.Title
										   ELSE
											   d.Title
									   END
							   END AS DeliverTitle,
							   rsr.Number,
							   rsr.[Date],
							   rsr.[Date] AS Date_Original,
							   CFG.GetCLRSaturnDate(rsr.[Date], @dateFormat, 0, @dateType) AS Date_Date,
							   sdtb.BaseEntity,
							   rsr.TotalInvoicePrice,
							   rsr.PreVoucherID,
							   rsr.[Version],
							   rsr.Creator,
							   rsr.CreationDate,
							   CFG.GetCLRSaturnDate(rsr.CreationDate, @dateFormat, 1, @dateType) AS CreateDateString,
							   rsr.LastEditionDate,
							   CFG.GetCLRSaturnDate(rsr.LastEditionDate, @dateFormat, 1, @dateType) AS EditionDateString,
							   rsr.FinancialPeriodID,
							   p.VoucherID,
							   v.Number AS VoucherNumber,
							   v.[Date] AS VoucherDate,
							   cfg.GetClrSaturnDate(v.[Date],@dateFormat,0,@dateType) AS Date_VoucherDate,
							   u.[Name] AS CreatorUserName,
							   lu.[Name] AS EditorName,
							   CAST(CASE
										WHEN rc.StockID IS NULL THEN
											1
										ELSE
											0
									END AS BIT) AS StockIsInRecounting,
								CASE sdtb.BaseEntity 
									WHEN 1 THEN @WithOutbase
									WHEN 14 THEN @StockReceipt
									WHEN 5 THEN @ReturnRequest
								END AS BaseEntityTitle,
								case @cultureNo
									when 1 then sdt.Title
									when 2 then sdt.Title2
								end as StockDocumentTypeTitle ,
								CASE 
									WHEN p.VoucherID IS NOT NULL THEN @Voucher
									WHEN rsr.PreVoucherID IS NOT NULL THEN @PreVoucher
									ELSE @Submit
								END AS StateString
				FROM STC.ReturnStockReceipt AS rsr
				JOIN [STC].[StockDocumentTypeBaseEntity] sdtb ON rsr.StockDocumentTypeBaseEntityID = sdtb.StockDocumentTypeBaseEntityID
				JOIN #stockAccess AS sa ON sa.StockID = rsr.StockID
				JOIN #vwStockDocumentsAccess AS vsda ON vsda.StockDocumentTypeID = sdtb.StockDocumentTypeID
				LEFT JOIN
				(   SELECT DISTINCT rip.StockID
					FROM STC.RecountingInventoryTag AS rit
						JOIN STC.RecountingInventoryTagItem AS riti ON riti.RecountingInventoryTagID = rit.RecountingInventoryTagID
						JOIN STC.RecountingInventoryPeriod AS rip ON rit.RecountingInventoryPeriodID = rip.RecountingInventoryPeriodID
					WHERE rit.Status <> -1
				) rc ON rc.StockID = rsr.StockID
				JOIN CFG.[User] AS u ON u.UserID = rsr.Creator
				JOIN CFG.[User] AS lu ON lu.UserID = rsr.LastEditor
				JOIN STC.StockDocumentType AS sdt ON sdt.StockDocumentTypeID = sdtb.StockDocumentTypeID
				LEFT JOIN STF.Stock AS ds ON ds.StockID = rsr.DeliverStockID
				LEFT JOIN ACC.DL AS d ON d.DLID = rsr.DeliverDlID
				JOIN STF.Stock AS s ON s.StockID = rsr.StockID
				LEFT JOIN
				( SELECT DISTINCT pv.PreVoucherID, vp.VoucherID
					FROM ACC.PreVoucher AS pv
						JOIN ACC.VoucherPrevoucher AS vp ON vp.PrevoucherID = pv.PreVoucherID
				) AS p ON p.PreVoucherID = rsr.PreVoucherID
				LEFT JOIN ACC.Voucher AS v ON v.VoucherID = p.VoucherID
			WHERE rsr.FinancialPeriodID = @FinancialPeriodID
					AND ( @UserID = -1
						OR ( @ViewRelatedToUser IS NOT NULL AND rsr.Creator = @UserID )
						OR
						( @ViewRelatedToOthers IS NOT NULL AND rsr.creator not in ( SELECT rfcst.value FROM CFG.R_FnCommaStr2Table(@UnauthorizedUsers) AS rfcst WHERE rfcst.value = rsr.Creator ) 
			)
		))';

    IF @Filter IS NULL
       OR @Filter = ''
        SET @Filter = '';
    ELSE
        SET @Filter = N'Where (' + @Filter + N')';

    DECLARE @tableName NVARCHAR(100);
    SET @tableName = CFG.getTempTableName(1);

    SET @Query = CFG.ApplyPaging(@tableName, @Query, @PageNumber, @RowspPage, @Filter, @Sort);
	
	--PRINT @Query
    EXECUTE sys.sp_executesql @Query,
                              N'@dateFormat NVARCHAR(10), 
								@cultureNo INT,
								@dateType int,
								@ViewRelatedToOthers NVARCHAR(MAX),
								@UnauthorizedUsers	  NVARCHAR(MAX),
								@FinancialPeriodID int,
								@UserID int,
								@ViewRelatedToUser int	,
								@WithOutbase NVARCHAR(100),
								@StockReceipt NVARCHAR(100),
								@ReturnRequest NVARCHAR(100),
								@Voucher NVARCHAR(100),
								@PreVoucher NVARCHAR(100),
								@Submit NVARCHAR(100)
								   ',
                              @FinancialPeriodID = @FinancialPeriodID,
                              @dateType = @dateType,
                              @dateFormat = @dateFormat,
                              @ViewRelatedToUser = @ViewRelatedToUser,
                              @ViewRelatedToOthers = @ViewRelatedToOthers,
                              @UnauthorizedUsers = @UnauthorizedUsers,
                              @UserID = @UserID,
                              @cultureNo = @cultureNo,
							  @WithOutbase = @WithOutbase,
							  @StockReceipt = @StockReceipt,
							  @ReturnRequest = @ReturnRequest,
							  @Voucher = @Voucher,
							  @PreVoucher = @PreVoucher,
							  @Submit = @Submit

    DECLARE @Count INT;

    EXEC (N'select * from ' + @tableName + N' ORDER BY _RN');

    SET @Query = N'select top 1 @Count=  r_count from ' + @tableName;
    EXECUTE sys.sp_executesql @Query, N'@count int out', @Count = @Count OUT;

    RETURN ISNULL(@Count, 0);
END;
