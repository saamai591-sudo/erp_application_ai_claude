CREATE   PROC STC.spStockReceiptUndoPricing
(@stockReceiptItemIds ArrayInput READONLY)
AS
BEGIN
    -- update items fee and price
    UPDATE sri
    SET sri.Fee = 0,
        sri.Price = 0
    FROM STC.StockReceiptItem AS sri
        JOIN @stockReceiptItemIds AS srii
            ON srii.Val = sri.StockReceiptItemID;

    -- update header total data
    UPDATE sr
    SET sr.TotalCosts =
        (
            SELECT SUM(ShareOfCosts)
            FROM STC.StockReceiptItem
            WHERE StockReceiptID = sr.StockReceiptID
        ),
        sr.TotalInvoicePrice =
        (
            SELECT SUM(Price)
            FROM STC.StockReceiptItem
            WHERE StockReceiptID = sr.StockReceiptID
        ),
        sr.TotalNetPrice =
        (
            SELECT SUM(NetPrice)
            FROM STC.StockReceiptItem
            WHERE StockReceiptID = sr.StockReceiptID
        ),
        sr.TotalEstimatedPrice =
        (
            SELECT SUM(EstimatedPrice)
            FROM STC.StockReceiptItem
            WHERE StockReceiptID = sr.StockReceiptID
        )
    FROM STC.StockReceipt AS sr
        JOIN
        (
            SELECT DISTINCT
                   sri.StockReceiptID
            FROM @stockReceiptItemIds AS itc
                JOIN STC.StockReceiptItem AS sri
                    ON sri.StockReceiptItemID = itc.Val
        ) items
            ON sr.StockReceiptID = items.StockReceiptID;

    -- remove revision costs
    DELETE rc
    FROM STC.RevisionCost AS rc
    JOIN STC.RevisionCostItem AS rci
        ON rci.RevisionCostID = rc.RevisionCostID
    JOIN @stockReceiptItemIds AS sri
        ON sri.Val = rci.StockReceiptItemID
    WHERE AutoGenerated = 1
	AND ISNULL([AutoGenerateType],0) = 2
END;
