CREATE PROC [STC].[spRevisionCostInsert] 
    @Number int,
    @Date datetime,
    @AutoGenerated bit,
    @PreVoucherID int,
    @FinancialPeriodID int,
    @Creator int,
    @CreationDate datetime,
    @LastEditor int,
    @LastEditionDate datetime,
    @Type TINYINT,
	@BranchID INT
--WITH ENCRYPTION 
AS 
begin 
	SET NOCOUNT ON 
	SET XACT_ABORT ON  
	
	
	SET @Number = ISNULL(
				(
					SELECT MAX(Number) + 1
					FROM   [STC].[RevisionCost]
					WHERE FinancialPeriodID = @FinancialPeriodID
				),
				1
			)
	
	INSERT INTO [STC].[RevisionCost] ([Number], [Date], [AutoGenerated], [PreVoucherID], [FinancialPeriodID], [Version], [Creator], [CreationDate], [LastEditor], [LastEditionDate], [Type],[BranchID])
	SELECT @Number, @Date, @AutoGenerated, @PreVoucherID, @FinancialPeriodID, 0, @Creator, @CreationDate, @LastEditor, @LastEditionDate, @Type,@BranchID
	
	-- Begin Return Select <- do not remove
	SELECT [RevisionCostID], 
			[Version], 
			[Number]
	FROM   [STC].[RevisionCost]
	WHERE  [RevisionCostID] = SCOPE_IDENTITY()
	-- End Return Select <- do not remove
END
