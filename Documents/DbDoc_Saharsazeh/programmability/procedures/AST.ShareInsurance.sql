
-------------------------------------
CREATE   PROCEDURE [AST].[ShareInsurance]
@FinancialPeriod int,
@Date Date,
@AssetsSettingIDs varchar(max),
@AutoGenerated BIT = 0

--WITH ENCRYPTION 
	 AS 
BEGIN
	
	if exists (
		select * from ast.AssetClosingOperation 
		where FinancialPeriodID = @FinancialPeriod
		)	
		begin
			RAISERROR('به دلیل بسته بودن سیستم دارایی ثابت، انجام این عملیات مجاز نیست.', 16, 10)
			return
			end

	declare @financialperiodDuration smallint,
		    @PrecisionDigit tinyint,
			@Plaque varchar(max),
			@Message nvarchar(max),
			@StartDate date


	set @PrecisionDigit = cfg.GetBaseCurrencyPrecision()
	
		SELECT VALUE into #AssetsSettingIDs FROM   CFG.R_FnCommaStr2Table(@AssetsSettingIDs)

	if exists (SELECT [InsuranceSharingID] from ast.[InsuranceSharing] where Date >= @Date)
	begin
	select @Plaque = STUFF((SELECT  DISTINCT Top 10 ' ,' + a.Plaque 		
					from ast.[InsuranceSharing] T
					join ast.AssetSetting ass on ass.AssetSettingID = T.AssetSettingID
					join ast.Asset a on a.AssetID = ass.AssetID
					join #AssetsSettingIDs id on id.value = T.AssetSettingID
					where T.Date >= @Date
			FOR XML PATH(''), TYPE
			).value('.', 'NVARCHAR(MAX)'),1,1,'')

	

		if @Plaque is not null
		 begin

		 set @Plaque = @Plaque + ', ...'
		 set @Message = 'E_' +'پلاکهای زیر قبلا در بزرگتر مساوی این تاریخ محاسبه هزینه شده اند.'+char(13)+@Plaque

		  RAISERROR(@Message, 16, 10)

	      RETURN

		 end

	end
		

	select  @financialperiodDuration = DateDiff(day,dateadd(day,-1,startdate),enddate),
	@StartDate = StartDate
	from cfg.financialperiod
	where FinancialPeriodID = @FinancialPeriod

	-- محاسبه
	update InsuranceSharing_Temp
	set  Insurance = case when enddate <= @Date
									then TotalShare - isnull((SELECT SUM([SharingValue])
																		FROM ast.InsuranceSharing
																		WHERE  InsuranceItemID = T.InsuranceItemID
																		) ,0) 
						  else
								round(TotalShare
								*
								([DateDiff] /DateDiff(day,dateadd(day,-1,FromDate),enddate) ) , @PrecisionDigit)
								-
								isnull((SELECT SUM([SharingValue])
								FROM ast.InsuranceSharing
								WHERE AssetSettingID = T.assetsettingid
								AND InsuranceItemID = T.InsuranceItemID
								AND FinancialPeriodID = @FinancialPeriod 
								) ,0) 
					end
	from ast.InsuranceSharing_Temp T
	join #AssetsSettingIDs a
		on t.AssetSettingID = a.value

	


	-- ذخيره نتايج در جدول
	DECLARE @CurrentDate DATETIME ,
			@CurrentUser INT
			
	SET @CurrentDate = GETDATE();
	SET @CurrentUser = CFG.GetuserID();
	
	

	INSERT INTO [AST].[InsuranceSharing]
           ([InsuranceItemID]
           ,[SharingValue]
           ,[AssetSettingID]
           ,[FinancialPeriodID]
		   ,[Date]
		   ,[IsAutoGenerated])
    SELECT 
			[InsuranceItemID]
           ,[Insurance]
           ,[AssetSettingID]
           ,@FinancialPeriod
		   ,@Date
		   ,@AutoGenerated
    FROM AST.InsuranceSharing_Temp dt
	join #AssetsSettingIDs a
		on dt.AssetSettingID = a.value
    where  dt.Insurance <> 0							 
     
	delete from ast.InsuranceSharing_Temp         
END
