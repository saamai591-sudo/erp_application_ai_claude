CREATE   PROCEDURE [AST].DoDepreciation
	@DepreciationPeriodID	INT = null,
	@BranchID				INT = null,
	@Subject				TINYINT = null,		-- 1: محاسبه دوره‌ای، 2: خروج، 3: اسقاط، 4: فروش، 5: ارسال به شعبه، 6: تغییر گروه، 7: تجدید ارزیابی
	@AutoGenerated			BIT = 0,
	@Document               NVARCHAR(250) = Null,
	@DocumentID             INT = Null,
	@FinancialPeriod        INT = null
--WITH ENCRYPTION
AS

SET NOCOUNT ON
SET XACT_ABORT ON

-- این رویه از چند جا فراخوانی می‌شود:
--   محاسبه دوره‌ای  : @DepreciationPeriodID پر است، تاریخ مبنا پایان دوره استهلاک است و برای همه داراییهای فعال شعبه محاسبه می‌شود
--   عملیات سند     : (خروج، اسقاط، فروش، ارسال به شعبه، تغییر گروه، تجدید ارزیابی) @FinancialPeriod و @DocumentID پر است، تاریخ مبنا تاریخ همان سند است
--                     و فقط برای داراییهای همان سند محاسبه و کنترل انجام می‌شود
-- در هر دو حالت، همه کنترل‌ها و محاسبات فقط روی داراییهایی است که ast.GetDepreciationInfo برگردانده است
BEGIN
	IF @DocumentID = 0
		SET @DocumentID = NULL

	DECLARE @Date                       DATE = NULL,
			@PeriodStartDate            DATE,
			@StartDate                  DATE,
			@EndDate                    DATE,
			@FinancialPeriodDuration    DECIMAL(30, 4),
			@PreFinancialPeriod         INT,
			@ErrorTable                 NVARCHAR(400),
			@DlTypeID                   INT,
			@DlTypeTitle                NVARCHAR(250),
			@Assets                     NVARCHAR(MAX),
			@Message                    NVARCHAR(MAX),
			@PrecisionDigit             TINYINT = cfg.GetBaseCurrencyPrecision(),
			@DepreciationCalculationID  INT,
			@CurrentDate                DATETIME = GETDATE(),
			@CurrentUser                INT = CFG.GetuserID()

	IF (@FinancialPeriod IS NULL)
		SELECT @FinancialPeriod = dp.FinancialPeriodID,
			   @Date            = dp.EndDate,
			   @PeriodStartDate = dp.StartDate
		FROM   ast.DepreciationPeriod AS dp
		WHERE  dp.DepreciationPeriodID = @DepreciationPeriodID

	SELECT @StartDate = StartDate,
		   @EndDate   = EndDate,
		   @FinancialPeriodDuration = DATEDIFF(DAY, StartDate, EndDate) + 1
	FROM   cfg.FinancialPeriod
	WHERE  FinancialPeriodID = @FinancialPeriod

	CREATE TABLE #Error ([Message] NVARCHAR(MAX), IsDetail BIT)


	-------------------------------------------------------------------------------
	-- کنترل‌هایی که فقط به پارامترها بستگی دارند
	-------------------------------------------------------------------------------
	IF EXISTS
	   (
		   SELECT 1
		   FROM   ast.DepreciationCalculation dc
		   WHERE  dc.DepreciationPeriodID = @DepreciationPeriodID
				  AND dc.BranchID = @BranchID
	   )
	BEGIN
		INSERT INTO #Error ([Message], IsDetail) VALUES (N'AssetManager.Messages.BranchHasCalculationInPeriod', 0)
		GOTO ReturnErrors
	END

	IF EXISTS
	   (
		   SELECT 1
		   FROM   ast.AssetClosingOperation a
		   WHERE  a.FinancialPeriodID = @FinancialPeriod
				  AND a.BranchID = @BranchID
	   )
	BEGIN
		INSERT INTO #Error ([Message], IsDetail) VALUES (N'AssetManager.Messages.BranchIsClosed', 0)
		GOTO ReturnErrors
	END

	IF @Document = 'DepreciationCalculation'
	   AND EXISTS
	   (
		   SELECT 1
		   FROM   ast.DepreciationPeriod AS dp
				  LEFT JOIN ast.DepreciationCalculation AS dc
					   ON  dc.DepreciationPeriodID = dp.DepreciationPeriodID
					   AND dc.BranchID = @BranchID
		   WHERE  dp.FinancialPeriodID = @FinancialPeriod
				  AND dp.StartDate < @PeriodStartDate
				  AND dc.DepreciationCalculationID IS NULL
	   )
	BEGIN
		INSERT INTO #Error ([Message], IsDetail) VALUES (N'AssetManager.Messages.PreviousPeriodNotCalculated', 0)
		GOTO ReturnErrors
	END
	-- Forms whose confirmation triggers a depreciation calculation must be confirmed (status 2) up to the calculation date
	IF @Document = 'DepreciationCalculation'
	BEGIN
		IF EXISTS (SELECT 1 FROM ast.Destruction WHERE BranchID = @BranchID AND [Date] <= @Date AND DestructionStatus <> 2)
			INSERT INTO #Error ([Message], IsDetail) VALUES (N'AssetManager.Messages.SomeDestructionAssetsNotConfirmed', 0)

		IF EXISTS (SELECT 1 FROM ast.Salvage WHERE BranchID = @BranchID AND [Date] <= @Date AND SalvageStatus <> 2)
			INSERT INTO #Error ([Message], IsDetail) VALUES (N'AssetManager.Messages.SomeSalvageAssetsNotConfirmed', 0)

		IF EXISTS (SELECT 1 FROM ast.Sale WHERE BranchID = @BranchID AND [Date] <= @Date AND SaleStatus <> 2)
			INSERT INTO #Error ([Message], IsDetail) VALUES (N'AssetManager.Messages.SomeSaleAssetsNotConfirmed', 0)

		IF EXISTS (SELECT 1 FROM ast.[Transfer] WHERE SourceBranchID = @BranchID AND [Date] <= @Date AND TransferStatus <> 2)
			INSERT INTO #Error ([Message], IsDetail) VALUES (N'AssetManager.Messages.SomeTransferAssetsNotConfirmed', 0)

		IF EXISTS (SELECT 1 FROM #Error)
			GOTO ReturnErrors
	END

	-------------------------------------------------------------------------------
	-- دریافت داراییها و بازه‌های محاسبه (فقط داراییهای همین محاسبه) و کنترل‌های مربوط به آن
	-------------------------------------------------------------------------------
	-- جدول موقت نتیجه محاسبه (توسط ast.GetDepreciationInfo پر می‌شود)
	-- Net = مبلغ قابل استهلاک، NetFormula = متن فرمول آن
	CREATE TABLE #Depreciation_Temp
	(
		ID                      INT IDENTITY(1, 1) PRIMARY KEY,
		AssetID                 INT,
		Plaque                  NVARCHAR(200),
		Title                   NVARCHAR(1024),
		Title2                  NVARCHAR(1024),
		StartDate               DATE,
		EndDate                 DATE,
		BranchID                INT,
		AssetSettingID          INT,
		DepreciationMethod      TINYINT,
		DepreciationRate        DECIMAL(5, 2),
		[Status]                INT,
		BaseValue               DECIMAL(30, 4),
		AccumulatedDepreciation DECIMAL(30, 4),
		RemainingLifeTime       INT,
		SalvageValue            DECIMAL(30, 4),
		DepreciationType        TINYINT,
		RepairID                INT,
		AdjustmentItemID        INT,
		RevaluationItemID       INT,
		Depreciation            DECIMAL(30, 4),
		AssetsSettingLifeTime   INT,
		FullyDepreciate         BIT,
		Formul                  NVARCHAR(MAX),
		Net                     DECIMAL(32, 4),
		NetFormula              NVARCHAR(MAX)
	)

	SET @ErrorTable = cfg.getTempTableName(1)

	EXEC ast.GetDepreciationInfo
		 @FinancialPeriod = @FinancialPeriod,
		 @Date = @Date,
		 @Subject = @Subject,
		 @DocumentID = @DocumentID,
		 @BranchID = @BranchID,
		 @ErrorTable = @ErrorTable;

	EXEC (N'INSERT INTO #Error SELECT * FROM ' + @ErrorTable)
	EXEC (N'DROP TABLE ' + @ErrorTable)

	IF EXISTS (SELECT 1 FROM #Error)
		GOTO ReturnErrors

	UPDATE #Depreciation_Temp
	SET    Net = BaseValue - AccumulatedDepreciation - SalvageValue,
		   NetFormula = N'(' + CAST(BaseValue AS NVARCHAR(MAX)) + N' - ' + CAST(AccumulatedDepreciation AS NVARCHAR(MAX))
						+ N' - ' + CAST(SalvageValue AS NVARCHAR(MAX)) + N')'

	-- دوره مالی قبل باید برای شعبه بسته شده باشد (فقط اگر داراییهای این محاسبه قدیمی‌تر از شروع سال مالی باشند)
	SELECT TOP 1 @PreFinancialPeriod = FinancialPeriodID
	FROM   cfg.FinancialPeriod
	WHERE  EndDate < @StartDate
	ORDER BY EndDate DESC

	IF @PreFinancialPeriod IS NOT NULL
	   AND EXISTS
	   (
		   SELECT 1
		   FROM   #Depreciation_Temp c
				  JOIN ast.Asset a ON a.AssetID = c.AssetID
		   WHERE  a.BranchID = @BranchID
				  AND a.AssetCreationDate < @StartDate
	   )
	   AND NOT EXISTS
	   (
		   SELECT 1
		   FROM   ast.AssetClosingOperation a
		   WHERE  a.FinancialPeriodID = @PreFinancialPeriod
				  AND a.BranchID = @BranchID
	   )
	BEGIN
		INSERT INTO #Error ([Message], IsDetail) VALUES (N'AssetManager.Messages.PreviousPeriodNotClosed', 0)
		GOTO ReturnErrors
	END

	-- برای وضعیت داراییها بعد از تاریخ محاسبه، قبلاً استهلاک ثبت شده است
	INSERT INTO #Error ([Message], IsDetail)
	SELECT DISTINCT a.Plaque, 1
	FROM   #Depreciation_Temp c
		   JOIN ast.Asset a ON a.AssetID = c.AssetID
	WHERE  EXISTS
		   (
			   SELECT 1
			   FROM   ast.Depreciation d
			   WHERE  d.AssetSettingID = c.AssetSettingID
					  AND d.Date >= ISNULL(@Date, c.EndDate)
		   )

	IF EXISTS (SELECT 1 FROM #Error)
	BEGIN
		INSERT INTO #Error ([Message], IsDetail) VALUES (N'AssetManager_Messages.DepreciationAlreadyCalculated', 0)
		GOTO ReturnErrors
	END

	-- برای هر نوع تفصیلی مورد استفاده در استهلاک، همه وضعیتها باید تفصیل داشته باشند (اولین نوع ناقص گزارش می‌شود)
	SELECT TOP 1 @DlTypeID = u.DlTypeID,
				 @DlTypeTitle = dt.Title
	FROM   acc.UsedDlType u
		   JOIN acc.DlType dt ON dt.DlTypeID = u.DlTypeID
	WHERE  u.SaturnModuleID = 14
		   AND EXISTS
		   (
			   SELECT 1
			   FROM   #Depreciation_Temp c
			   WHERE  NOT EXISTS
					  (
						  SELECT 1
						  FROM   ast.AssetSettingDl d
						  WHERE  d.AssetSettingID = c.AssetSettingID
								 AND d.DlTypeID = u.DlTypeID
					  )
		   )
	ORDER BY u.DlTypeID

	IF @DlTypeID IS NOT NULL
	BEGIN
		INSERT INTO #Error ([Message], IsDetail)
		SELECT DISTINCT a.Plaque, 1
		FROM   #Depreciation_Temp c
			   JOIN ast.Asset a ON a.AssetID = c.AssetID
		WHERE  NOT EXISTS
			   (
				   SELECT 1
				   FROM   ast.AssetSettingDl d
				   WHERE  d.AssetSettingID = c.AssetSettingID
						  AND d.DlTypeID = @DlTypeID
			   )

		INSERT INTO #Error ([Message], IsDetail) VALUES (N'AssetManager.Messages.DlTypeNotAssigned^' + @DlTypeTitle, 0)
		GOTO ReturnErrors
	END


	-------------------------------------------------------------------------------
	-- محاسبه استهلاک هر ردیف
	-------------------------------------------------------------------------------
	-- نزولی
	UPDATE c
	SET    Depreciation = c.Net * c.DepreciationRate / 100
						  * (CONVERT(FLOAT, c.AssetsSettingLifeTime) / CONVERT(FLOAT, @FinancialPeriodDuration)),
		   Formul = c.NetFormula + N' * ' + CAST(c.DepreciationRate AS NVARCHAR(MAX))
					+ N' / 100 * (convert (float ,' + CAST(c.AssetsSettingLifeTime AS NVARCHAR(MAX))
					+ N') / convert (float ,' + CAST(@FinancialPeriodDuration AS NVARCHAR(MAX)) + N'))'
	FROM   #Depreciation_Temp c
	WHERE  c.DepreciationMethod = 1
		   AND c.EndDate >= c.StartDate

	-- عملکرد
	UPDATE c
	SET    Depreciation = c.Net / (p.Capacity - p.PerfBefore) * p.PerfInYear,
		   Formul = c.NetFormula + N' / (' + CAST(p.Capacity AS NVARCHAR(MAX)) + N' - ' + CAST(p.PerfBefore AS NVARCHAR(MAX))
					+ N') * (' + CAST(p.PerfInYear AS NVARCHAR(MAX)) + N')'
	FROM   #Depreciation_Temp c
		   CROSS APPLY
		   (
			   SELECT ISNULL((SELECT SUM(VALUE)
							  FROM   ast.AssetCapacity
							  WHERE  AssetID = c.AssetID), 0) AS Capacity,
					  ISNULL((SELECT SUM(VALUE)
							  FROM   ast.AssetSettingPerformance a
									 JOIN ast.AssetSetting b ON a.AssetSettingID = b.AssetSettingID
							  WHERE  AssetID = c.AssetID
									 AND EndDate < @StartDate), 0) AS PerfBefore,
					  ISNULL((SELECT SUM(VALUE)
							  FROM   ast.AssetSettingPerformance a
									 JOIN ast.AssetSetting b ON a.AssetSettingID = b.AssetSettingID
							  WHERE  AssetID = c.AssetID
									 AND EndDate BETWEEN @StartDate AND @EndDate), 0) AS PerfInYear
		   ) p
	WHERE  c.DepreciationMethod = 5
		   AND c.EndDate >= c.StartDate

	-- مستقیم دارای عمر مفید
	UPDATE c
	SET    Depreciation = (c.Net / c.RemainingLifeTime) * c.AssetsSettingLifeTime,
		   Formul = N'(' + c.NetFormula + N' / ' + CAST(c.RemainingLifeTime AS NVARCHAR(MAX)) + N')*' + CAST(c.AssetsSettingLifeTime AS NVARCHAR(MAX))
	FROM   #Depreciation_Temp c
	WHERE  c.DepreciationMethod = 2
		   AND c.RemainingLifeTime > 0
		   AND c.AssetsSettingLifeTime > 0
		   AND c.FullyDepreciate = 0
		   AND c.EndDate >= c.StartDate

	-- مستقیم فاقد عمر مفید
	UPDATE c
	SET    Depreciation = c.Net,
		   Formul = c.NetFormula
	FROM   #Depreciation_Temp c
	WHERE  c.DepreciationMethod = 2
		   AND (c.RemainingLifeTime <= 0 OR c.FullyDepreciate = 1)
		   AND c.Net <> 0

	-- بلااستفاده ها
	UPDATE c
	SET    Depreciation = CASE WHEN c.AssetsSettingLifeTime < 0 THEN c.Depreciation ELSE c.Depreciation * 0.3 END,
		   Formul = N'(' + c.Formul + N')' + CASE WHEN c.AssetsSettingLifeTime < 0 THEN N'' ELSE CAST(c.Depreciation * 0.3 AS NVARCHAR(MAX)) END
	FROM   #Depreciation_Temp c
	WHERE  c.Depreciation <> 0
		   AND c.[Status] = 2

	-- 100 درصد
	UPDATE c
	SET    Depreciation = c.Net,
		   Formul = c.NetFormula
	FROM   #Depreciation_Temp c
	WHERE  c.DepreciationMethod = 4
		   AND c.Net <> 0

	UPDATE #Depreciation_Temp
	SET    Depreciation = ROUND(Depreciation, @PrecisionDigit),
		   Formul = N'ROUND(' + Formul + N',' + CAST(@PrecisionDigit AS NVARCHAR(MAX)) + N')'

	-- کسر استهلاکی که در همین سال مالی قبلاً ثبت شده (و استهلاک طی سال ثبت دارایی)
	SELECT d.AssetID, d.AssetSettingID, d.DepreciationType, d.RepairID, d.AdjustmentItemID, d.RevaluationItemID,
		   SUM(d.Value) AS DepreciationUpToNow
	INTO   #DepInYear
	FROM   ast.Depreciation d
	WHERE  d.FinancialPeriodID = @FinancialPeriod
		   AND d.AssetID IN (SELECT AssetID FROM #Depreciation_Temp)
	GROUP BY d.AssetID, d.AssetSettingID, d.DepreciationType, d.RepairID, d.AdjustmentItemID, d.RevaluationItemID

	UPDATE c
	SET    Depreciation = c.Depreciation - ISNULL(y.DepreciationUpToNow, 0) - ISNULL(a.DuringDepreciation, 0),
		   Formul = N'(' + c.Formul + N') - ' + CAST(ISNULL(y.DepreciationUpToNow, 0) AS NVARCHAR(MAX))
					+ N' - ' + CAST(ISNULL(a.DuringDepreciation, 0) AS NVARCHAR(MAX))
	FROM   #Depreciation_Temp c
		   LEFT JOIN
		   (
			   SELECT b.AssetSettingID, a.DuringDepreciation
			   FROM   ast.Asset a
					  JOIN ast.AssetSetting b
						   ON  b.AssetID = a.AssetID
						   AND b.ParentID IS NULL
			   WHERE  a.AssetCreationDate BETWEEN @StartDate AND @EndDate
					  AND a.Nature <> 3		-- an asset received from another branch already carries DuringDepreciation in its opening accumulated depreciation
					  AND ISNULL(a.DuringDepreciation, 0) > 0
					  AND a.AssetID IN (SELECT AssetID FROM #Depreciation_Temp)
		   ) a ON a.AssetSettingID = c.AssetSettingID
		   LEFT JOIN #DepInYear y
				ON  y.AssetSettingID = c.AssetSettingID
				AND y.DepreciationType = c.DepreciationType
				AND (c.RepairID IS NULL OR c.RepairID = y.RepairID)
				AND (c.AdjustmentItemID IS NULL OR c.AdjustmentItemID = y.AdjustmentItemID)
				AND (c.RevaluationItemID IS NULL OR c.RevaluationItemID = y.RevaluationItemID)

	UPDATE c
	SET    Formul = CASE
						WHEN c.DepreciationMethod = 1 THEN N'روش نزولی: '
						WHEN c.DepreciationMethod = 2 AND c.RemainingLifeTime > 0 THEN N'روش مستقیم دارای عمر مفید: '
						WHEN c.DepreciationMethod = 2 AND c.RemainingLifeTime <= 0 THEN N'روش مستقیم فاقد عمر مفید: '
						WHEN c.DepreciationMethod = 4 THEN N'روش 100 درصد: '
						WHEN c.DepreciationMethod = 5 THEN N'روش عملکردی:'
				   END + c.Formul
	FROM   #Depreciation_Temp c


	-------------------------------------------------------------------------------
	-- کنترل نهایی: فقط داراییهایی که در همین محاسبه ردیف جدید دارند
	-- استهلاک سال مالی (ثبت شده + محاسبه جدید) هر جزء نباید از (ارزش دارایی تا تاریخ مبنا - ارزش اسقاط) بیشتر شود
	-------------------------------------------------------------------------------
	SELECT c.AssetID,
		   ISNULL(@Date, MAX(c.EndDate)) AS AsOfDate
	INTO   #AsOf
	FROM   #Depreciation_Temp c
	WHERE  c.Depreciation <> 0
	GROUP BY c.AssetID

	SELECT v.AssetID,
		   SUM(v.VALUE) AS VALUE
	INTO   #AssetValue
	FROM   [AST].[VWAssetValue] v
		   JOIN #AsOf x
				ON  x.AssetID = v.AssetID
				AND v.[DATE] <= x.AsOfDate
	GROUP BY v.AssetID

	SELECT @Assets = STUFF(
			   (
				   SELECT DISTINCT ',' + QUOTENAME(a.Plaque)
				   FROM   (
							  SELECT u.AssetID, u.DepreciationType, u.RepairID, u.AdjustmentItemID, u.RevaluationItemID,
									 SUM(u.Depreciation) AS Depreciation
							  FROM   (
										 SELECT y.AssetID, y.DepreciationType, y.RepairID, y.AdjustmentItemID, y.RevaluationItemID,
												y.DepreciationUpToNow AS Depreciation
										 FROM   #DepInYear y
										 WHERE  y.AssetID IN (SELECT AssetID FROM #AsOf)

										 UNION ALL

										 SELECT c.AssetID, c.DepreciationType, c.RepairID, c.AdjustmentItemID, c.RevaluationItemID,
												c.Depreciation
										 FROM   #Depreciation_Temp c
										 WHERE  c.Depreciation <> 0
									 ) u
							  GROUP BY u.AssetID, u.DepreciationType, u.RepairID, u.AdjustmentItemID, u.RevaluationItemID
						  ) d
						  JOIN ast.Asset a ON a.AssetID = d.AssetID
						  JOIN #AssetValue v ON v.AssetID = d.AssetID
				   WHERE  v.VALUE - a.SalvageValue < d.Depreciation
				   FOR XML PATH(''), TYPE
			   ).value('.', 'NVARCHAR(MAX)'),
			   1,
			   1,
			   ''
		   )

	IF @Assets IS NOT NULL
	BEGIN
		SET @Message = N'E_' + N'اشکال در محاسبه استهلاک داراییهای زیر:' + CHAR(13) + CHAR(10) + @Assets

		RAISERROR(@Message, 16, 10)
		RETURN
	END


	-------------------------------------------------------------------------------
	-- اصلاح ارزش اسقاط: مجموع استهلاک عادی نباید ارزش دارایی را از ارزش اسقاط کمتر کند؛
	-- مابه‌التفاوت از آخرین وضعیت کسر می‌شود
	-------------------------------------------------------------------------------
	SELECT a.AssetID,
		   a.SalvageValue - (a.BaseValue - (a.AccumulatedDepreciation + a.DuringDepreciation + b.OverDepreciation + c.InDepreciation)) AS Diff
	INTO   #SalvageDiff
	FROM   ast.Asset a
		   JOIN (
					SELECT AssetID, SUM(Depreciation) AS InDepreciation
					FROM   #Depreciation_Temp
					WHERE  DepreciationType = 1
					GROUP BY AssetID
				) c ON c.AssetID = a.AssetID
		   JOIN (
					SELECT AssetID, SUM(VALUE) AS OverDepreciation
					FROM   ast.Depreciation
					WHERE  DepreciationType = 1
						   AND AssetID IN (SELECT AssetID FROM #Depreciation_Temp)
					GROUP BY AssetID
				) b ON b.AssetID = a.AssetID
	WHERE  a.BaseValue - (a.AccumulatedDepreciation + a.DuringDepreciation + b.OverDepreciation + c.InDepreciation) < a.SalvageValue

	UPDATE c
	SET    Depreciation = c.Depreciation - s.Diff
	FROM   #SalvageDiff s
		   JOIN (
					SELECT ID, AssetID,
						   ROW_NUMBER() OVER (PARTITION BY AssetID ORDER BY AssetSettingID DESC, ID DESC) AS Rno
					FROM   #Depreciation_Temp
					WHERE  DepreciationType = 1
				) l ON l.AssetID = s.AssetID AND l.Rno = 1
		   JOIN #Depreciation_Temp c ON c.ID = l.ID


	-------------------------------------------------------------------------------
	-- ذخیره نتایج
	-------------------------------------------------------------------------------
	DECLARE @OwnTransaction BIT = CASE WHEN @@TRANCOUNT = 0 THEN 1 ELSE 0 END

	IF @OwnTransaction = 1
		BEGIN TRANSACTION

	IF @Document = 'DepreciationCalculation'
	BEGIN
		INSERT INTO ast.DepreciationCalculation
			   (DepreciationPeriodID, VoucherID, BranchID, Creator, CreationDate, Version, LastEditor, LastEditionDate)
		VALUES (@DepreciationPeriodID, NULL, @BranchID, @CurrentUser, @CurrentDate, 0, @CurrentUser, @CurrentDate)

		SET @DepreciationCalculationID = SCOPE_IDENTITY()
	END

	INSERT INTO [AST].[Depreciation]
		   (
			   [FinancialPeriodID],
			   [Date],
			   [AssetID],
			   [AssetSettingID],
			   [RepairID],
			   [AdjustmentItemID],
			   [RevaluationItemID],
			   [Value],
			   [DepreciationType],
			   [VoucherID],
			   [Version],
			   [Creator],
			   [CreationDate],
			   [LastEditor],
			   [LastEditionDate],
			   [Formul],
			   [IsAutoGenerated],
			   DepreciationCalculationID,
			   DestructionID,
			   SalvageID,
			   SaleID,
			   TransferID,
			   ChangeCategoryID,
			   RevaluationID,
			   DOCUMENT,
			   DocumentID
		   )
	SELECT @FinancialPeriod,
		   ISNULL(@Date, c.EndDate),
		   c.AssetID,
		   c.AssetSettingID,
		   c.RepairID,
		   c.AdjustmentItemID,
		   c.RevaluationItemID,
		   c.Depreciation,
		   c.DepreciationType,
		   NULL,
		   0,
		   @CurrentUser,
		   @CurrentDate,
		   @CurrentUser,
		   @CurrentDate,
		   c.Formul,
		   @AutoGenerated,
		   @DepreciationCalculationID,
		   CASE WHEN @Document = 'Destruction'    THEN @DocumentID END,
		   CASE WHEN @Document = 'Salvage'        THEN @DocumentID END,
		   CASE WHEN @Document = 'Sale'           THEN @DocumentID END,
		   CASE WHEN @Document = 'Transfer'       THEN @DocumentID END,
		   CASE WHEN @Document = 'ChangeCategory' THEN @DocumentID END,
		   CASE WHEN @Document = 'Revaluation'    THEN @DocumentID END,
		   @Document,
		   ISNULL(@DocumentID, @DepreciationCalculationID)
	FROM   #Depreciation_Temp c
	WHERE  c.Depreciation <> 0

	IF @OwnTransaction = 1
		COMMIT TRANSACTION


ReturnErrors:
	SELECT * FROM #Error; -- (DO NOT REMOVE) ==> needs to return table (message,isDetail) finally to use db.Database.SqlQueryRaw in backend

END

