CREATE   PROC [STC].[spOutgoingInsert]
    @AutoGenerated BIT,
    @StockDocumentTypeBaseEntityID INT , 
    @Number INT,
    @Date DATE,
    @StockID INT,
    @DeliverDlID BIGINT,
    @DeliverStockID INT,
    @FinancialPeriodID INT,
    @PreVoucherID INT,
    @Creator INT,
    @CreationDate DATETIME,
    @TotalPrice DECIMAL(30, 4)
--WITH ENCRYPTION 
AS
BEGIN
    SET NOCOUNT ON;
    SET XACT_ABORT ON;

    DECLARE @StartNum INT = NULL,
			@StockDocumentTypeID INT,
            @EndNum INT = NULL,
            @Stock BIT = 0,
            @ResetType BIT = 0,
            @DocumentNumID INT,
            @OutgoingID INT,
            @Message NVARCHAR(MAX);

    SELECT  @StockDocumentTypeID = StockDocumentTypeID
    FROM    stc.StockDocumentTypeBaseEntity sdtb
	WHERE sdtb.StockDocumentTypeBaseEntityID = @StockDocumentTypeBaseEntityID

    SELECT @StartNum = StartNum,
           @EndNum = EndNum,
           @DocumentNumID = DocumentNumID
    FROM CFG.DocumentNum
    WHERE DocumentNumTypeID = 16
          AND FinancialPeriodID = @FinancialPeriodID;

    IF EXISTS
    (
        SELECT 1
        FROM CFG.DocumentNumResetNumberBase
        WHERE DocumentNumID = @DocumentNumID
              AND DocumentNumResetNumberBaseTypeID = 3
    )
    BEGIN
        SET @Stock = 1;
    END;

    IF EXISTS
    (
        SELECT 1
        FROM CFG.DocumentNumResetNumberBase
        WHERE DocumentNumID = @DocumentNumID
              AND DocumentNumResetNumberBaseTypeID = 2
    )
    BEGIN
        SET @ResetType = 1;
    END;

    IF (@Number = 0 OR @Number IS NULL)
    BEGIN
        SET @Number = ISNULL(
                      (
                          SELECT MAX(Number) + 1
                          FROM [STC].[Outgoing] o
						  JOIN [STC].[StockDocumentTypeBaseEntity] sdtb 
								ON o.StockDocumentTypeBaseEntityID = sdtb.StockDocumentTypeBaseEntityID
                          WHERE FinancialPeriodID = @FinancialPeriodID
                                AND
                                (
                                    @Stock = 0
                                    OR StockID = @StockID
                                )
                                AND
                                (
                                    @ResetType = 0
                                    OR sdtb.StockDocumentTypeID = @StockDocumentTypeID
                                )
                      ),
                      @StartNum
                            );
    END;
    ELSE
    BEGIN
        IF (EXISTS
        (
            SELECT 1
            FROM [STC].[Outgoing] o
			JOIN [STC].[StockDocumentTypeBaseEntity] sdtb 
				ON o.StockDocumentTypeBaseEntityID = sdtb.StockDocumentTypeBaseEntityID
            WHERE FinancialPeriodID = @FinancialPeriodID
                  AND
                  (
                      @Stock = 0
                      OR StockID = @StockID
                  )
                  AND
                  (
                      @ResetType = 0
                      OR sdtb.StockDocumentTypeID = @StockDocumentTypeID
                  )
                  AND Number = @Number
        )
           )
        BEGIN
            RAISERROR('NumberIsDuplicate', 16, 12);
			RETURN 0;
        END;
    END;

    IF (@Number >= @StartNum AND (@EndNum IS NULL OR @Number <= @EndNum))
    BEGIN

        INSERT INTO [STC].[Outgoing]
        (
            [AutoGenerated],
            [StockDocumentTypeBaseEntityID],
            [Number],
            [Date],
            [StockID],
            [DeliverDlID],
            [DeliverStockID],
            [FinancialPeriodID],
            [PreVoucherID],
            [Version],
            [Creator],
            [CreationDate],
            [LastEditor],
            [LastEditionDate],
            [TotalPrice]
        )
        SELECT @AutoGenerated,
               @StockDocumentTypeBaseEntityID,
               @Number,
               @Date,
               @StockID,
               @DeliverDlID,
               @DeliverStockID,
               @FinancialPeriodID,
               @PreVoucherID,
               0,
               @Creator,
               @CreationDate,
               @Creator,
               @CreationDate,
               @TotalPrice;
        SET @OutgoingID = SCOPE_IDENTITY();
        -- Begin Return Select <- do not remove
        SELECT [OutgoingID],
               [Version],
               [Number]
        FROM [STC].[Outgoing]
        WHERE [OutgoingID] = @OutgoingID;
        -- End Return Select <- do not remove
    END;
    ELSE
    BEGIN
        RAISERROR('InvalidNumberRange', 16, 12);
    END;
END;
