CREATE     PROC [AST].[GetCalculatedInsurances]
(
@FinancialPeriodID int
)
--WITH ENCRYPTION 
as

declare @Working nvarchar(150),
		@Unused nvarchar(150),
		@UserCulture varchar(2),
		@Columns nvarchar(max),
		@Query nvarchar(max),
		@ColumnsInSelect nvarchar(max),
		@CultureNo tinyint
	
	set @UserCulture = CFG.GetuserCulture();

	select @CultureNo = CultureNo
	from CFG.CultureInfo 
	where Culture = @UserCulture

	select @Working =''''+ LV.Value+''''
	from cfg.LocalizeEnum L
	join cfg.LocalizeEnumValue LV on L.LocalizeEnumID = LV.LocalizeEnumID
	where L.Enum = 'AssetusageStatus'
	and L.Item = 'Working'
	and LV.Culture = @UserCulture

	select @Unused = ''''+ LV.Value+''''
	from cfg.LocalizeEnum L
	join cfg.LocalizeEnumValue LV on L.LocalizeEnumID = LV.LocalizeEnumID
	where L.Enum = 'AssetusageStatus'
	and L.Item = 'Unused'
	and LV.Culture = @UserCulture



	select @Columns = STUFF((SELECT DISTINCT ',' + QUOTENAME(DlTypeID) 
									FROM acc.UsedDlType  WHERE SaturnModuleID = 14
									FOR XML PATH(''), TYPE
								   ).value('.', 'NVARCHAR(MAX)'),1,1,'')
								   
	if(@Columns is null)
	set @Columns = '[-1]'
	
	select @ColumnsInSelect = STUFF((SELECT DISTINCT ' ,' +QUOTENAME(DlTypeID) +' as T' +cast(DlTypeID as nvarchar(150))
									FROM acc.UsedDlType  WHERE SaturnModuleID = 14
									FOR XML PATH(''), TYPE
								   ).value('.', 'NVARCHAR(MAX)'),1,1,'')
								   
	if(@ColumnsInSelect is null)
	set @ColumnsInSelect = ''

		declare @UserID INT,
			@DateType TINYINT,
			@DateFormat VARCHAR(50)

	SET  @UserID=cfg.GetuserID()

	SELECT @DateType = us.SettingValue
	FROM   cfg.UserSetting us
	WHERE  us.SettingKey = 'Date_Type'
	       AND us.UserID = @UserID
	
	IF @DateType IS NULL
	SET @DateType = CASE cfg.GetuserCulture() WHEN 'fa' THEN 0	
											  WHEN 'en' THEN 1
											  WHEN 'ar' THEN 2 END
	
	
	SELECT @DateFormat = us.SettingValue
	FROM   cfg.UserSetting us
	WHERE  us.SettingKey = 'Date_Format'
	       AND us.UserID =  @UserID	

   

	IF @DateFormat IS NULL
		SET @DATEFORMAT = 'YY/MM/DD' 

	SET @Query = N'
select d.InsuranceSharingID,a.Plaque,a.Title,a.Title2,b.Code as BranchCode,
b.Title as BranchTitle,b.Title2 as BranchTitle2'+@ColumnsInSelect+'
,d.SharingValue,
d.VoucherID,
d.IsAutoGenerated,
v.ReferenceNumber as VoucherNumber,
CFG.GetCLRSaturnDate(v.Date,'''+@DateFormat+' '' , 0,'+cast(@DateType as varchar(10))+')AS VoucherDate,
CFG.GetCLRSaturnDate(d.Date,'''+@DateFormat+' '' , 0,'+cast(@DateType as varchar(10))+')AS Date,
d.Date CalculationDate,
h.Number Number,
CFG.GetCLRSaturnDate(h.Date,'''+@DateFormat+' '' , 0,'+cast(@DateType as varchar(10))+')AS InsuranceDate,
pa.title Organization,
t.title InsuranceType,
CFG.GetCLRSaturnDate(h.FromDate,'''+@DateFormat+' '' , 0,'+cast(@DateType as varchar(10))+')AS FromDate,
CFG.GetCLRSaturnDate(h.EndDate,'''+@DateFormat+' '' , 0,'+cast(@DateType as varchar(10))+')AS EndDate

from AST.InsuranceSharing d
join AST.AssetSetting ass on d.AssetSettingID = ass.AssetSettingID
join AST.Asset a on a.AssetID = ass.AssetID
join ast.insuranceitem i on d.insuranceitemid = i.insuranceitemid
join ast.insurance h on h.InsuranceID = i.InsuranceID
join cfg.party pa on pa.partyid = h.partyid
join ast.insurancetype t on  t.InsuranceTypeID = h.InsuranceTypeID
join CFG.Branch b on b.BranchID = a.BranchID
	LEFT JOIN 
	(
	select AssetSettingID,asd.DlTypeID,
	case when '+ CAST(@CultureNo AS CHAR(1)) +' = 1 then d.Title
	        when '+ CAST(@CultureNo AS CHAR(1)) +' = 2 then d.Title2
	   end as Title
	from ast.AssetSettingDl asd
	JOIN acc.Dl d ON asd.DlID = d.DLID 
	)x pivot
	(
	max(Title)
	for DlTypeID in ('+@Columns+')
	)p on p.AssetSettingID = d.AssetSettingID 
left join acc.voucher v on v.voucherid = d.voucherid
where d.FinancialPeriodID ='+cast (@FinancialPeriodID as varchar(20))


	EXEC (@Query)


