CREATE     PROC [STF].[spTraceDocumentNumTypeUpdate]
    @TraceDocumentNumTypeID INT ,
    @TraceID INT ,
    @DocumentNumTypeID SMALLINT ,
    @Version INT ,
    @Creator INT ,
    @CreationDate DATETIME ,
    @LastEditor INT ,
    @LastEditionDate DATETIME,
	@IsAutoGenerated BIT 
AS
    SET NOCOUNT ON;


    IF @Version = (   SELECT [Version]
                      FROM   [STF].[TraceDocumentNumType]
                      WHERE  [TraceDocumentNumTypeID] = @TraceDocumentNumTypeID )
        BEGIN

            SET @Version = @Version + 1;

            UPDATE [STF].[TraceDocumentNumType]
            SET    [TraceID] = @TraceID ,
                   [DocumentNumTypeID] = @DocumentNumTypeID ,
                   IsAutoGenerated = @IsAutoGenerated,
                   [Version] = @Version ,
                   [Creator] = @Creator ,
                   [CreationDate] = @CreationDate ,
                   [LastEditor] = @LastEditor ,
                   [LastEditionDate] = @LastEditionDate
            WHERE  [TraceDocumentNumTypeID] = @TraceDocumentNumTypeID;

            -- Begin Return Select <- do not remove
            SELECT [Version] 
            FROM   [STF].[TraceDocumentNumType]
            WHERE  [TraceDocumentNumTypeID] = @TraceDocumentNumTypeID;
        -- End Return Select <- do not remove

        END;
