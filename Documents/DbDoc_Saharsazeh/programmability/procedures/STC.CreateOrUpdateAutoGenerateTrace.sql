
CREATE       PROC [STC].CreateOrUpdateAutoGenerateTrace
(
    @DocumentName NVARCHAR(500) ,
    @DocumentId int
)
--WITH ENCRYPTION
AS
    BEGIN

        SELECT dnt.EngName ,
               tdnt.TraceID ,
               tdnt.TraceDocumentNumTypeID ,
               tgc.Parameter ,
               tgc.[Order] ,
               tgc.[Length] ,
               st.StuffID
        INTO   #autoTraces
        FROM   STF.TraceDocumentNumType AS tdnt
               JOIN CFG.DocumentNumType AS dnt ON dnt.DocumentNumTypeID = tdnt.DocumentNumTypeID
               JOIN STF.TraceGenerateConfig AS tgc ON tgc.TraceDocumentNumTypeID = tdnt.TraceDocumentNumTypeID
               JOIN STF.StuffTrace AS st ON st.TraceID = tdnt.TraceID
        WHERE  tdnt.IsAutoGenerated = 1;

        IF @DocumentName = 'StockReceiptItem' 
            BEGIN

                SELECT sri.StockReceiptItemID ,
                       at.TraceID ,
                       at.[Order] ,
                       at.Parameter ,
                       CASE WHEN at.Parameter = 1 THEN
                                REPLACE(STR(sdt.Code, at.Length), ' ', '0')
                            WHEN at.Parameter = 2 THEN
                                REPLACE(STR(s.Code, at.Length), ' ', '0')
                            WHEN at.Parameter = 3 THEN
                                REPLACE(
                                    STR(
                                        CASE WHEN d.DLID IS NOT NULL THEN
                                                 d.Code
                                             ELSE s2.Code
                                        END ,
                                        at.Length) ,
                                    ' ' ,
                                    '0')
                            WHEN at.Parameter = 4 THEN
                                REPLACE(STR(sr.Number, at.Length), ' ', '0')
                            WHEN at.Parameter = 5 THEN fp.Title
                       END Val
                INTO   #tResult
                FROM   STC.StockReceiptItem AS sri
                       JOIN STC.StockReceipt AS sr ON sr.StockReceiptID = sri.StockReceiptID
                       JOIN CFG.FinancialPeriod AS fp ON fp.FinancialPeriodID = sr.FinancialPeriodID
					   JOIN [STC].[StockDocumentTypeBaseEntity] sdtb
								ON sr.StockDocumentTypeBaseEntityID = sdtb.StockDocumentTypeBaseEntityID
                       JOIN STC.StockDocumentType AS sdt ON sdt.StockDocumentTypeID = sdtb.StockDocumentTypeID
                       JOIN STF.Stock AS s ON s.StockID = sr.StockID
                       LEFT JOIN ACC.DL AS d ON d.DLID = sr.DeliverDlID
                       LEFT JOIN STF.Stock AS s2 ON s2.StockID = sr.DeliverStockID
                       JOIN #autoTraces AS at ON at.StuffID = sri.StuffID
                                                 AND at.EngName = 'StockReceipt'
                WHERE  sri.StockReceiptID = @DocumentId
                                and sdt.DocumentType <> 5
                
                ;

                SELECT   r.StockReceiptItemID ,
                         r.TraceID ,
                         NULL AS DLID ,
                         STUFF(
                             (   SELECT   '' + Val
                                 FROM     #tResult
                                 WHERE    (   StockReceiptItemID = r.StockReceiptItemID
                                              AND TraceID = r.TraceID )
                                 ORDER BY [Order]
                                 FOR XML PATH(''), TYPE ).value(
                                                              '(./text())[1]' ,
                                                              'VARCHAR(MAX)') ,
                             1 ,
                             0 ,
                             '') AS [Value] ,
                         0 AS Version ,
                         CFG.GetuserID() AS Creator ,
                         GETDATE() AS CreationDate ,
                         CFG.GetuserID() AS LastEditor ,
                         GETDATE() AS LastEditionDate
                INTO     #tempInsertRes
                FROM     #tResult r
                GROUP BY r.StockReceiptItemID ,
                         r.TraceID;

                PRINT 'delete';

                DELETE STC.StockReceiptItemTrace
                WHERE StockReceiptItemTraceID IN (   SELECT srit.StockReceiptItemTraceID
                                                     FROM   STC.StockReceiptItemTrace AS srit
                                                            JOIN #tempInsertRes AS tir ON tir.StockReceiptItemID = srit.StockReceiptItemID
                                                                                          AND tir.TraceID = srit.TraceID );

                PRINT 'Insert';
                INSERT STC.StockReceiptItemTrace ( StockReceiptItemID ,
                                                   TraceID ,
                                                   DlID ,
                                                   Value ,
                                                   Version ,
                                                   Creator ,
                                                   CreationDate ,
                                                   LastEditor ,
                                                   LastEditionDate )
                       SELECT tir.StockReceiptItemID ,
                              tir.TraceID ,
                              tir.DLID ,
                              tir.Value ,
                              tir.Version ,
                              tir.Creator ,
                              tir.CreationDate ,
                              tir.LastEditor ,
                              tir.LastEditionDate
                       FROM   #tempInsertRes AS tir;

            END;
        ELSE IF @DocumentName = 'ReturnedOutgoingItem'
                 BEGIN

                     SELECT sri.ReturnedOutgoingItemID ,
                            at.TraceID ,
                            at.[Order] ,
                            at.Parameter ,
                            CASE WHEN at.Parameter = 1 THEN
                                     REPLACE(
                                         STR(sdt.Code, at.[Length]), ' ', '0')
                                 WHEN at.Parameter = 2 THEN
                                     REPLACE(
                                         STR(s.Code, at.[Length]), ' ', '0')
                                 WHEN at.Parameter = 3 THEN
                                     REPLACE(
                                         STR(
                                             CASE WHEN d.DLID IS NOT NULL THEN
                                                      d.Code
                                                  ELSE s2.Code
                                             END ,
                                             at.[Length]) ,
                                         ' ' ,
                                         '0')
                                 WHEN at.Parameter = 4 THEN
                                     REPLACE(
                                         STR(sr.Number, at.[Length]) ,
                                         ' ' ,
                                         '0')
                                 WHEN at.Parameter = 5 THEN fp.Title
                            END Val
                     INTO   #tResult2
                     FROM   STC.ReturnedOutgoingItem AS sri
                            JOIN STC.ReturnedOutgoing AS sr ON sr.ReturnedOutgoingID = sri.ReturnedOutgoingID
                            JOIN [STC].[StockDocumentTypeBaseEntity] sdtb 
                                ON sr.StockDocumentTypeBaseEntityID = sdtb.StockDocumentTypeBaseEntityID
                            JOIN CFG.FinancialPeriod AS fp ON fp.FinancialPeriodID = sr.FinancialPeriodID
                            JOIN STC.StockDocumentType AS sdt ON sdt.StockDocumentTypeID = sdtb.StockDocumentTypeID
                            JOIN STF.Stock AS s ON s.StockID = sr.StockID
                            LEFT JOIN ACC.DL AS d ON d.DLID = sr.DlDeliverID
                            LEFT JOIN STF.Stock AS s2 ON s2.StockID = sr.StockDeliverID
                            JOIN #autoTraces AS at ON at.StuffID = sri.StuffID
                                                      AND at.EngName = 'ReturnedOutgoing'
                     WHERE  sri.ReturnedOutgoingID = @DocumentId;

                     SELECT   r.ReturnedOutgoingItemID ,
                              r.TraceID ,
                              NULL AS DLID ,
                              STUFF(
                                  (   SELECT   '' + Val
                                      FROM     #tResult2
                                      WHERE    (   ReturnedOutgoingItemID = r.ReturnedOutgoingItemID
                                                   AND TraceID = r.TraceID )
                                      ORDER BY [Order]
                                      FOR XML PATH(''), TYPE ).value(
                                                                   '(./text())[1]' ,
                                                                   'VARCHAR(MAX)') ,
                                  1 ,
                                  0 ,
                                  '') AS [Value] ,
                              0 AS Version ,
                              CFG.GetuserID() AS Creator ,
                              GETDATE() AS CreationDate ,
                              CFG.GetuserID() AS LastEditor ,
                              GETDATE() AS LastEditionDate
                     INTO     #tempInsertRes2
                     FROM     #tResult2 r
                     GROUP BY r.ReturnedOutgoingItemID ,
                              r.TraceID;

                     PRINT 'delete';

                     DELETE STC.ReturnedOutgoingItemTrace
                     WHERE ReturnedOutgoingItemTraceID IN (   SELECT srit.ReturnedOutgoingItemTraceID
                                                              FROM   STC.ReturnedOutgoingItemTrace AS srit
                                                                     JOIN #tempInsertRes2 AS tir ON tir.ReturnedOutgoingItemID = srit.ReturnedOutgoingItemID
                                                                                                    AND tir.TraceID = srit.TraceID );

                     PRINT 'Insert';
                     INSERT STC.ReturnedOutgoingItemTrace ( ReturnedOutgoingItemID ,
                                                            TraceID ,
                                                            DlID ,
                                                            [Value] ,
                                                            [Version] ,
                                                            Creator ,
                                                            CreationDate ,
                                                            LastEditor ,
                                                            LastEditionDate )
                            SELECT tir.ReturnedOutgoingItemID ,
                                   tir.TraceID ,
                                   tir.DLID ,
                                   tir.[Value] ,
                                   tir.[Version] ,
                                   tir.Creator ,
                                   tir.CreationDate ,
                                   tir.LastEditor ,
                                   tir.LastEditionDate
                            FROM   #tempInsertRes2 AS tir;

                 END;
    END;
