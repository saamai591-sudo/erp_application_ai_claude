
--------------------------------------

CREATE   PROC [STC].sp_UndoPricingValidation
(
    @PricingDate DATE,
    @selItems NVARCHAR(MAX),
    @FinancialPeriodID INT
)
--WITH ENCRYPTION
WITH RECOMPILE
AS
BEGIN TRY
    DECLARE @Columns NVARCHAR(MAX),
            @Query NVARCHAR(MAX),
            @ConditionalInnerJoin NVARCHAR(MAX),
            @And NVARCHAR(MAX),
            @Message NVARCHAR(MAX);

    IF OBJECT_ID('CheckUndoPricingValidationTemp') IS NOT NULL
        DROP TABLE CheckUndoPricingValidationTemp;

    IF OBJECT_ID('tempdb..##Selected') IS NOT NULL
        DROP TABLE ##Selected;

    EXEC CFG.TableFromIStuffTraceString @selItems, '##Selected', 1;

	alter table ##Selected add LastPricingDate Date

    SELECT @Columns = STUFF(
    (
        SELECT DISTINCT
               ',' + QUOTENAME(al.TraceID)
        FROM STF.Trace al
        WHERE PricingBase = 1
        FOR XML PATH(''), TYPE
    ).value('.', 'NVARCHAR(MAX)'),1   ,1   ,'');

    IF (@Columns IS NULL)
        SET @Columns = N'[-1]';

    SELECT @ConditionalInnerJoin
        = N'inner join ##Selected Selected on Selected.stuffid = @.stuffid AND Selected.StockID = @.StockID '
          + STUFF((SELECT DISTINCT
						' AND (Selected.' + QUOTENAME(TraceID) + ' is null or @.' + QUOTENAME(TraceID) + '= Selected.'
						+ QUOTENAME(TraceID) + ')'
					FROM STF.Trace
					WHERE PricingBase = 1
					FOR XML PATH(''), TYPE
				 ).value('.', 'NVARCHAR(MAX)'),1   ,1   ,'');


    IF (@ConditionalInnerJoin IS NULL)
        SET @ConditionalInnerJoin = N'inner join ##Selected Selected on Selected.stuffid = @.stuffid AND Selected.StockID = @.StockID ';



	set @Query = N'
	update Selected
	set LastPricingDate = M.LastPricingDate
	from (
	select  TraceID,
			Case 
				When DLID IS NOT NULL THEN cast (DLID as nvarchar(max)) 
				When TraceItemID IS NOT NULL THEN cast (TraceItemID as nvarchar(max)) 
				else Value 
			end Value,
			i.stockid,i.PricingItemID,i.stuffID,LastPricingDate
			from stc.PricingItem i
			left join 	 stc.PricingItemTrace tr  on tr.PricingItemID = i.PricingItemID
			WHERE  [LastPricingDate] >= @pPricingDate	
	) x
	pivot 
	(
		 max(Value)
		for TraceID in (' + @Columns + ')
	) M 
	  '+ replace(@ConditionalInnerJoin,'@','M')
	EXECUTE sp_executeSQL     
			@Query,
			N'@pPricingDate Date',
			@pPricingDate = @PricingDate
    

	CREATE TABLE #ValidationTemp
    (
        ValidationNo NVARCHAR(MAX),
        ValidationDesc NVARCHAR(MAX)
    );

    --** Check Validations	
    --** کنترل عمليات پايان دوره
    INSERT INTO #ValidationTemp
    SELECT DISTINCT
            id,
            'STC_SpFinalStuffInventory_2'
    FROM ##Selected
        JOIN STC.StockClosingOperation sco
            ON ##Selected.StockID = sco.StockID
    WHERE sco.FinancialPeriodID = @FinancialPeriodID
            AND sco.[Status] = 2;



    --** برگشت رسيد


    SET @Query
        = N'
		select Selected.id position,ReturnStockReceiptItemID,prevoucherid,ReturnStockReceiptID,Date
		into CheckUndoPricingValidationTemp
		from
		(
		select  i.ReturnStockReceiptItemID,TraceID,i.stuffid,h.prevoucherid,h.ReturnStockReceiptID,h.stockid,
				Case When t.DLID IS NOT NULL THEN cast (t.DLID as nvarchar(max)) 
					When t.TraceItemID IS NOT NULL THEN cast (t.TraceItemID as nvarchar(max)) 
				else Value end Value,h.Date
		from stc.ReturnStockReceipt h
		inner join stc.ReturnStockReceiptItem i  on h.ReturnStockReceiptID = i.ReturnStockReceiptID
		left join 
		 stc.ReturnStockReceiptItemTrace t on i.ReturnStockReceiptItemID=t.ReturnStockReceiptItemID
		where h.FinancialPeriodID = @pFinancialPeriodID
		)x pivot
			( max(Value)
					for TraceID in ( ' + @Columns + N')
				) p ' + REPLACE(@ConditionalInnerJoin,'@','P');

    EXECUTE sp_executesql @Query,
                          N'@pFinancialPeriodID INT',
                          @pFinancialPeriodID = @FinancialPeriodID


    INSERT INTO #ValidationTemp
    SELECT DISTINCT
           position,
           'STC_sp_UndoPricingValidation_3'
    FROM STC.RevisionCostItem rci
        JOIN STC.RevisionCost rc
            ON rc.RevisionCostID = rci.RevisionCostID
        JOIN CheckUndoPricingValidationTemp
            ON CheckUndoPricingValidationTemp.ReturnStockReceiptItemID = rci.ReturnStockReceiptItemID
    WHERE rc.AutoGenerated = 1
          AND rc.PreVoucherID IS NOT NULL
          AND rc.Date >= @PricingDate;

    INSERT INTO #ValidationTemp
    SELECT DISTINCT
           position,
           'STC_sp_UndoPricingValidation_4'
    FROM CheckUndoPricingValidationTemp CT
        JOIN STC.ReturnStockReceiptItem RARI
            ON RARI.ReturnStockReceiptItemID = CT.ReturnStockReceiptItemID
    WHERE prevoucherid IS NOT NULL
          AND CT.Date >= @PricingDate;

    IF OBJECT_ID('CheckUndoPricingValidationTemp') IS NOT NULL
        DROP TABLE CheckUndoPricingValidationTemp;


    --** رسيد
    SET @Query
        = N'
		select Selected.id position,StockReceiptItemID,prevoucherid,StockReceiptID,Date,stockdocumenttypeid,AutoGenerated
		into CheckUndoPricingValidationTemp
		from
		(
		select  i.StockReceiptItemID,TraceID,i.stuffid,h.prevoucherid,h.StockReceiptID,h.stockid,
				Case When t.DLID IS NOT NULL THEN cast (t.DLID as nvarchar(max)) 
					When t.TraceItemID IS NOT NULL THEN cast (t.TraceItemID as nvarchar(max)) 
				else Value end Value,h.Date,sdtb.stockdocumenttypeid,h.AutoGenerated
		from stc.StockReceipt h
        JOIN [STC].[StockDocumentTypeBaseEntity] sdtb 
            ON h.StockDocumentTypeBaseEntityID = sdtb.StockDocumentTypeBaseEntityID
		inner join stc.StockReceiptItem i  on h.StockReceiptID = i.StockReceiptID
		left join 
		 stc.StockReceiptItemTrace t on i.StockReceiptItemID=t.StockReceiptItemID
		where h.FinancialPeriodID = @pFinancialPeriodID
		)x pivot
			( max(Value)
					for TraceID in ( ' + @Columns + N')
				) p ' + REPLACE(@ConditionalInnerJoin,'@','P');

    EXECUTE sp_executesql @Query,
                          N'@pFinancialPeriodID INT',
                          @pFinancialPeriodID = @FinancialPeriodID

    INSERT INTO #ValidationTemp
    SELECT DISTINCT
           position,
           'STC_sp_UndoPricingValidation_3'
    FROM STC.RevisionCostItem rci
        JOIN STC.RevisionCost rc
            ON rc.RevisionCostID = rci.RevisionCostID
        JOIN CheckUndoPricingValidationTemp
            ON CheckUndoPricingValidationTemp.StockReceiptItemID = rci.StockReceiptItemID
    WHERE rc.AutoGenerated = 1
          AND rc.PreVoucherID IS NOT NULL
          AND rc.Date >= @PricingDate;


    SET @Message = N'برخی از رسیدهای مونتاژ، تبدیل یا انتقالی دارای پیش نویس سند می‌باشند.';

    INSERT INTO #ValidationTemp
    SELECT DISTINCT
           position,
           @Message
    FROM CheckUndoPricingValidationTemp CT
    JOIN STC.StockDocumentType b
        ON b.StockDocumentTypeID = CT.StockDocumentTypeID
    WHERE prevoucherid IS NOT NULL
          AND b.DocumentType IN ( 5, 8, 9 )
          AND CT.Date >= @PricingDate

    IF OBJECT_ID('CheckUndoPricingValidationTemp') IS NOT NULL
        DROP TABLE CheckUndoPricingValidationTemp;


    --** حواله
    SET @Query
        = N'
		select Selected.id position,OutgoingItemID,prevoucherid,OutgoingID,Date,StockReceiptprevoucherid,StuffCompositionID,StockDocumentTypeBaseEntityID
		into CheckUndoPricingValidationTemp
		from
		(
		select  i.OutgoingItemID,TraceID,i.stuffid,h.prevoucherid,h.OutgoingID,h.stockid,
				Case When t.DLID IS NOT NULL THEN cast (t.DLID as nvarchar(max)) 
					When t.TraceItemID IS NOT NULL THEN cast (t.TraceItemID as nvarchar(max)) 
				else Value end Value,h.Date,sr.prevoucherid StockReceiptprevoucherid,i.StuffCompositionID,h.StockDocumentTypeBaseEntityID
		from stc.Outgoing h
		inner join stc.OutgoingItem i  on h.OutgoingID = i.OutgoingID
        left join stc.StockReceiptItem sri on sri.OutgoingItemid = i.OutgoingItemid
        left join stc.StockReceipt sr on sr.StockReceiptID = sri.StockReceiptID
		left join 
		 stc.OutgoingItemTrace t on i.OutgoingItemID=t.OutgoingItemID
		where  h.FinancialPeriodID = @pFinancialPeriodID
		)x pivot
			( max(Value)
					for TraceID in ( ' + @Columns + N')
				) p ' + replace(@ConditionalInnerJoin,'@','P');

    EXECUTE sp_executesql @Query,
                          N'@pFinancialPeriodID INT',
                          @pFinancialPeriodID = @FinancialPeriodID
                      
    INSERT INTO #ValidationTemp
    SELECT DISTINCT
           position,
           'STC_sp_UndoPricingValidation_3'
    FROM STC.RevisionCostItem rci
        JOIN STC.RevisionCost rc
            ON rc.RevisionCostID = rci.RevisionCostID
        JOIN CheckUndoPricingValidationTemp
            ON CheckUndoPricingValidationTemp.OutgoingItemID = rci.OutgoingItemID
    WHERE rc.AutoGenerated = 1
          AND rc.Date >= @PricingDate
          AND rc.PreVoucherID IS NOT NULL;

    INSERT INTO #ValidationTemp
    SELECT DISTINCT
           position,
            'STC_sp_UndoPricingValidation_5'
    FROM CheckUndoPricingValidationTemp
    WHERE prevoucherid IS NOT NULL
          AND Date >= @PricingDate;


    INSERT INTO #ValidationTemp
    SELECT DISTINCT
           position,
           'تعدادی از حواله های دارایی ثابت تبدیل به رسید دارایی شده اند.'
    FROM CheckUndoPricingValidationTemp ct
        JOIN AST.AssetReceiptItem c
            ON c.OutgoingItemID = ct.OutgoingItemID
    WHERE ct.Date >= @PricingDate
	and c.BaseValue <> 0;

    INSERT INTO #ValidationTemp
    SELECT DISTINCT
           position,
           'تعدادی از حواله های مصرف دارایی ثابت در هزینه های بهره برداری رسید دارایی استفاده شده اند.'
    FROM CheckUndoPricingValidationTemp ct
        JOIN AST.UtilizationCost c
            ON c.OutgoingItemID = ct.OutgoingItemID
    WHERE ct.Date >= @PricingDate
	and c.Price <> 0;

    INSERT INTO #ValidationTemp
    SELECT DISTINCT
           position,
           'تعدادی از حواله های مصرف دارایی ثابت در تعمیرات دارایی استفاده شده اند.'
    FROM CheckUndoPricingValidationTemp ct
        JOIN AST.RepairStuffCost c
            ON c.OutgoingItemID = ct.OutgoingItemID
    WHERE ct.Date >= @PricingDate
	and c.Price <> 0;


    INSERT INTO #ValidationTemp
    SELECT DISTINCT
           position,
           case when b.DocumentType = 4 then 'رسید انتقالی های با مبدا این رکورد، دارای پیش نویس هستند.'
                when b.DocumentType = 15 then 'رسیدهای دوباره کاری با مبدا این رکورد، دارای پیش نویس هستند.'
                end
    FROM CheckUndoPricingValidationTemp ct
    join stc.StockDocumentTypeBaseEntity a on ct.StockDocumentTypeBaseEntityID = a.StockDocumentTypeBaseEntityID
    join stc.StockDocumentType b on a.StockDocumentTypeID = b.StockDocumentTypeID
    WHERE StockReceiptprevoucherid is not null
    and  ct.Date >= @PricingDate
     

    INSERT INTO #ValidationTemp
    SELECT DISTINCT
           position,
           'رسید ترکیب های با مبدا این رکورد، دارای پیش نویس هستند.'
    FROM CheckUndoPricingValidationTemp ct
    join stc.StuffComposition sc on sc.StuffCompositionID = ct.StuffCompositionid
    join stc.StockReceiptItem sri on sri.StockReceiptItemID = sc.StockReceiptItemID
    join stc.StockReceipt sr on sr.StockReceiptID = sri.StockReceiptID
    WHERE sr.PreVoucherID is not null
    and  ct.Date >= @PricingDate
    

    INSERT INTO #ValidationTemp
    SELECT DISTINCT
           position,
           'رسید تبدیل های با مبدا این رکورد، دارای پیش نویس هستند.'
    FROM CheckUndoPricingValidationTemp ct
    join stc.ConvertSpecification sc on sc.OutgoingItemID = ct.OutgoingItemID
    join stc.StockReceiptItem sri on sri.ConvertSpecificationID = sc.ConvertSpecificationID
    join stc.StockReceipt sr on sr.StockReceiptID = sri.StockReceiptID
    WHERE sr.PreVoucherID is not null
    and  ct.Date >= @PricingDate

    INSERT INTO #ValidationTemp
    SELECT DISTINCT
           position,
           'دریافت از پیمانکارهای با مبدا این رکورد، دارای پیش نویس هستند.'
    FROM CheckUndoPricingValidationTemp ct
    join stc.StockReceiptChargingService sc on sc.OutgoingItemID = ct.OutgoingItemID
    join stc.StockReceiptItem sri on sri.StockReceiptItemID = sc.StockReceiptItemID
    join stc.StockReceipt sr on sr.StockReceiptID = sri.StockReceiptID
    WHERE sr.PreVoucherID is not null
    and  ct.Date >= @PricingDate

    IF OBJECT_ID('CheckUndoPricingValidationTemp') IS NOT NULL
        DROP TABLE CheckUndoPricingValidationTemp;



    -- حواله های تبدیل، ترکیب، کارمزدی یا انتقالی که انبار مقصد آنها برای برگشت انتخاب نشده اند
    BEGIN

        SELECT @And = 
				ISNULL(STUFF((SELECT DISTINCT ' AND (&.' + QUOTENAME(TraceID) + ' is null or @.' + QUOTENAME(TraceID) + '= &.'+ QUOTENAME(TraceID) + ')'
								FROM STF.Trace
								WHERE PricingBase = 1
						FOR XML PATH(''), TYPE
					  ).value('.', 'NVARCHAR(MAX)'),1,0,''),'');

        SET @Query = N'
		select Selected.id position,a.*
		into CheckUndoPricingValidationTemp
		from 
		(
		select  *
		from STC.VWStockReceiptWithBase
		where FinancialPeriodID = @pFinancialPeriodID
		and   OriginDate >= @pDate
		)a
		left join 
		(select OutgoingItemID,
				TraceID,
				Case 
					When DLID IS NOT NULL THEN cast (DLID as nvarchar(max)) 
					When TraceItemID IS NOT NULL THEN cast (TraceItemID as nvarchar(max)) 
				else Value end Value
		from stc.OutgoingItemTrace
		)x
		pivot
		(
		max(Value)
		for TraceID in ( ' + @Columns + ')
		)oit on a.OutgoingItemID=oit.OutgoingItemID
		left join 
		(select stockreceiptitemID,
				TraceID,
				Case 
					When DLID IS NOT NULL THEN cast (DLID as nvarchar(max)) 
					When TraceItemID IS NOT NULL THEN cast (TraceItemID as nvarchar(max)) 
				else Value end Value
		from stc.stockreceiptitemTrace
		)x
		pivot
			(
			max(Value)
			for TraceID in ( ' + @Columns + ')
			)sit on a.stockreceiptitemID=sit.stockreceiptitemID
		join ##Selected Selected on Selected.stuffid = a.OriginStuff AND Selected.StockID = a.OriginStock ' 
		 + replace(replace(@And,'&','Selected') ,'@','oit') + N'
		left join ##Selected Selected2 on Selected2.stuffid = a.DestinationStuff AND Selected2.StockID = a.DestinationStock ' 
		 + replace(replace(@And,'&','Selected2') ,'@','sit') +
		'
		where Selected2.stuffid is null and a.OriginDate <= Selected.LastPricingDate and a.DestinationDate <= Selected2.LastPricingDate 
		'
        EXECUTE sp_executesql @Query,
                              N'@pFinancialPeriodID INT,@pDate Date',
                              @pFinancialPeriodID = @FinancialPeriodID,
                              @pDate = @PricingDate;

        INSERT INTO #ValidationTemp
		SELECT DISTINCT
           position,
           'کاردکس کالای '+b.code+' در انبار '+c.Title+' به این ردیف وابسته است و باید در عملیات برگشت قیمت گذاری شرکت نماید.'
        FROM CheckUndoPricingValidationTemp a
		join stf.VWStuff b on a.DestinationStuff = b.StuffID
		join stf.Stock c on c.StockID = a.DestinationStock

    END;
    IF OBJECT_ID('CheckUndoPricingValidationTemp') IS NOT NULL
        DROP TABLE CheckUndoPricingValidationTemp;


    --**برگشت حواله
    SET @Query
        = N'
		select Selected.id position,ReturnedOutgoingItemID,prevoucherid,ReturnedOutgoingID,Date,OutgoingItemID
		into CheckUndoPricingValidationTemp
		from
		(
		select  i.ReturnedOutgoingItemID,TraceID,i.stuffid,h.prevoucherid,h.ReturnedOutgoingID,h.stockid,
				Case When t.DLID IS NOT NULL THEN cast (t.DLID as nvarchar(max)) 
					 When t.TraceItemID IS NOT NULL THEN cast (t.TraceItemID as nvarchar(max)) 
				else Value end Value,h.Date,OutgoingItemID
		from stc.ReturnedOutgoing h
		inner join stc.ReturnedOutgoingItem i  on h.ReturnedOutgoingID = i.ReturnedOutgoingID
		left join 
		 stc.ReturnedOutgoingItemTrace t on i.ReturnedOutgoingItemID=t.ReturnedOutgoingItemID
		where h.FinancialPeriodID = @pFinancialPeriodID
		)x pivot
			( max(Value)
					for TraceID in ( ' + @Columns + N')
				) p ' + replace(@ConditionalInnerJoin,'@','P');

    EXECUTE sp_executesql @Query,
                          N'@pFinancialPeriodID INT',
                          @pFinancialPeriodID = @FinancialPeriodID

    INSERT INTO #ValidationTemp
    SELECT DISTINCT
           position,
           'STC_sp_UndoPricingValidation_3'
    FROM STC.RevisionCostItem rci
        JOIN STC.RevisionCost rc
            ON rc.RevisionCostID = rci.RevisionCostID
        JOIN CheckUndoPricingValidationTemp
            ON CheckUndoPricingValidationTemp.ReturnedOutgoingItemID = rci.ReturnedOutgoingItemID
    WHERE rc.AutoGenerated = 1
          AND rc.PreVoucherID IS NOT NULL
          AND rc.Date >= @PricingDate;


    INSERT INTO #ValidationTemp
    SELECT DISTINCT
           position,
            'STC_sp_UndoPricingValidation_2'
    FROM CheckUndoPricingValidationTemp
    WHERE prevoucherid IS NOT NULL
          AND Date >= @PricingDate;


    IF OBJECT_ID('CheckUndoPricingValidationTemp') IS NOT NULL
        DROP TABLE CheckUndoPricingValidationTemp;

    SELECT ValidationNo,
           ValidationDesc
    FROM #ValidationTemp;

END TRY
BEGIN CATCH

    DECLARE @ErrorMessage NVARCHAR(4000),
            @ErrorSeverity INT,
            @ErrorState INT;

    SELECT @ErrorMessage = ERROR_MESSAGE(),
           @ErrorSeverity = ERROR_SEVERITY(),
           @ErrorState = ERROR_STATE();

    RAISERROR(   @ErrorMessage,  -- Message text.
                 @ErrorSeverity, -- Severity.
                 @ErrorState     -- State.
             );

END CATCH;
