CREATE 
PROC [ACC].[spVoucherUpdate]
    @VoucherID INT,
    @BranchID INT,
    @FinancialPeriodID INT,
    @DocumentTypeID SMALLINT,
    @Number INT,
    @ReferenceNumber INT,
    @DailyNumber INT,
    @SubNumber NVARCHAR(256),
    @Date DATE,
    @VoucherStatusID SMALLINT,
    @Description NVARCHAR(MAX),
    @Description2 NVARCHAR(MAX),
    @Version INT,
    @Total DECIMAL(36, 10),
    @AutoGenerated BIT,
    @LastEditor INT ,
    @LastEditionDate DATETIME 

--WITH ENCRYPTION 
AS
BEGIN

    SET NOCOUNT ON;
        DECLARE @Reviewer INT = NULL,
                @StartNum INT = NULL,
                @EndNum INT = NULL,
                @CompanyId INT;

        IF EXISTS
        (
            SELECT VoucherStatusID
            FROM ACC.Voucher
            WHERE VoucherID = @VoucherID
                  AND VoucherStatusID <> 3
        )
           AND @VoucherStatusID = 3
        BEGIN
            SET @Reviewer = CFG.GetuserID();
        END;

        SELECT @CompanyId = b.CompanyID
        FROM CFG.Branch AS b
        WHERE b.BranchID = @BranchID;


        IF EXISTS
        (
            SELECT [Version]
            FROM [ACC].[Voucher]
            WHERE [VoucherID] = @VoucherID
                  AND @Version <> [Version]
        )
            RAISERROR('Version mismatch...', 16, 10);


        SELECT @StartNum = StartNum,
               @EndNum = EndNum
        FROM CFG.DocumentNum
        WHERE DocumentNumTypeID = 1
              AND FinancialPeriodID = @FinancialPeriodID; 

        IF (@Number = 0 OR @Number IS NULL)
            SET @Number = ISNULL(
                          (
                              SELECT MAX(v.Number) + 1
                              FROM [ACC].[Voucher] v
                                  JOIN CFG.Branch AS b
                                      ON b.BranchID = v.BranchID
                              WHERE v.FinancialPeriodID = @FinancialPeriodID
                                    AND b.CompanyID = @CompanyId
                          ),
                          1
                                );

        IF EXISTS
        (
            SELECT 1
            FROM [ACC].[Voucher] v
                JOIN CFG.Branch AS b
                    ON b.BranchID = v.BranchID
            WHERE v.VoucherID <> @VoucherID
                  AND v.Number = @Number
                  AND v.FinancialPeriodID = @FinancialPeriodID
                  AND b.CompanyID = @CompanyId
        )
        BEGIN
            RAISERROR(N'Accounting.DuplicateVoucherNumber', 16, 12);
        END;

        IF (@Number >= @StartNum AND (@EndNum IS NULL OR @Number <= @EndNum))
        BEGIN
            DECLARE @lastDate DATE;

            SELECT @lastDate = v.Date
            FROM ACC.Voucher v
            WHERE v.VoucherID = @VoucherID;

            IF (@lastDate <> @Date)
            BEGIN
                SET @DailyNumber = ISNULL(
                                   (
                                       SELECT MAX(v.DailyNumber) + 1
                                       FROM [ACC].[Voucher] AS v
                                           JOIN CFG.Branch AS b
                                               ON b.BranchID = v.BranchID
                                       WHERE v.Date = @Date
                                             AND b.CompanyID = @CompanyId
                                   ),
                                   1
                                         );
            END;

            UPDATE [ACC].[Voucher]
            SET [BranchID] = @BranchID,
                [DocumentTypeID] = @DocumentTypeID,
                [Number] = @Number,
                [DailyNumber] = @DailyNumber,
                [SubNumber] = @SubNumber,
                [Date] = @Date,
                [VoucherStatusID] = @VoucherStatusID,
                [Description] = @Description,
                [Description2] = @Description2,
                [LastEditor] = @LastEditor,
                [LastEditionDate] = @LastEditionDate,
                [Version] = @Version + 1,
                [Total] = @Total,
                [Reviewer] = @Reviewer,
                [AutoGenerated] = @AutoGenerated
            WHERE [VoucherID] = @VoucherID;

            -- Begin Return Select <- do not remove
            SELECT [Version]
            FROM [ACC].[Voucher]
            WHERE [VoucherID] = @VoucherID;
        -- End Return Select <- do not remove
        END;
        ELSE
        BEGIN

            RAISERROR('InvalidNumberRange', 16, 12);
        END;

END;
