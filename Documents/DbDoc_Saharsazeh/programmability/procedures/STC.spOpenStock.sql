CREATE   PROC [STC].spOpenStock
    @FinancialPeriodID INT ,
    @StockID INT ,
    @Status TINYINT    	
	--WITH ENCRYPTION 
AS
SET NOCOUNT ON; 

	
BEGIN TRY
	DECLARE @NextFinancialPeriod     INT,
	        @StartDate               DATETIME = NULL,
	        @StockReceipt            INT,
	        @StockReceiptVersion     INT,
	        @Message                 NVARCHAR(MAX);
	
	
	SET @StartDate = (
	        SELECT MIN(StartDate)
	        FROM   CFG.FinancialPeriod
	        WHERE  StartDate > (
	                   SELECT EndDate
	                   FROM   CFG.FinancialPeriod
	                   WHERE  FinancialPeriodID = @FinancialPeriodID
	               )
	    );
	SET @NextFinancialPeriod = (
	        SELECT FinancialPeriodID
	        FROM   CFG.FinancialPeriod
	        WHERE  StartDate = @StartDate
	    );
	
	SELECT @StockReceipt = sr.StockReceiptID,
	       @StockReceiptVersion = sr.[Version]
	FROM   STC.StockReceipt sr 
        JOIN [STC].[StockDocumentTypeBaseEntity] sdtb
            ON sr.StockDocumentTypeBaseEntityID = sdtb.StockDocumentTypeBaseEntityID
	       JOIN STC.StockDocumentType sdt
	            ON  sdt.StockDocumentTypeID = sdtb.StockDocumentTypeID
	WHERE  sr.FinancialPeriodID = @NextFinancialPeriod
	       AND sr.AutoGenerated = 1
	       AND sdt.DocumentType = 7
	       AND sr.StockID = @StockID;
	
	DECLARE @ItemIDs VARCHAR(MAX);
	IF @Status = 1
	BEGIN
	    SET @ItemIDs = STUFF(
	            (
	                SELECT ',' + CAST(i.StockReceiptItemID as VARCHAR(256))
	                FROM   STC.StockReceipt h
					JOIN [STC].[StockDocumentTypeBaseEntity] sdtb
						ON h.StockDocumentTypeBaseEntityID = sdtb.StockDocumentTypeBaseEntityID
	                       JOIN STC.StockDocumentType sdt
	                            ON  sdt.StockDocumentTypeID = sdtb.StockDocumentTypeID
	                       JOIN STC.StockReceiptItem i
	                            ON  i.StockReceiptID = h.StockReceiptID
	                WHERE  FinancialPeriodID = @NextFinancialPeriod
	                       AND StockID = @StockID
	                       AND sdt.[DocumentType] = 2
	                       AND AutoGenerated = 1
	                           FOR XML PATH('')
	            ),
	            1,
	            1,
	            ''
	        );
	    
	    DECLARE @LastStatus TINYINT;
	    
	    SET @LastStatus = (
	            SELECT [Status]
	            FROM   [STC].[StockClosingOperation]
	            WHERE  [FinancialPeriodID] = @FinancialPeriodID
	                   AND StockID = @StockID
	        );
	    
	    IF @LastStatus = 2
	    BEGIN
	        RAISERROR('STC_spOpenStock_1', 16, 12);
	    END;
	    
	    
	    IF @StockReceipt IS NOT NULL
	    BEGIN
	        EXEC STC.spStockReceiptDelete @StockReceipt,
	             @StockReceiptVersion;
	    END;
	    
	    
	    DELETE 
	    FROM   STC.StockClosingOperation
	    WHERE  StockID = @StockID
	           AND FinancialPeriodID = @FinancialPeriodID;
	END;
	
	IF @Status = 2
	BEGIN
	    IF EXISTS (
	           SELECT *
	           FROM   stc.PricingItem [pi]
	           WHERE  LastPricingDate >= (
	                      SELECT startdate
	                      FROM   cfg.financialperiod
	                      WHERE  financialperiodid = @NextFinancialPeriod
	                  )
	                  AND (StockID is null OR StockID = @StockID)
	       )
	        RAISERROR(
	            'در دوره مالی بعد عملیات قیمت گذاری انجام شده است.',
	            16,
	            12
	        );
	    
	    UPDATE s
	    SET    Fee       = 0,
	           Price     = 0
	    FROM   STC.StockReceiptItem s
	    WHERE  s.StockReceiptID = @StockReceipt;
	    
	    UPDATE s
	    SET    TotalInvoicePrice     = 0,
	           TotalNetPrice         = 0
	    FROM   STC.StockReceipt s
	    WHERE  s.StockReceiptID = @StockReceipt;
	    
	    
	    UPDATE STC.StockClosingOperation
	    SET    STATUS                    = 1
	    WHERE  StockID                   = @StockID
	           AND FinancialPeriodID     = @FinancialPeriodID;
	END;
END TRY
BEGIN CATCH
	DECLARE @ErrorMessage NVARCHAR(4000);
	DECLARE @ErrorSeverity INT;
	DECLARE @ErrorState INT;
	
	SELECT @ErrorMessage = ERROR_MESSAGE(),
	       @ErrorSeverity     = ERROR_SEVERITY(),
	       @ErrorState        = ERROR_STATE();
	
	
	RAISERROR (
	    @ErrorMessage,	-- Message text.
	    @ErrorSeverity,	-- Severity.
	    @ErrorState -- State.
	);
END CATCH;
