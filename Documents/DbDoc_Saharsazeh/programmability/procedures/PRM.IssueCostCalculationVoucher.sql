CREATE   proc PRM.IssueCostCalculationVoucher
(
	@CostCalculationPeriodID int,
	@SubNumber NVARCHAR(256) ,
	@Date DATETIME ,
	@Number INT,
	@DocumentTypeId int,
	@Description           NVARCHAR(MAX) = NULL,
    @Description2          NVARCHAR(MAX) = NULL
)
as

	DECLARE @User INT,
			@FinancialPeriodID int,
			@EndDate Date,
			@StartDate Date,
			@CurrentDate Date,
			@VoucherID int,
			@MaxVoucherItemID int
        
	SET @User = cfg.GetuserID();
	SET @CurrentDate = GETDATE();
	 

	select  @FinancialPeriodID = FinancialPeriodID,
			@EndDate = EndDate,
			@StartDate = StartDate
	from prm.CostCalculationPeriod
	where CostCalculationPeriodID = @CostCalculationPeriodID


	create table #Voucher
	(
	[VoucherID] int,
	[Version] int,
    [Number] int,
    [ReferenceNumber] int,
    [DailyNumber] int,
    [Reviewer] int,
	)
	insert into #Voucher
	exec [ACC].spVoucherInsert
				-1, --@BranchID  ,
				@FinancialPeriodID  ,
				@DocumentTypeId, --@DocumentTypeID  ,
				@Number, --@Number  ,
				null, --@ReferenceNumber  ,
				null, --@DailyNumber  ,
				@SubNumber, --@SubNumber  ,
				@Date, --@Date  ,
				1, --@VoucherStatusID  ,
				@Description  ,
				@Description2  ,
				0, --@Total ,
				1, --@AutoGenerated 
				@User, --@Creator,
				@CurrentDate --@CreationDate,

	select @VoucherID = [VoucherID]
	from #Voucher

	update PRM.CostCalculation
	set [VoucherID] = @VoucherID
	where CostCalculationPeriodID = @CostCalculationPeriodID

	select @MaxVoucherItemID = MAX(VoucherItemID)
	from acc.VoucherItem

	declare @CostCenterDlTYpe int
	select @CostCenterDlTYpe = DlTypeID
	from acc.DlType
	where code = 102

	select  SlDl.SlID,
			cc.DlID,
			SUM(ShareOfCost) Cost,
			ROW_NUMBER() over(order by SlDl.SlID) RowIndex,
			@MaxVoucherItemID + ROW_NUMBER() over(order by SlDl.slid) ID
		into #WorkInProgress
	from prm.PeriodProduction pp
	join prm.PeriodProductionOtherCost oc on pp.PeriodProductionID = oc.PeriodProductionID
	join stf.StuffDetail sd on sd.StuffID = pp.StuffID
	join cfg.CostCenter cc on cc.CostCenterID = pp.CostCenterId
	join stf.StockDocumentTypeSlDl SlDl on SlDl.StuffAccountGroupID = sd.StuffAccountGroupID
	join stc.StockDocumentType sdt on sdt.StockDocumentTypeID = SlDl.StockDocumentTypeID and sdt.Type = 1 and Sdt.DocumentType = 0 and DlTypeID = @CostCenterDlTYpe
	where pp.CostCalculationPeriodID = @CostCalculationPeriodID 
	group by SlDl.SlID,cc.DlID
	having SUM(ShareOfCost)<>0

	if exists (select * from #WorkInProgress where SlID is null)
	begin
	raiserror('برای برخی از گروه حسابها معین تولید مرکز انتخاب نشده است',16,13)
	return
	end

	set identity_insert [ACC].[VoucherItem] on
	INSERT INTO [ACC].[VoucherItem]
			   (VoucherItemID
			   ,[VoucherID]
			   ,[VoucherItemIndex]
			   ,[SlID]
			   ,[Description]
			   ,[Description2]
			   ,[Debit]
			   ,[Credit]
			   ,[CurrencyID]
			   ,[CurrencyRate]
			   ,[CurrencyDebit]
			   ,[CurrencyCredit]
			   ,[Creator]
			   ,[CreationDate]
			   ,[LastEditor]
			   ,[LastEditionDate]
			   ,[Version])

	select		id
				,@VoucherID
			   ,RowIndex
			   ,[SlID]
			   ,N'تخصیص عوامل جمع آوری شده به کار در جریان ساخت'
			   ,N'خصیص عوامل جمع آوری شده به کار در جریان ساخت'
			   ,case when Cost  > 0 then Cost else 0 end
			   ,case when Cost  < 0 then -Cost else 0 end
			   ,-1
			   ,1
			   ,case when Cost  > 0 then Cost else 0 end
			   ,case when Cost  < 0 then -Cost else 0 end
			   ,@User
			   ,GETDATE()
			   ,@User
			   ,GETDATE()
			   ,0
	from #WorkInProgress
	where Cost <> 0
	set identity_insert [ACC].[VoucherItem] off

	INSERT INTO [ACC].[AccountLevelVoucherItem]
			   ([VoucherItemID]
			   ,[AccountLevelID]
			   ,[DlID]
			   ,[Value]
			   ,[Creator]
			   ,[CreationDate]
			   ,[LastEditor]
			   ,[LastEditionDate]
			   ,[Version])
	select id
			   ,[AccountLevelID]
			   ,[DlID]
			   ,null
			   ,[Creator]
			   ,[CreationDate]
			   ,[LastEditor]
			   ,[LastEditionDate]
			   ,[Version]
	from #WorkInProgress a
	join acc.AccountLevelSL b on a.SlID = b.SlID and DlTypeID = 27
	where Cost <> 0


	select @MaxVoucherItemID = MAX(VoucherItemID)
	from acc.VoucherItem

	declare @MaxRowIndex int
	select @MaxRowIndex = RowIndex
	from #WorkInProgress

	select  SlID,
			cc.DlID,
			Cost,
			@MaxRowIndex + ROW_NUMBER() over(order by slid) RowIndex,
			@MaxVoucherItemID + ROW_NUMBER() over(order by slid) ID
	into #VoucherItem
	from prm.OtherCost a
	join cfg.CostCenter cc on cc.CostCenterID = a.CostCenterId
	where CostCalculationPeriodID = @CostCalculationPeriodID
	and cost<>0



	set identity_insert [ACC].[VoucherItem] on
	INSERT INTO [ACC].[VoucherItem]
			   (VoucherItemID
			   ,[VoucherID]
			   ,[VoucherItemIndex]
			   ,[SlID]
			   ,[Description]
			   ,[Description2]
			   ,[Debit]
			   ,[Credit]
			   ,[CurrencyID]
			   ,[CurrencyRate]
			   ,[CurrencyDebit]
			   ,[CurrencyCredit]
			   ,[Creator]
			   ,[CreationDate]
			   ,[LastEditor]
			   ,[LastEditionDate]
			   ,[Version])

	select		ID
			   ,@VoucherID
			   ,RowIndex
			   ,[SlID]
			   ,N'بهای تمام شده عامل جمع آوری شده'
			   ,N'بهای تمام شده'
			   ,case when Cost  < 0 then -Cost else 0 end
			   ,case when Cost  > 0 then Cost else 0 end
			   ,-1
			   ,1
			  ,case when Cost  < 0 then -Cost else 0 end
			   ,case when Cost  > 0 then Cost else 0 end
			   ,@User
			   ,GETDATE()
			   ,@User
			   ,GETDATE()
			   ,0
	from #VoucherItem
	set identity_insert [ACC].[VoucherItem] off


	INSERT INTO [ACC].[AccountLevelVoucherItem]
			   ([VoucherItemID]
			   ,[AccountLevelID]
			   ,[DlID]
			   ,[Value]
			   ,[Creator]
			   ,[CreationDate]
			   ,[LastEditor]
			   ,[LastEditionDate]
			   ,[Version])
	select id
			   ,[AccountLevelID]
			   ,[DlID]
			   ,null
			   ,[Creator]
			   ,[CreationDate]
			   ,[LastEditor]
			   ,[LastEditionDate]
			   ,[Version]
	from #VoucherItem a
	join acc.AccountLevelSL b on a.SlID = b.SlID and DlTypeID = 27


	select @MaxVoucherItemID = MAX(VoucherItemID)
	from acc.VoucherItem

	select @MaxRowIndex =  MAX(VoucherItemIndex)
	from acc.VoucherItem
	where VoucherID = @VoucherID

	select  SlDl.SlID,
			cc.DlID,
			sum(price) price,
			@MaxRowIndex + ROW_NUMBER() over(order by SlDl.SlID) RowIndex,
			@MaxVoucherItemID + ROW_NUMBER() over(order by SlDl.slid) ID
		into #DebitProductionDelivery
	from prm.ProductionDelivery pd
	join prm.ProductionDeliveryItem pdi on pd.ProductionDeliveryID = pdi.ProductionDeliveryID
	join stf.StuffDetail sd on sd.StuffID = pdi.StuffID
	join cfg.CostCenter cc on cc.CostCenterID = pd.DeliverCostCenterId
	join stf.StockDocumentTypeSlDl SlDl on SlDl.StuffAccountGroupID = sd.StuffAccountGroupID
	join stc.StockDocumentType sdt on sdt.StockDocumentTypeID = SlDl.StockDocumentTypeID and sdt.Type = 1 and Sdt.DocumentType = 0 and DlTypeID = @CostCenterDlTYpe
	where pd.Date between @StartDate and @EndDate  and price <> 0
	group by SlDl.SlID,cc.DlID
		having sum(price)<>0


	if exists (select * from #DebitProductionDelivery where SlID is null)
	begin
	raiserror('برای برخی از گروه حسابها معین تولید مرکز انتخاب نشده است',16,13)
	return
	end




	set identity_insert [ACC].[VoucherItem] on
	INSERT INTO [ACC].[VoucherItem]
			   (VoucherItemID
			   ,[VoucherID]
			   ,[VoucherItemIndex]
			   ,[SlID]
			   ,[Description]
			   ,[Description2]
			   ,[Debit]
			   ,[Credit]
			   ,[CurrencyID]
			   ,[CurrencyRate]
			   ,[CurrencyDebit]
			   ,[CurrencyCredit]
			   ,[Creator]
			   ,[CreationDate]
			   ,[LastEditor]
			   ,[LastEditionDate]
			   ,[Version])

	select		id
				,@VoucherID
			   ,RowIndex
			   ,[SlID]
			   ,N'تحویل تولید'
			   ,N'تحویل تولید'
			   ,price
			   ,0
			   ,-1
			   ,1
			   ,price
			   ,0
			   ,@User
			   ,GETDATE()
			   ,@User
			   ,GETDATE()
			   ,0
	from #DebitProductionDelivery
	set identity_insert [ACC].[VoucherItem] off

	INSERT INTO [ACC].[AccountLevelVoucherItem]
			   ([VoucherItemID]
			   ,[AccountLevelID]
			   ,[DlID]
			   ,[Value]
			   ,[Creator]
			   ,[CreationDate]
			   ,[LastEditor]
			   ,[LastEditionDate]
			   ,[Version])
	select id
			   ,[AccountLevelID]
			   ,[DlID]
			   ,null
			   ,[Creator]
			   ,[CreationDate]
			   ,[LastEditor]
			   ,[LastEditionDate]
			   ,[Version]
	from #DebitProductionDelivery a
	join acc.AccountLevelSL b on a.SlID = b.SlID and DlTypeID = @CostCenterDlTYpe

	select @MaxVoucherItemID = MAX(VoucherItemID)
	from acc.VoucherItem

	select @MaxRowIndex =  MAX(VoucherItemIndex)
	from acc.VoucherItem
	where VoucherID = @VoucherID

	select  SlDl.SlID,
			cc.DlID,
			sum(price) price,
			@MaxRowIndex + ROW_NUMBER() over(order by SlDl.SlID) RowIndex,
			@MaxVoucherItemID + ROW_NUMBER() over(order by SlDl.slid) ID
		into #CreditProductionDelivery
	from prm.ProductionDelivery pd
	join prm.ProductionDeliveryItem pdi on pd.ProductionDeliveryID = pdi.ProductionDeliveryID
	join stf.StuffDetail sd on sd.StuffID = pdi.StuffID
	join cfg.CostCenter cc on cc.CostCenterID = pd.CostCenterId
	join stf.StockDocumentTypeSlDl SlDl on SlDl.StuffAccountGroupID = sd.StuffAccountGroupID
	join stc.StockDocumentType sdt on sdt.StockDocumentTypeID = SlDl.StockDocumentTypeID  and sdt.Type = 2 and Sdt.DocumentType = 2 and DlTypeID = @CostCenterDlTYpe
	where pd.Date between @StartDate and @EndDate  and price <> 0
	group by SlDl.SlID,cc.DlID
	having sum(price)<>0


	if exists (select * from #CreditProductionDelivery where SlID is null)
	begin
	raiserror('برای برخی از گروه حسابها معین مصرف مرکز انتخاب نشده است',16,13)
	return
	end

	set identity_insert [ACC].[VoucherItem] on
	INSERT INTO [ACC].[VoucherItem]
			   (VoucherItemID
			   ,[VoucherID]
			   ,[VoucherItemIndex]
			   ,[SlID]
			   ,[Description]
			   ,[Description2]
			   ,[Debit]
			   ,[Credit]
			   ,[CurrencyID]
			   ,[CurrencyRate]
			   ,[CurrencyDebit]
			   ,[CurrencyCredit]
			   ,[Creator]
			   ,[CreationDate]
			   ,[LastEditor]
			   ,[LastEditionDate]
			   ,[Version])

	select		id
				,@VoucherID
			   ,RowIndex
			   ,[SlID]
			   ,N'تحویل تولید'
			   ,N'تحویل تولید'
			   ,0
			   ,price
			   ,-1
			   ,1
			   ,0
			   ,price
			   ,@User
			   ,GETDATE()
			   ,@User
			   ,GETDATE()
			   ,0
	from #CreditProductionDelivery
	set identity_insert [ACC].[VoucherItem] off

	INSERT INTO [ACC].[AccountLevelVoucherItem]
			   ([VoucherItemID]
			   ,[AccountLevelID]
			   ,[DlID]
			   ,[Value]
			   ,[Creator]
			   ,[CreationDate]
			   ,[LastEditor]
			   ,[LastEditionDate]
			   ,[Version])
	select id
			   ,[AccountLevelID]
			   ,[DlID]
			   ,null
			   ,[Creator]
			   ,[CreationDate]
			   ,[LastEditor]
			   ,[LastEditionDate]
			   ,[Version]
	from #CreditProductionDelivery a
	join acc.AccountLevelSL b on a.SlID = b.SlID and DlTypeID = @CostCenterDlTYpe


	BEGIN TRY

		EXEC ACC.ValidateVouchers @voucherIDs = @VoucherID,	-- nvarchar(max)
			 @currentFinancialPeriodID = @FinancialPeriodID,	-- int
			 @isDelete = 0,	-- bit
			 @voucherItemIds = DEFAULT -- nvarchar(max)
	          
	END TRY
	BEGIN CATCH
		DECLARE @ErrorMessage NVARCHAR(4000);
		DECLARE @ErrorSeverity INT;
		DECLARE @ErrorState INT;

		SELECT @ErrorMessage = ERROR_MESSAGE(),
			   @ErrorSeverity = ERROR_SEVERITY(),
			   @ErrorState = ERROR_STATE();


		RAISERROR(   @ErrorMessage,  -- Message text.
					 @ErrorSeverity, -- Severity.
					 @ErrorState     -- State.
				 );
		RETURN;
	END CATCH;
