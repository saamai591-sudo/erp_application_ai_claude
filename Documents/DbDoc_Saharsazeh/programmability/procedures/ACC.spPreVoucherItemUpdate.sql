CREATE     PROC [ACC].[spPreVoucherItemUpdate]
    @PreVoucherItemID int,
    @PreVoucherID int,
    @RowIndex int,   
    @SlID int,
    @Description nvarchar(MAX),
    @Description2 nvarchar(MAX),
    @Debit decimal(36, 10),
    @Credit decimal(36, 10),
    @CurrencyID int,
    @CurrencyRate decimal(20, 10),
    @CurrencyDebit decimal(36, 10),
    @CurrencyCredit decimal(36, 10),
    @IsAutoGenerated bit,
    @Creator int,
    @CreationDate datetime,
    @LastEditor int,
    @LastEditionDate datetime,
    @Version int

		--WITH ENCRYPTION 
AS 
	SET NOCOUNT ON 
	
	DECLARE @voucherID INT

	SELECT @voucherID  = VoucherID
	FROM acc.VoucherPrevoucher vp
	WHERE PrevoucherID = @PreVoucherID

	if @Version <> (Select [Version] from [ACC].[PreVoucherItem]
	where [PreVoucherItemID] = @PreVoucherItemID)
	OR @voucherID is not null
	RAISERROR('Version mismatch...', 16 , 10)

		UPDATE [ACC].[PreVoucherItem]
		SET     [RowIndex] = @RowIndex, 
				
				[SlID] = @SlID, 
				[Description] = @Description, 
				[Description2] = @Description2, 
				[Debit] = @Debit, 
				[Credit] = @Credit, 
				[CurrencyID] = @CurrencyID, 
				[CurrencyRate] = @CurrencyRate, 
				[CurrencyDebit] = @CurrencyDebit, 
				[CurrencyCredit] = @CurrencyCredit, 
				[LastEditor] = @LastEditor, 
				[LastEditionDate] = @LastEditionDate, 
				[Version] = @Version + 1,
				@IsAutoGenerated=IsAutoGenerated
		WHERE  [PreVoucherItemID] = @PreVoucherItemID
	
		-- Begin Return Select <- do not remove
		SELECT [Version]
		FROM   [ACC].[PreVoucherItem]
		WHERE  [PreVoucherItemID] = @PreVoucherItemID	
		-- End Return Select <- do not remove
