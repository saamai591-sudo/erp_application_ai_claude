CREATE   PROCEDURE ACC.spAccCurrencyExchangePrevoucherInsert
	@AccCurrencyExchangeID NVARCHAR(MAX)
--WITH ENCRYPTION 
AS 
	 
	DECLARE @DocumentNumTypeId  INT = (SELECT DocumentNumTypeID FROM CFG.DocumentNumType WHERE EngName = 'AccCurrencyExchange'),
			 @CreatorId INT

	SET @CreatorId = cfg.GetuserID();

    SELECT [value] ID	            
	INTO #DocumentIds
	FROM cfg.R_FnCommaStr2Table(@AccCurrencyExchangeID) 	
				
	if EXISTS (
		SELECT 1 FROM acc.AccCurrencyExchange AS ace
		WHERE ace.AccCurrencyExchangeID = @AccCurrencyExchangeID AND ace.PreVoucherID IS NOT NULL	
	)
	BEGIN
      RAISERROR('BaseEntity.AlreadyIssuedVoucher', 16, 12);
      RETURN 0;
	END;

	-- Insert Into PreVoucher Tabel

	INSERT INTO [ACC].[PreVoucher](
		BranchID,
		[DocumentNumtypeID],
		[Date],
		[FinancialPeriodID],
		[Description],
		[Description2],
		[Creator],
		[CreationDate],
		[LastEditor],
		[LastEditionDate],
		[Version]
    )
	SELECT 
		BranchId,
		@DocumentNumTypeId,
		DATE,
		FinancialPeriodID,
		Description,
		Description2,
		@CreatorId,
		GETDATE(),
		@CreatorId,
		GETDATE(),
		0
	FROM acc.AccCurrencyExchange AS ace
    JOIN #DocumentIds b ON ace.AccCurrencyExchangeID = b.ID 
	WHERE ace.AccCurrencyExchangeID = @AccCurrencyExchangeID




	DECLARE @PrevoucherID INT
	SET @PrevoucherID = SCOPE_IDENTITY()
		
    UPDATE ACC.AccCurrencyExchange
    SET PreVoucherID = @PrevoucherID
    WHERE AccCurrencyExchangeID = @AccCurrencyExchangeID
    
    
    
     SELECT row_number() OVER ( ORDER BY SRC.AccCurrencyExchangeItemID, rno) RowIndex ,* into #Src
      FROM (
 SELECT 1 Rno,
                ace.AccCurrencyExchangeID,
                'ExchangedSl' [Type],
                acei.AccCurrencyExchangeItemID,
                acei.SlID,
                ace.[Description],
                ace.Description2,
                acei.DiffDebit Debit,
                acei.DiffCredit Credit,
                ace.CurrencyID,
                0 CurrencyRate,        
                0 CurrencyDebit,
                0 CurrencyCredit,
                1 IsAutoGenerated
         FROM acc.AccCurrencyExchangeItem   AS acei
         JOIN acc.AccCurrencyExchange AS ace
             ON ace.AccCurrencyExchangeID = acei.AccCurrencyExchangeID
        WHERE acei.AccCurrencyExchangeID = @AccCurrencyExchangeID
 
         UNION ALL

         SELECT 2 Rno,
                ace.AccCurrencyExchangeID,
                'ProfitAndLossSl' as [Type],
                acei.AccCurrencyExchangeItemID,
                s.CurrencyExchangeSLID,
                ace.[Description],
                ace.Description2,
                acei.DiffCredit,
                acei.DiffDebit,
                -1,
                1 CurrencyRate,        
                acei.DiffCredit,
                acei.DiffDebit,
                1 IsAutoGenerated
         FROM acc.AccCurrencyExchangeItem   AS acei
         join acc.SL AS s on s.SlID = acei.SlID
         JOIN acc.AccCurrencyExchange  AS ace
             ON ace.AccCurrencyExchangeID = acei.AccCurrencyExchangeID
         WHERE  acei.AccCurrencyExchangeID = @AccCurrencyExchangeID
 ) src
    
    
    
    
 
     INSERT INTO ACC.PreVoucherItem(
         PreVoucherID,
         RowIndex,
         SlID,
         [Description],
         Description2,
         Debit,
         Credit,
         CurrencyID,
         CurrencyRate,
         CurrencyDebit,
         CurrencyCredit,
         IsAutoGenerated,
         Creator,
         CreationDate,
         LastEditor,
         LastEditionDate,
         Version,
         BaseDocumentName,
         BaseDocumentID
    )
 
     SELECT 
        @PrevoucherID,
        src.RowIndex ,
        SRC.SlID,
        SRC.[Description],
        SRC.Description2,
        src.Debit,
        src.Credit,
        SRC.CurrencyID,
        SRC.CurrencyRate,
        SRC.CurrencyDebit,
        SRC.CurrencyCredit,
        SRC.IsAutoGenerated,
        @CreatorId,
        GETDATE(),
        @CreatorId,
        GETDATE(),
        0,
        'AccCurrencyExchange',
        SRC.AccCurrencyExchangeID
     FROM #SRC src
     

     
     INSERT INTO acc.PreVoucherItemAccountLevel
     (
     	-- PreVoucherItemAccountLevelID -- this column value is auto-generated
     	PreVoucherItemID,
     	AccountLevelID,
     	DlID,
     	[Value],
     	Creator,
     	CreationDate,
     	LastEditor,
     	LastEditionDate,
     	Version
     )
    SELECT pvi.PreVoucherItemID,aceial.AccountLevelID,aceial.DlID,Null,@CreatorId,GETDATE(),@CreatorId,GETDATE(),0
    FROM #Src src
    join acc.PreVoucherItem AS pvi on  src.RowIndex = pvi.RowIndex and pvi.PreVoucherID = @PrevoucherID
    join acc.AccCurrencyExchangeItemAccountLevel AS aceial on src.AccCurrencyExchangeItemID = aceial.AccCurrencyExchangeItemID
    WHERE src.[Type] = 'ExchangedSl'     


     INSERT INTO acc.PreVoucherItemAccountLevel
     (
     	-- PreVoucherItemAccountLevelID -- this column value is auto-generated
     	PreVoucherItemID,
     	AccountLevelID,
     	DlID,
     	[Value],
     	Creator,
     	CreationDate,
     	LastEditor,
     	LastEditionDate,
     	Version
     )
    SELECT pvi.PreVoucherItemID,aceial.AccountLevelID,aceial.DlID,Null,@CreatorId,GETDATE(),@CreatorId,GETDATE(),0
    FROM #Src src
    join acc.PreVoucherItem AS pvi on src.RowIndex = pvi.RowIndex and pvi.PreVoucherID = @PrevoucherID
    join acc.AccCurrencyExchangeItemAccountLevel AS aceial on src.AccCurrencyExchangeItemID = aceial.AccCurrencyExchangeItemID
    join acc.DL AS d on d.DLID = aceial.DlID
    join acc.DlType AS dt on d.DlTypeID = dt.DlTypeID 
    join acc.AccountLevelSL AS als on src.SlID = als.SlID and als.DlTypeID = dt.DlTypeID
    WHERE src.[Type] = 'ProfitAndLossSl'
