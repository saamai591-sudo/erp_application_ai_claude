CREATE PROC [STC].[spRevisionCostUpdate]
    @RevisionCostID INT ,
    @Number INT ,
    @Date DATETIME ,
    @AutoGenerated BIT ,
    @PreVoucherID INT ,
    @FinancialPeriodID INT ,
    @Version INT ,
    @Creator INT ,
    @CreationDate DATETIME ,
    @LastEditor INT ,
    @LastEditionDate DATETIME ,
    @Type TINYINT ,
    @BranchID INT
--WITH ENCRYPTION 
AS
BEGIN
    SET NOCOUNT ON; 

    DECLARE @PreVersion INT ,
        @PrePrevoucher INT;
	
    SELECT  @PreVersion = [Version] ,
            @PrePrevoucher = PreVoucherID
    FROM    [STC].[RevisionCost]
    WHERE   [RevisionCostID] = @RevisionCostID;

    IF @Version <> @PreVersion
        OR @PrePrevoucher IS NOT NULL
        RAISERROR('Version mismatch...', 16 , 10);

    UPDATE  [STC].[RevisionCost]
    SET     [Number] = @Number ,
            [Date] = @Date ,
            [AutoGenerated] = @AutoGenerated ,
            [Version] = @Version + 1 ,
            [LastEditor] = @LastEditor ,
            [LastEditionDate] = @LastEditionDate ,
            [Type] = @Type ,
            BranchID = @BranchID
    WHERE   [RevisionCostID] = @RevisionCostID;

	-- Begin Return Select <- do not remove
    SELECT  [Version] ,
			[Number]
    FROM    [STC].[RevisionCost]
    WHERE   [RevisionCostID] = @RevisionCostID;	
	-- End Return Select <- do not remove
END
