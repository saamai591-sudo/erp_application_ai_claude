CREATE     PROC [STC].spStockReceiptUpdate
    @StockReceiptID INT,
    @AutoGenerated BIT,
    @StockDocumentTypeBaseEntityID INT,
    @StockID INT,
    @DeliverDlID BIGINT,
    @DeliverStockID INT,
    @Number INT,
    @Date DATE,
    @TotalInvoicePrice DECIMAL(30, 4),
    @TotalEstimatedPrice DECIMAL(30, 4),
    @TotalCosts DECIMAL(30, 4),
    @TotalNetPrice DECIMAL(30, 4),
    @PreVoucherID INT,
    @OutgoingID INT,
    @Version INT,
    @Creator INT,
    @CreationDate DATETIME,
    @LastEditor INT,
    @LastEditionDate DATETIME,
    @FinancialPeriodID INT,
    @BaseDocument INT = 1

--WITH ENCRYPTION 
AS
BEGIN
    SET NOCOUNT ON;

    DECLARE @PrePrevoucher INT,
            @PreVersion INT,
            @Message NVARCHAR(MAX);

    SELECT @PreVersion = [Version],
           @PrePrevoucher = PreVoucherID
    FROM [STC].[StockReceipt]
    WHERE [StockReceiptID] = @StockReceiptID;

    IF @Version <> @PreVersion
       OR @PrePrevoucher IS NOT NULL
        RAISERROR('Version mismatch...', 16, 10);

    DECLARE @Type TINYINT,
	@StockDocumentTypeID INT;

	select @StockDocumentTypeID = StockDocumentTypeID 
	from STC.StockDocumentTypeBaseEntity sdtb
	WHERE sdtb.StockDocumentTypeBaseEntityID = @StockDocumentTypeBaseEntityID

    SELECT @Type = [Type]
    FROM STC.StockDocumentType AS sdt
    WHERE sdt.StockDocumentTypeID = @StockDocumentTypeID;

    IF (
           @Type = 7
           AND EXISTS
    (
        SELECT *
        FROM STC.StockReceipt sr	
		join STC.StockDocumentTypeBaseEntity sdtb 
				on sr.StockDocumentTypeBaseEntityID = sdtb.StockDocumentTypeBaseEntityID        
		INNER JOIN STC.StockDocumentType AS sdt
                ON sdt.StockDocumentTypeID = sdtb.StockDocumentTypeID
        WHERE StockReceiptID <> @StockReceiptID
              AND FinancialPeriodID = @FinancialPeriodID
              AND StockID = @StockID
              AND [Type] = 7
    )
       )
    BEGIN
       

        RAISERROR('STC_spStockReceiptInsert_1', 16, 12);
    --RAISERROR (N'برای این انبار قبلا موجودی اول دوره وارد شده است.', -- Message text.
    --		16, -- Severity,
    --		12); -- State

    END;

    DECLARE @StartNum INT = NULL,
            @EndNum INT = NULL,
            @Stock BIT = 0,
            @ResetType BIT = 0,
            @DocumentNumID INT,
            @DocumentNumTypeID INT;


    SELECT @DocumentNumTypeID = DocumentNumTypeID
    FROM CFG.[DocumentNumType]
    WHERE EngName = 'StockReceipt';

    SELECT @StartNum = StartNum,
           @EndNum = EndNum,
           @DocumentNumID = DocumentNumID
    FROM CFG.DocumentNum
    WHERE DocumentNumTypeID = @DocumentNumTypeID
          AND FinancialPeriodID = @FinancialPeriodID;

    IF EXISTS
    (
        SELECT *
        FROM CFG.DocumentNumResetNumberBase
        WHERE DocumentNumID = @DocumentNumID
              AND DocumentNumResetNumberBaseTypeID = 3
    )
    BEGIN
        SET @Stock = 1;
    END;

    IF (
           @Type = 7
           OR EXISTS
    (
        SELECT *
        FROM CFG.DocumentNumResetNumberBase
        WHERE DocumentNumID = @DocumentNumID
              AND DocumentNumResetNumberBaseTypeID = 2
    )
       )
    BEGIN
        SET @ResetType = 1;
    END;


    IF (@Number = 0 OR @Number IS NULL)
    BEGIN
        SET @Number = ISNULL(
                      (
                          SELECT MAX(Number) + 1
                          FROM [STC].[StockReceipt] sr
						  JOIN [STC].[StockDocumentTypeBaseEntity] sdtb
								ON sr.StockDocumentTypeBaseEntityID = sdtb.StockDocumentTypeBaseEntityID
                          WHERE FinancialPeriodID = @FinancialPeriodID
                                AND
                                (
                                    @Stock = 0
                                    OR StockID = @StockID
                                )
                                AND
                                (
                                    @ResetType = 0
                                    OR sdtb.StockDocumentTypeID = @StockDocumentTypeID
                                )
                      ),
                      @StartNum
                            );
    END;
    ELSE
    BEGIN
        IF (EXISTS
        (
            SELECT *
            FROM [STC].[StockReceipt] sr
			JOIN [STC].[StockDocumentTypeBaseEntity] sdtb
				ON sr.StockDocumentTypeBaseEntityID = sdtb.StockDocumentTypeBaseEntityID
            WHERE StockReceiptID <> @StockReceiptID
                  AND FinancialPeriodID = @FinancialPeriodID
                  AND
                  (
                      @Stock = 0
                      OR StockID = @StockID
                  )
                  AND
                  (
                      @ResetType = 0
                      OR sdtb.StockDocumentTypeID = @StockDocumentTypeID
                  )
                  AND Number = @Number
        )
           )
        BEGIN --NumberIsDuplicate			
           
            RAISERROR('NumberIsDuplicate', 16, 12);
        --RAISERROR('شماره وارد شده تکراری است.', 16, 12)

        END;
    END;

    IF (@Number >= @StartNum AND (@EndNum IS NULL OR @Number <= @EndNum))
    BEGIN



        UPDATE [STC].[StockReceipt]
        SET [AutoGenerated] = @AutoGenerated,
            [StockDocumentTypeBaseEntityID] = @StockDocumentTypeBaseEntityID,
            [StockID] = @StockID,
            [DeliverDlID] = @DeliverDlID,
            [DeliverStockID] = @DeliverStockID,
            [Number] = @Number,
            [Date] = @Date,
            [TotalInvoicePrice] = @TotalInvoicePrice,
            [TotalEstimatedPrice] = @TotalEstimatedPrice,
            [TotalCosts] = @TotalCosts,
            [TotalNetPrice] = @TotalNetPrice,
            [OutgoingID] = @OutgoingID,
            [Version] = @Version + 1,
            [LastEditor] = @LastEditor,
            [LastEditionDate] = @LastEditionDate
        WHERE [StockReceiptID] = @StockReceiptID;

        -- Begin Return Select <- do not remove
        SELECT  [Version] 
        FROM [STC].[StockReceipt]
        WHERE [StockReceiptID] = @StockReceiptID;
    -- End Return Select <- do not remove


    END;
    ELSE
    BEGIN
        
        RAISERROR( 'NumberIsDuplicate', 16, 12);
    --RAISERROR('شماره وارد شده خارج از محدوده تعریف شده می باشد.', 16, 12)
    END;

END;
