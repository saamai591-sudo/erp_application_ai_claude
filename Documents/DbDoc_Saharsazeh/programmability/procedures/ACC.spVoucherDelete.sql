
-------------------------------------------------------------
CREATE    PROC [ACC].[spVoucherDelete]
    @VoucherID INT ,
    @Version INT
		--WITH ENCRYPTION 
AS
SET NOCOUNT ON; 
BEGIN TRY
	DECLARE @documentTypeID      SMALLINT,
			@voucherStatusID     SMALLINT,
			@OldVersion int,
			@AutoGenerated BIT,
			@Message NVARCHAR(MAX)

	SELECT @documentTypeID = DocumentTypeID,
			@voucherStatusID     = VoucherStatusID,
			@OldVersion = Version,
			@AutoGenerated = AutoGenerated
	FROM   [ACC].[Voucher]
	WHERE  [VoucherID]          = @VoucherID;
	    
	IF @Version = @OldVersion
	BEGIN
	    IF EXISTS (
	           SELECT DocumentTypeID
	           FROM   ACC.DocumentType
	           WHERE  DocumentTypeID = @documentTypeID 
	                  AND engname IN ('Opening', 'Closing')
	       )
	    BEGIN
	        RAISERROR('امکان حذف اسناد افتتاحیه و اختتامیه بصورت دستی وجود ندارد', 16, 12);
	        RETURN 
	    END;

	    IF @AutoGenerated = 1 and 
		EXISTS (
	           SELECT DocumentTypeID
	           FROM   ACC.DocumentType
	           WHERE  DocumentTypeID = @documentTypeID 
	                  AND engname not IN ('Tasir', 'ClosingProfitAndLoss')
	       )
	    BEGIN
	        RAISERROR('امکان حذف اسناد سیستمی بصورت دستی وجود ندارد', 16, 12);
	        RETURN 
	    END;
	    
	    IF  @voucherStatusID = 3 OR  @voucherStatusID = 4
	    BEGIN
	        RAISERROR('با توجه به وضعیت سند، امکان حذف اين سند وجود ندارد', 16, 12);
	        RETURN 
	    END;
	    
	     IF EXISTS (
	         SELECT 1 FROM acc.GIVoucherItem AS gi
	         WHERE gi.VoucherID=@VoucherID
	       )
	    BEGIN
	        RAISERROR('به دلیل استفاده در سند کل، نمی توان این سند را حذف کرد', 16, 12);
	        RETURN 
	    END;
	    
	     SELECT @message = STUFF(
	                (
	                SELECT DISTINCT
	                        '# برای ردیف ' + CAST(vi.VoucherItemIndex AS NVARCHAR(20)) + N' اعلامیه صادر شده است.'
	                FROM   acc.VoucherItem AS vi
	                        JOIN acc.DCNote AS d
	                            ON  d.VoucherItemID = vi.VoucherItemID
	                WHERE  vi.VoucherID = @VoucherID
	                GROUP BY
	                        vi.VoucherItemIndex FOR XML PATH('')
	            ),
	            1,
	            1,
	                ''
	            );
	     
	     IF @Message is NOT NULL
	     BEGIN
	     	RAISERROR (
		    @Message,	-- Message text.
		    16,	-- Severity,
		    12,	-- State,
		    N'Voucher',	-- First argument.
		    @VoucherID
		); -- Second argument.
		return
	     END
	    
	    DELETE 
	    FROM   [ACC].[Voucher]
	    WHERE  [VoucherID] = @VoucherID;
	END;
	ELSE
	BEGIN
		RAISERROR (
		    N'Delete_%s_%d.',	-- Message text.
		    16,	-- Severity,
		    10,	-- State,
		    N'Voucher',	-- First argument.
		    @VoucherID
		); -- Second argument.
	END;
END TRY
BEGIN CATCH
	IF CURSOR_STATUS('global', 'db_cursor') = 1
	BEGIN
	    CLOSE db_cursor; 
	    DEALLOCATE db_cursor;
	END;		
	DECLARE @ErrorMessage NVARCHAR(4000);
	DECLARE @ErrorSeverity INT;
	DECLARE @ErrorState INT;
	
	SELECT @ErrorMessage = ERROR_MESSAGE(),
	       @ErrorSeverity     = ERROR_SEVERITY(),
	       @ErrorState        = ERROR_STATE();
	
	
	RAISERROR (
	    @ErrorMessage,	-- Message text.
	    @ErrorSeverity,	-- Severity.
	    @ErrorState -- State.
	);
END CATCH;
