------------------------------------------------------------------------------------------------------------------
create   PROCEDURE [STC].spRevisionCostPreVoucherInsert
	@RevisionCostID NVARCHAR(MAX)
--WITH ENCRYPTION 
AS

	DECLARE @DocumentNumTypeId INT = (		
								SELECT  DNT.DocumentNumTypeID
								FROM   CFG.DocumentNumType DNT
								WHERE  DNT.EngName = 'RevisionCost'),
			@MDEntity INT = (select Top 1 Id from mdt.DmdEntity AS de where Name = 'RevisionCost'),					
			@HasAccountingVoucher bit,
			@MaxPrevoucherID int,
			@creatorId INT ,
			@HeaderDescription  nvarchar(max),
			@HeaderDescription2 nvarchar(max),
			@InventoryDescription  nvarchar(max),
			@InventoryDescription2  nvarchar(max),
			@ThirdPartyDescription nvarchar(max),
			@ThirdPartyDescription2 nvarchar(max),
			@Culture VARCHAR(10),
			@CultureNo TinyInt
		
		SET @creatorId = cfg.GetuserID();
		SET @Culture = CFG.GetuserCulture()
		select @CultureNo = CultureNo
		from cfg.CultureInfo
		where Culture = @Culture

		SELECT [value] ID
		INTO #DocumentIds
		FROM   cfg.R_FnCommaStr2Table(@RevisionCostID) 


		select  @HeaderDescription = Description,
				@HeaderDescription2 = Description2
		from CFG.[VoucherDescription] 
		where MDEntityID = @MDEntity and [Key] = 'Header'

		select  @InventoryDescription = Description,
				@InventoryDescription2 = Description2
		from CFG.[VoucherDescription] 
		where MDEntityID = @MDEntity and [Key] = 'Inventory'

		select  @ThirdPartyDescription = Description,
				@ThirdPartyDescription2 = Description2
		from CFG.[VoucherDescription] 
		where MDEntityID = @MDEntity and [Key] = 'ThirdParty'
			
		 --- FetchValues ---
		select @MaxPrevoucherID = max(PreVoucherID)
		from acc.PreVoucher

		SELECT isnull(@MaxPrevoucherID,0) + ROW_NUMBER() over(order by rc.RevisionCostID ) PrevoucherID,
			   rc.RevisionCostID,
			   TYPE,
			   AutoGenerated,
			   FinancialPeriodID,
			   Number,
			   rc.DATE,
			   BranchID,
			   @HeaderDescription [Description],
			   @HeaderDescription2 [Description2],
			   cast(null as varchar(max)) ErrorMessage,
			   FullDateAlternateKey,
			   PersianFullDateAlternateKey
			into #RevisionCost
		FROM   stc.RevisionCost rc
		JOIN #DocumentIds on #DocumentIds.ID = rc.RevisionCostID		
	    JOIN cfg.DimDate DD on DD.Date = rc.Date
	
		select @HasAccountingVoucher = case lower(configvalue) when 'true' then 1 else 0 end
		 from CFG.Configuration
		where ConfigKey = 'TranslationBetweenStocksHasAccountingVoucher'
	
		create table #RevisionCostItemTemp
		(
			RevisionCostItemID int,
			RevisionCostID int,
			PreVoucherId int,
			InventorySlID int,
			SlID int,
			Deference decimal(30,4),
			[Type] tinyint,
			[DocumentType] tinyint,
			dlid bigint,
			dltype int,
			StockID int,
			InventoryDescription nvarchar(max),
			InventoryDescription2 nvarchar(max),
			ThirdPartyDescription nvarchar(max),
			ThirdPartyDescription2 nvarchar(max),
			[Nature] nvarchar(10),
			StuffAccountGroup nvarchar(max),
			StockDocumentType nvarchar(max),
			dlcode nvarchar(200),
			SlBaseOnDl bit
		)

		insert into #RevisionCostItemTemp
		select 
			RCI.RevisionCostItemID,
			RC.RevisionCostID,
			RC.PrevoucherID,
			case when rc.FinancialPeriodID <> sr.FinancialPeriodID then sag.AdjustmentSLID else sagas.InventorySlID end,
			wip.SlID ,
			RCI.Deference,
			sdt.[Type],
			sdt.DocumentType,
			sr.DeliverDlID,
			d.DlTypeID,
			sr.stockid,
			@InventoryDescription,
			@InventoryDescription2,
			@ThirdPartyDescription,
			@ThirdPartyDescription2,
			'entry',
			case when @CultureNo = 1 then SAG.Title else SAG.Title2 end ,
			case when @CultureNo = 1 then sdt.Title else sdt.Title2 end ,
			d.Code,
			SlBaseOnDl
		from #RevisionCost RC 
		join STC.RevisionCostItem RCI on RC.RevisionCostID = RCI.RevisionCostID
		join STC.StockReceiptItem ARI on RCI.StockReceiptItemID = ARI.StockReceiptItemID
		join STC.StockReceipt SR on SR.StockReceiptID = ARI.StockReceiptID	
		JOIN [STC].[StockDocumentTypeBaseEntity] sdtb ON SR.StockDocumentTypeBaseEntityID = sdtb.StockDocumentTypeBaseEntityID
		join stf.Stock st on st.StockID = sr.StockID
		JOIN stc.StockDocumentType AS sdt ON sdt.StockDocumentTypeID = sdtb.StockDocumentTypeID
		join STF.StuffDetail SD on SD.StuffID = ARI.StuffID
		left join STF.StuffAccountGroup SAG on SAG.StuffAccountGroupID = SD.StuffAccountGroupID
		LEFT JOIN stf.StuffAccountGroupAccountSl sagas ON st.StockTypeID = sagas.StockTypeID 
														and sagas.StuffAccountGroupID = SAG.StuffAccountGroupID
		left join stf.StockDocumentTypeSlDl AS wip  on wip.StuffAccountGroupID = SAG.StuffAccountGroupID 
													AND wip.StockDocumentTypeID = sdt.StockDocumentTypeID 
													AND (sdt.SlBaseOnDl = 0 or wip.dlid = sr.DeliverDlID)
		left join acc.dl d on d.DLID = sr.DeliverDlID
		where (sdt.DocumentType <> 5 or @HasAccountingVoucher = 1)

		insert into #RevisionCostItemTemp
		select 
			RCI.RevisionCostItemID,
			RC.RevisionCostID,
			RC.PrevoucherID,
			sagas.InventorySlID,
			wip.SlID,
			RCI.Deference,
			sdt.[Type],
			sdt.DocumentType,
			ro.DlDeliverID,
			d.DlTypeID,
			ro.StockID,
			@InventoryDescription,
			@InventoryDescription2,
			@ThirdPartyDescription,
			@ThirdPartyDescription2,
			'entry',
			case when @CultureNo = 1 then SAG.Title else SAG.Title2 end ,
			case when @CultureNo = 1 then sdt.Title else sdt.Title2 end ,
			d.Code,
			SlBaseOnDl
		from #RevisionCost RC 
		join STC.RevisionCostItem RCI on RC.RevisionCostID = RCI.RevisionCostID
		join STC.ReturnedOutgoingItem AROI on RCI.ReturnedOutgoingItemID = AROI.ReturnedOutgoingItemID
		join STC.ReturnedOutgoing RO on RO.ReturnedOutgoingID = AROI.ReturnedOutgoingID
		JOIN [STC].[StockDocumentTypeBaseEntity] sdtb ON RO.StockDocumentTypeBaseEntityID = sdtb.StockDocumentTypeBaseEntityID
		JOIN stf.Stock st on st.StockID = ro.StockID
		JOIN stc.StockDocumentType AS sdt ON sdt.StockDocumentTypeID = sdtb.StockDocumentTypeID
		join STF.StuffDetail SD on SD.StuffID = AROI.StuffID
		left join STF.StuffAccountGroup SAG on SAG.StuffAccountGroupID = SD.StuffAccountGroupID
		LEFT JOIN stf.StuffAccountGroupAccountSl sagas ON st.StockTypeID = sagas.StockTypeID 
														and sagas.StuffAccountGroupID = SAG.StuffAccountGroupID
	    left join stf.StockDocumentTypeSlDl AS wip  on wip.StuffAccountGroupID = SAG.StuffAccountGroupID 
													AND wip.StockDocumentTypeID = sdt.StockDocumentTypeID 
													and (sdt.SlBaseOnDl = 0 or wip.dlid = ro.DlDeliverID)
		left join acc.dl d on d.DLID = ro.DlDeliverID

		insert into #RevisionCostItemTemp
		select 
			RCI.RevisionCostItemID,
			RC.RevisionCostID,
			RC.PrevoucherID,
			sagas.InventorySlID,
			wip.SlID,
			RCI.Deference,
			sdt.[Type],
			sdt.DocumentType,
			RSR.DeliverDlID,
			d.DlTypeID,
			RSR.StockID,
			@InventoryDescription,
			@InventoryDescription2,
			@ThirdPartyDescription,
			@ThirdPartyDescription2,
			'exit',
			case when @CultureNo = 1 then SAG.Title else SAG.Title2 end ,
			case when @CultureNo = 1 then sdt.Title else sdt.Title2 end ,
			d.Code,
			SlBaseOnDl
		from #RevisionCost RC 
		join STC.RevisionCostItem RCI on RC.RevisionCostID = RCI.RevisionCostID
		join STC.ReturnStockReceiptItem RARI on RCI.ReturnStockReceiptItemID = RARI.ReturnStockReceiptItemID
		join STC.ReturnStockReceipt RSR on RSR.ReturnStockReceiptID = RARI.ReturnStockReceiptID
		JOIN [STC].[StockDocumentTypeBaseEntity] sdtb ON RSR.StockDocumentTypeBaseEntityID = sdtb.StockDocumentTypeBaseEntityID
		join stf.Stock st on st.StockID = rsr.StockID
		JOIN stc.StockDocumentType AS sdt ON sdt.StockDocumentTypeID = sdtb.StockDocumentTypeID
		join STF.StuffDetail SD on SD.StuffID = RARI.StuffID
		left join STF.StuffAccountGroup SAG on SAG.StuffAccountGroupID = SD.StuffAccountGroupID
		LEFT JOIN stf.StuffAccountGroupAccountSl sagas ON st.StockTypeID = sagas.StockTypeID 
														and sagas.StuffAccountGroupID = SAG.StuffAccountGroupID
	    left join stf.StockDocumentTypeSlDl AS wip  on wip.StuffAccountGroupID = SAG.StuffAccountGroupID 
													AND wip.StockDocumentTypeID = sdt.StockDocumentTypeID 
													and (sdt.SlBaseOnDl = 0 or wip.dlid = RSR.DeliverDlID)
		left join acc.dl d on d.DLID = RSR.DeliverDlID

		insert into #RevisionCostItemTemp
		select 
			RCI.RevisionCostItemID,
			RC.RevisionCostID,
			RC.PrevoucherID,
			sagas.InventorySlID,
			wip.SlID ,
			RCI.Deference,
			sdt.[Type],
			sdt.DocumentType,
			o.DeliverDlID,
			d.DlTypeID,
			O.StockID,
			@InventoryDescription,
			@InventoryDescription2,
			@ThirdPartyDescription,
			@ThirdPartyDescription2,
			'exit',
			case when @CultureNo = 1 then SAG.Title else SAG.Title2 end ,
			case when @CultureNo = 1 then sdt.Title else sdt.Title2 end ,
			d.Code,
			SlBaseOnDl
		from #RevisionCost RC 
		join STC.RevisionCostItem RCI on RC.RevisionCostID = RCI.RevisionCostID
		join STC.OutgoingItem OI on RCI.OutgoingItemID = OI.OutgoingItemID
		join STC.Outgoing O on O.OutgoingID = OI.OutgoingID
		JOIN [STC].[StockDocumentTypeBaseEntity] sdtb 
			ON O.StockDocumentTypeBaseEntityID = sdtb.StockDocumentTypeBaseEntityID
		join stf.Stock st on st.StockID = o.StockID
		JOIN stc.StockDocumentType AS sdt ON sdt.StockDocumentTypeID = sdtb.StockDocumentTypeID
		join STF.StuffDetail SD on SD.StuffID = oi.StuffID
		left join STF.StuffAccountGroup SAG on SAG.StuffAccountGroupID = SD.StuffAccountGroupID
		LEFT JOIN stf.StuffAccountGroupAccountSl sagas ON st.StockTypeID = sagas.StockTypeID 
														and sagas.StuffAccountGroupID = SAG.StuffAccountGroupID
	    left join stf.StockDocumentTypeSlDl AS wip  on wip.StuffAccountGroupID = SAG.StuffAccountGroupID 
													AND wip.StockDocumentTypeID = sdt.StockDocumentTypeID 
													and (sdt.SlBaseOnDl = 0 or wip.dlid = o.DeliverDlID)
		left join acc.dl d on d.DLID = o.DeliverDlID


		if exists (select 1 from #RevisionCost where [type] = 3)
		and not exists (select 1 from #RevisionCostItemTemp where DocumentType <> 4)
		and @HasAccountingVoucher = 0
			update a 
			set ErrorMessage = N'AllRowsAreForTransfer'
			from #RevisionCost a


		update a 
		set ErrorMessage = isnull(ErrorMessage,'') + N'InventorySlNotSpecified'+char(10)+char(13)
		from #RevisionCost a
		join #RevisionCostItemTemp b on a.RevisionCostID = b.RevisionCostID
		where InventorySlID IS NULL
		and (@HasAccountingVoucher = 1 or DocumentType <> 4)

		update a 
		set ErrorMessage = isnull(ErrorMessage,'') + 
								case when SlBaseOnDl = 0 
								then N'StockManager.Messages.SlNotSpecifiedForTheOutgoingTypeInTheStuffGroup^' + StuffAccountGroup+',' + StockDocumentType
								else N'StockManager.Messages.SlNotSpecifiedForTheOutgoingTypeForTheDlInTheStuffGroup^' + StuffAccountGroup +','+ StockDocumentType +','+ dlcode
								end+char(10)+char(13)
		from #RevisionCost a
		join #RevisionCostItemTemp b on a.RevisionCostID = b.RevisionCostID
		where SlID IS NULL 
		and (@HasAccountingVoucher = 1 or DocumentType <> 4)

		if exists (select * from #RevisionCost where ErrorMessage is not null )
		BEGIN	
			select RevisionCostID,ErrorMessage from #RevisionCost
			RETURN;
		END

	    SET IDENTITY_INSERT [ACC].[PreVoucher] ON
	    INSERT INTO [ACC].[PreVoucher]([PreVoucherID],[BranchID],[DocumentNumtypeID],[Date],[FinancialPeriodID],[Description],[Description2],[Creator],[CreationDate],[LastEditor],[LastEditionDate],[Version])
		SELECT [PreVoucherID],BranchId,@DocumentNumTypeId,date,FinancialPeriodID,Description,Description2,@CreatorId,GETDATE(),@CreatorId,GETDATE(),0
		from #RevisionCost
		SET IDENTITY_INSERT [ACC].[PreVoucher] OFF
    

	    UPDATE a
	    SET    PreVoucherID = b.PreVoucherId
		from stc.RevisionCost a
		join #RevisionCost b on a.RevisionCostID = b.RevisionCostID

		INSERT INTO [ACC].[PreVoucherItem]
           ([PreVoucherID]
           ,[RowIndex]
           ,[SlID]
           ,[Description]
           ,[Description2]
           ,[Debit]
           ,[Credit]
           ,[CurrencyID]
           ,[CurrencyRate]
           ,[CurrencyDebit]
           ,[CurrencyCredit]
           ,[IsAutoGenerated]
           ,[Creator]
           ,[CreationDate]
           ,[LastEditor]
           ,[LastEditionDate]
           ,[Version]
		   ,BaseDocumentName
		   ,BaseDocumentID) 
        SELECT
            PreVoucherId,
            1,
            case when Deference > 0 and [nature] = 'entry'  then  InventorySlID 
				 when Deference > 0 and [nature] = 'exit'   then  SlID
				 when Deference < 0 and [nature] = 'entry'  then  SlID
				 when Deference < 0 and [nature] = 'exit'   then  InventorySlID
			end,
            case when Deference > 0 and [nature] = 'entry'  then  InventoryDescription 
				 when Deference > 0 and [nature] = 'exit'   then  ThirdPartyDescription
				 when Deference < 0 and [nature] = 'entry'  then  ThirdPartyDescription
				 when Deference < 0 and [nature] = 'exit'   then  InventoryDescription
			end,
            case when Deference > 0 and [nature] = 'entry'  then  InventoryDescription2 
				 when Deference > 0 and [nature] = 'exit'   then  ThirdPartyDescription2
				 when Deference < 0 and [nature] = 'entry'  then  ThirdPartyDescription2
				 when Deference < 0 and [nature] = 'exit'   then  InventoryDescription2
			end,
            ABS(Deference),
            0,
           -1,
            1,
            ABS(Deference),
            0,
            1,
            @CreatorId  ,
		    GETDATE(), 
		    @CreatorId  ,
			GETDATE(), 
			0,
			'RevisionCostItem',
			RevisionCostItemID
		from #RevisionCostItemTemp
		where(@HasAccountingVoucher = 1 or DocumentType <> 4)

		INSERT INTO [ACC].[PreVoucherItem]
           ([PreVoucherID]
           ,[RowIndex]
           ,[SlID]
           ,[Description]
           ,[Description2]
           ,[Debit]
           ,[Credit]
           ,[CurrencyID]
           ,[CurrencyRate]
           ,[CurrencyDebit]
           ,[CurrencyCredit]
           ,[IsAutoGenerated]
           ,[Creator]
           ,[CreationDate]
           ,[LastEditor]
           ,[LastEditionDate]
           ,[Version]
		   ,BaseDocumentName
		   ,BaseDocumentID) 
        SELECT
            PreVoucherId,
            1,
            case when Deference > 0 and [nature] = 'entry'  then  SlID 
				 when Deference > 0 and [nature] = 'exit'   then  InventorySlID
				 when Deference < 0 and [nature] = 'entry'  then  InventorySlID
				 when Deference < 0 and [nature] = 'exit'   then  SlID
			end,
            case when Deference > 0 and [nature] = 'entry'  then  ThirdPartyDescription 
				 when Deference > 0 and [nature] = 'exit'   then  InventoryDescription
				 when Deference < 0 and [nature] = 'entry'  then  InventoryDescription
				 when Deference < 0 and [nature] = 'exit'   then  ThirdPartyDescription
			end,
            case when Deference > 0 and [nature] = 'entry'  then  ThirdPartyDescription2
				 when Deference > 0 and [nature] = 'exit'   then  InventoryDescription2
				 when Deference < 0 and [nature] = 'entry'  then  InventoryDescription2
				 when Deference < 0 and [nature] = 'exit'   then  ThirdPartyDescription2
			end,
            0,
            ABS(Deference),
            -1,
            1,
            0,
            ABS(Deference),          
            1,
            @CreatorId  ,
			GETDATE(), 
			@CreatorId  ,
			GETDATE(), 
			0 ,
			'RevisionCostItem',
			RevisionCostItemID
		from #RevisionCostItemTemp	
		where(@HasAccountingVoucher = 1 or DocumentType <> 4)


		INSERT INTO Acc.PreVoucherItemAccountLevel
	        (
	        PreVoucherItemID,
	        AccountLevelID,
	        DLID,
	        [Value],
	        Creator,
	        CreationDate,
	        LastEditor,
	        LastEditionDate,
	        Version
	        )
	    SELECT  a.PreVoucherItemID,
	            b.AccountLevelID,
	            c.dlid,
	            NULL,
	            @CreatorId,
	            GETDATE(),
	            @CreatorId,
	            GETDATE(),
	               0
		 from #RevisionCostItemTemp h
		 join acc.prevoucheritem a on a.BaseDocumentName = 'RevisionCostItem' and a.BaseDocumentID = h.RevisionCostItemID
		 join acc.accountlevelsl b on a.slid = b.slid 
		 join acc.dl c on c.DLID = h.dlid and c.DlTypeID = b.DlTypeID

		INSERT INTO Acc.PreVoucherItemAccountLevel
	        (
	        PreVoucherItemID,
	        AccountLevelID,
	        DLID,
	        [Value],
	        Creator,
	        CreationDate,
	        LastEditor,
	        LastEditionDate,
	        Version
	        )
	    SELECT  a.PreVoucherItemID,
	            b.AccountLevelID,
	            c.dlid,
	            NULL,
	            @CreatorId,
	            GETDATE(),
	            @CreatorId,
	            GETDATE(),
	               0
		 from #RevisionCostItemTemp h
		 join acc.prevoucheritem a on a.BaseDocumentName = 'RevisionCostItem' and a.BaseDocumentID = h.RevisionCostItemID
		 join acc.accountlevelsl b on a.slid = b.slid 
		 join pos.Station s on s.DlID = h.DLID
		 join acc.dl c on c.DLID = s.CostCenterDlID and c.DlTypeID = b.DlTypeID



		;with temp as 
		(
			select  [pi].PreVoucherItemID,
					ROW_NUMBER() over(partition by pi.PreVoucherID order by PreVoucherItemID) RowIndex,
					REPLACE(
					REPLACE(
					REPLACE([pi].Description,
						'@@Number@@',i.Number),
						'@@Date_Gregorian@@',FullDateAlternateKey),
						'@@Date_Solar@@',PersianFullDateAlternateKey) [Description],
					REPLACE(
					REPLACE(
					REPLACE([pi].Description2,
						'@@Number@@',i.Number),
						'@@Date_Gregorian@@',FullDateAlternateKey),
						'@@Date_Solar@@',PersianFullDateAlternateKey)[Description2]
			from #RevisionCost i
			join  acc.PreVoucherItem [pi]  on [pi].PrevoucherID = i.PreVoucherID
		)

		update v
		set RowIndex = vi.RowIndex,
			Description = vi.Description,
			Description2 = vi.Description2
		from acc.PreVoucherItem v
		join temp vi  on v.PreVoucherItemID = vi.PreVoucherItemID
	

		update pi
		set [Description] =
					REPLACE(
					REPLACE(
					REPLACE([pi].Description,
						'@@Number@@',i.Number),
						'@@Date_Gregorian@@',FullDateAlternateKey),
						'@@Date_Solar@@',PersianFullDateAlternateKey) 		
		,
			[Description2] =
					REPLACE(
					REPLACE(
					REPLACE([pi].Description2,
						'@@Number@@',i.Number),
						'@@Date_Gregorian@@',FullDateAlternateKey),
						'@@Date_Solar@@',PersianFullDateAlternateKey)
		from acc.PreVoucher pi
		join #RevisionCost i on pi.PrevoucherID = i.PrevoucherID
