
CREATE     VIEW [CFG].[VwSeasonFile]
as

SELECT sf.SeasonFileID,
		sf.FinancialPeriodID,
		sf.	Season,
		sf.	AutoGenerated,
		sf.	DOCType,
		sf.	DocName	,
		sf.ID	,
		sf.StuffTitle,
		sf.	LessThanQuorum,
		sf.	Amount	,
		sf.Tax,
		sf.	Duty,
		sf.	ZipCode,
		sf.	PreNumberOfCity	,
		sf.Phone	,
		sf.Address	,
		sf.PartyFirstName	,
		sf.PartyLastName	,
		sf.EconomicCode	,
		sf.NationalID	,
		sf.HCType1Code	,
		sf.provinceCode	,
		sf.cityCode	,
		sf.Type	,
		sf.Number	,
		sf.Date	,
		sf.TradeType	,
		sf.BranchCode	,
		sf.BranchTitle	,
		sf.Version	,
		sf.Creator	,
		sf.CreationDate	,
		sf.LastEditor	,
		sf.LastEditionDate	,
		sf.Discount	,
		sf.ArzType	,
		sf.Arz_Price	,
		sf.Arz_MaliatArzeshAfzoodeh	,
		sf.Arz_AvarezArzeshAfzoodeh	,
		sf.Arz_SayerAvarez	,
		sf.Arz_TakhfifPrice	,
		sf.ArzBarabari_Price	,
		sf.ArzBarabari_MaliatArzeshAfzoodeh,
		sf.	ArzBarabari_AvarezArzeshAfzoodeh	,
		sf.ArzBarabari_SayerAvarez	,
		sf.ArzBarabari_TakhfifPrice	,
		sf.FactorNo	,
		sf.FactorDate	,
		sf.SarFaslType	,
		sf.Sarjam	,
		sf.IsHagholAmalKari	,
		sf.IsArzi	,
		sf.KalaType,
		sf.SaleTypeTitle	,
		sf.PurchaseType	,
		sf.FidaCode	,
		sf.AmountAccordingLicense	,
		sf.Currency	,
		sf.Arz_AmountAccordingLicense	,
		sf.ArzBarabari_AmountAccordingLicense	,
		sf.CotajNumber	,
		sf.CotajDate	,
		sf.EntranceCustomsCode	,
		sf.AssessmentCustomsCode	,
		sf.LetterCreditNumber	,
		sf.OpeningCreditDate	,
		sf.CountryCode	,
		sf.Nationality	,
		sf.PayDate	,
		sf.GrossPrice	,
		sf.NetPrice	,
		sf.TaxDeducted	,
		sf.ContractNumber	,
		sf.StartDate	,
		sf.FinishDate	,
		sf.CompanyID,
       CASE p.[Type]
            WHEN 0 THEN 1
            ELSE 2
       END                               K_TypeCode,
       CASE 
            WHEN pt.Code = 1 THEN 1
            ELSE 2
       END                               K_Tabeiat,
       CAST(vptt.VendorTaxType AS INT)               K_Type1Code,
       CASE 
            WHEN p.[Type] = 0 THEN p.Title
            ELSE NULL
       END                               K_Name,
       CASE 
            WHEN p.[Type] = 0 THEN p.LastName
            ELSE p.Title      end           K_LastNameSherkatName,
                 p.EconomicCode          K_EconomicNO,
                 CASE 
                      WHEN p.[Type] = 0 THEN p.IdentificationCode
                      ELSE p.NationalID
                 END                     K_NationalCode,
                 NULL                    K_TellPishCode,
                 v.Phone                 K_Tell,
                 va.ProvinceTaxCode      K_StateCode,
                 va.CityTaxCode          K_CityCode,
                 va.TitleAddress         K_Address,
                 va.ZipCode              K_PostCode
FROM   cfg.SeasonFile                 AS sf
       LEFT JOIN vnd.PurchaseInvoice  AS pi1
            ON  sf.ID = pi1.PurchaseInvoiceID
            AND sf.DocName = 'PurchaseInvoice'
       LEFT JOIN vnd.PurchaseType     AS pt
            ON  pt.PurchaseTypeID = pi1.[Type]
       LEFT JOIN cfg.Party            AS p
            ON  pt.PartyID = p.PartyID
       LEFT JOIN (
                SELECT ldi.LookupDataItemID,
                       ldi.Code
                FROM   CFG.LookupData AS ld
                       JOIN CFG.LookupDataItem AS ldi
                            ON  ldi.LookupDataID = ld.LookupDataID
                WHERE  ld.SystemName = 'nationality'
            ) n
            ON  p.Nationality = n.LookupDataItemID
       LEFT JOIN cfg.VwPartyTaxType   AS vptt
            ON  vptt.PartyID = p.PartyID
       LEFT JOIN cfg.vwphone          AS v
            ON  v.PartyID = p.PartyID
       LEFT JOIN cfg.VwAddress        AS va
            ON  p.PartyID = va.PartyID
            
    
