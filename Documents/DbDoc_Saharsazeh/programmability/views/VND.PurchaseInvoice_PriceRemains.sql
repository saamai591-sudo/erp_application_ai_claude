CREATE   VIEW [VND].PurchaseInvoice_PriceRemains
AS 

with Used
as
(
    SELECT PurchaseInvoiceItemID,
            SUM(T.Price) Price,
            SUM(t.PricedQuantity) PricedQuantity
    FROM   (
                SELECT a.PurchaseInvoiceItemID,
                        a.Share AS Price,
                        bi.MainQuantity  PricedQuantity
                FROM   [FOS].[OrderPricingItem] a  
				join fos.ClearanceItem ci on a.ClearanceItemID = ci.ClearanceItemID
				join fos.BillOfLadingItem bi on ci.BillOfLadingItemID = bi.BillOfLadingItemID
                WHERE a.PurchaseInvoiceItemID IS NOT NULL
                                      
                UNION ALL

                SELECT PurchaseInvoiceItemID,
                        pri.Price AS Price,
                        CASE 
                            WHEN pri.Price > 0 THEN pri.MainQuantity    ELSE 0
                            END PricedQuantity
                FROM   Stc.StockReceiptItem AS pri      
                WHERE pri.PurchaseInvoiceItemID IS NOT NULL
                                      
                UNION ALL

                SELECT pii.PurchaseInvoiceItemID,
                        pri.Price AS Price,
                        CASE 
                        WHEN pri.Price > 0 OR rci.RevisionCostItemID IS NOT NULL THEN pri.MainQuantity    ELSE 0
                        END PricedQuantity
                FROM   Stc.StockReceiptItem AS pri
                JOIN vnd.PurchaseInvoiceItem pii
                    ON  pii.StockReceiptItemID = pri.StockReceiptItemID
                LEFT JOIN stc.RevisionCostItem AS rci
                            ON  rci.StockReceiptItemID = pri.StockReceiptItemID
                LEFT JOIN stc.RevisionCost AS rc
                        ON  rc.RevisionCostID = rci.RevisionCostID AND rc.AutoGenerated = 1
                                                      
                UNION ALL
                                          
                SELECT PurchaseInvoiceItemID,
                        pri.BaseValue AS Price,
                        CASE WHEN pri.BaseValue > 0 THEN pri.MainQuantity ELSE 0 END PricedQuantity
                FROM   AST.AssetReceiptItem AS pri
                                          
                UNION ALL
                                          
                SELECT PurchaseInvoiceItemID,
                        pri.Price AS Price,
                        0
                FROM   AST.UtilizationCost AS pri
                ---                       
                UNION ALL
                       
                SELECT PurchaseInvoiceItemID,
                        pri.Price AS Price,
                        0
                FROM   AST.AssetReceiptUtilizationCost AS pri
                            
                UNION ALL
                                          
                SELECT PurchaseInvoiceItemID,
                        pri.Price AS Price,
                        0
                FROM   STC.ReceiptCost AS pri
                                          
                UNION ALL
                                          
                SELECT PurchaseInvoiceItemID,
                        pri.Price AS Price,
                        0
                FROM   AST.Insurance AS pri
                                          
                UNION ALL
                                          
                SELECT PurchaseInvoiceItemID,
                        pri.Price AS Price,
                        0
                FROM   AST.RepairServiceCost AS pri
                                          
                UNION ALL
                                          
                SELECT PurchaseInvoiceItemID,
                        Amount Price,
                        0
                FROM   FOS.CostOfOrderItem
                WHERE  PurchaseInvoiceItemID IS NOT NULL 
                                          
                UNION ALL
                                          
                SELECT PurchaseInvoiceItemID,
                        Price,
                        0
                FROM   AST.RepairStuffCost
                WHERE  PurchaseInvoiceItemID IS NOT NULL
                                          
                UNION ALL
                                          
                SELECT BaseDocumentID,
                        Amount,
                        0
                FROM   AST.AdjustmentItem
                WHERE  BaseDocumentType = 2

            )T
    GROUP BY
            PurchaseInvoiceItemID
)                 

SELECT T.PurchaseInvoiceItemID,
       CASE 
            WHEN isnull(ExchangeManner,0) = 1 THEN T.price
            ELSE T.Price - ISNULL(AllocationSharingAmount, 0)
       END     Price,
       CASE 
            WHEN si.PurchaseInvoiceItemID IS NOT NULL 
                 OR
                 bol.PurchaseInvoiceItemID IS NOT NULL THEN 
					CASE 
                        WHEN isnull(ExchangeManner,0) = 1 THEN 
                            T.price
                        ELSE T.Price - ISNULL(AllocationSharingAmount, 0)
                    END
            ELSE T.DoPrice
       END     DoPrice,
       CASE 
            WHEN si.PurchaseInvoiceItemID IS NOT NULL 
                 OR
                 bol.PurchaseInvoiceItemID IS NOT NULL THEN 0
            ELSE CASE 
                      WHEN isnull(ExchangeManner,0) = 1 THEN T.price
                      ELSE T.Price - ISNULL(AllocationSharingAmount, 0)
                 END 
                 - T.DoPrice
       END     Non,
       T.PricedQuantity, T.NonPricedQuantity
FROM   
(
        SELECT item.PurchaseInvoiceItemID,
                CASE 
                    WHEN Currency.IsBaseCurrencyBasis = 0 THEN ROUND(
                            item.CostOfBuying * H.CurrencyRate / Currency.ExchangeUnit,
                            [CFG].[GetBaseCurrencyPrecision]()
                        )
                    WHEN Currency.IsBaseCurrencyBasis = 1 THEN ROUND(
                            item.CostOfBuying * Currency.ExchangeUnit / H.CurrencyRate,
                            [CFG].[GetBaseCurrencyPrecision]()
                        )
                END                       Price,
                ISNULL(USED.Price, 0)  AS DoPrice,
                ISNULL(USED.PricedQuantity,0) PricedQuantity,
                item.MainQuantity - ISNULL(USED.PricedQuantity,0) NonPricedQuantity,
                H.ExchangeManner,
                item.AllocationSharingAmount
        FROM   VND.PurchaseInvoiceItem AS item
        INNER JOIN vnd.PurchaseInvoice H
            ON  H.PurchaseInvoiceID = item.PurchaseInvoiceID
		INNER JOIN vnd.PurchaseType pt
			ON pt.PurchaseTypeID = h.Type
        INNER JOIN cfg.Currency
            ON  Currency.CurrencyID = H.CurrencyID
        LEFT JOIN Used
            ON  item.PurchaseInvoiceItemID = USED.PurchaseInvoiceItemID
		LEFT JOIN VND.ConfirmPurchaseInvoice cpi
			ON cpi.PurchaseInvoiceID = h.PurchaseInvoiceID
		where (pt.HasConfirmStatement = 0 or h.CurrencyID = -1 or cpi.ConfirmPurchaseInvoiceID is not null)
) T
LEFT JOIN FOS.ShippingInsurance si
    ON  T.PurchaseInvoiceItemID = si.PurchaseInvoiceItemID
LEFT JOIN FOS.BillOfLading bol
    ON  T.PurchaseInvoiceItemID = bol.PurchaseInvoiceItemID
      
